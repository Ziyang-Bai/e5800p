def _tables(c):
    if len(c.data) & 1:
        c.db(0)
    patterns = {}
    rows = []
    for index, (kind, _, name) in enumerate(ENTRIES):
        if kind == FIXED:
            suffix = name.partition(' ')[2]
            pattern = tuple(suffix.encode('ascii'))
        else:
            pattern = _PATTERNS[kind]
        patterns.setdefault(pattern, f'pattern_{len(patterns)}')
        rows.append((NAME_ADDRESSES[name] & 65535, patterns[pattern],
                     (INSTRUCTION_RECORDS_ADDRESS + index * 16) & 65535))
    macro = (_ER, 44, _U16)
    patterns.setdefault(macro, f'pattern_{len(patterns)}')
