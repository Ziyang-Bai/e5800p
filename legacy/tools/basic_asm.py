    c.call('even_address')
    c.call('line_tail')
    c.jump('header_done')
    c.label('skip_header')
    c.call('discard_line')
    c.label('header_done')
    c.call('peek')
    c.cmp(0, 13)
    c.cond('ne', 'no_endasm')
    c.call('get')
    c.slot(0, 10, word=True)
    c.slot(0, 14, True, True)
    c.slot(0, 12, True, True)
    c.slot(0, 7)
    c.cmp(0, 0)
    c.cond('ne', 'skip_loop')
    c.value(25, 0)
    c.call('reset')
    c.label('label_pass')
    c.call('next')
    c.cmp(1, 3)
    c.cond('eq', 'add_label')
    c.cmp(1, 1)
    c.cond('eq', 'labels_done')
    c.cmp(1, 0)
    c.cond('ne', 'failure')
    c.jump('label_pass')
    c.label('add_label')
    c.slot(0, 125)
    c.cmp(0, 0)
    c.cond('ne', 'address_range')
    c.call('find_label')
    c.mov_er(2, 0)
    c.raw('27 f0')
    c.cond('ne', 'dup_label')
    c.raw('1a a0')
    c.mov_er(2, STACK_LOW + 12 + 192)
