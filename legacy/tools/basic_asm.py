"""Bounded, streaming BASIC ASM compiler for the nX-U8.

Sourceinfo: begin/end/ASM full LE32 addresses; end includes the source NUL.
Output: next/error/result LE32, reason/reserved LE16. Success returns zero;
syntax returns 2, stack returns 6, programming failure returns 0x100. The two
entries preserve XR4 and R8..R15. No source or machine-code heap is used.
CALL_SYS requires a literal CPU address; block labels are segment-local.
Output stays within the selected Flash segment and the uint16 writer count.
The 128-byte frame uses byte 124 for the segment and 125 for PC wrap.
"""

