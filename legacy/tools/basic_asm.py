    c.label('entry')
    c.pair(8, 0)
    c.pair(12, 2)
    c.raw('1a a0')
    c.mov_er(2, STACK_LOW + ASM_FRAME_SIZE + 192)
    c.raw('27 f0')
    c.cond('lt', 'entry_memory')
    c.raw('80 e1 1a ae')
    c.slot(12, 0, True, True)
    c.slot(7, 7, True)
    c.pair(10, 14)
