"""Shared machine-code encoder and bounded instruction-length reader.

ENCODE: ER0=near PC, ER2=bank-8 record offset, ER4=near nibble[8],
ER6=near output[8]. ER0=status (0 ok, 1 operand, 2 odd target, 3 segment end,
4 branch range), R2=length. XR4 and R8..R15 are preserved.
LENGTH: ER2=S1 PC -> ER0=length/FFFF, preserving ER2/XR4/R8..R15.
SOURCE_LENGTH: ER0=source offset, R2=data bank, ER4=exclusive stop;
returns ER0=length/FFFF, R2=prefix bytes (0/2), R3=SUB macro (0/1).
The private reader preserves XR4/R8..R15; it never reads past stop.
"""

from u8_emit import Code
from flash_layout import (CODEC_ENCODE_ADDRESS, CODEC_LENGTH_ADDRESS,
                          CODEC_SOURCE_LENGTH_ADDRESS, INSTRUCTION_RECORDS_ADDRESS)
from instruction_table import (IMM, RR, EE, EI7, SHIFT, ER_R, ONE_R, ONE_ER,
                               R_ABS, R_IND, R_DISP, ER_ABS, ER_IND, ER_DISP,
                               BR, FAR, FAR_SYS, TB, SP_IMM, FIXED, EXTBW,
                               ER_SP, SP_ER, SUB_IMM, ONE_XR, ONE_QR, ENTRIES)

LENGTH_ADDRESS = CODEC_LENGTH_ADDRESS
ENCODE_ADDRESS = CODEC_ENCODE_ADDRESS
SOURCE_LENGTH_ADDRESS = CODEC_SOURCE_LENGTH_ADDRESS

_DESC, _ADDR, _POS = 34, 36, 38
_KIND, _BASE, _A, _B, _HIGH, _DISP = 41, 42, 45, 46, 47, 48
_NIB = 64


class _Codec(Code):
    def __init__(self, address):
        super().__init__(address)
        self.seq = 0

    def op(self, *values):
        self.db(*values)

    def copy(self, dst, src):
        self.op(src << 4, 0x80 | dst)

    def pair(self, dst, src):
        self.op((src << 4) | 5, 0xf0 | dst)

    def add(self, reg, value):
        self.op(value & 255, 0x10 | reg)

    def and_(self, reg, value):
        self.op(value, 0x20 | reg)

    def or_(self, reg, value):
        self.op(value, 0x30 | reg)
    def shift(self, reg, count, right=False):
        self.op((count << 4) | (0x0c if right else 0x0a), 0x90 | reg)

    def cmp(self, reg, value):
        self.op(value, 0x70 | reg)

    def ram(self, reg, ptr, store=False, segment=None):
        if segment is not None:
            self.op(segment, 0xe3)
        self.op(ptr | int(store), 0x90 | reg)

    def add_er(self, register, value):
        if value > 63:
            self.op(0xa0, 0xe0 | register)
            value -= 32
        self.op(0x80 | value, 0xe0 | register)

    def slot(self, reg, slot, store=False):
        self.pair(2, 14)
        self.add_er(2, slot)
        self.ram(reg, 0x20, store)

    def word_slot(self, register, slot, store=False):
        self.pair(2, 14)
        self.add_er(2, slot)
        if register == 2:
            self.ram(0, 0x20)
            self.add_er(2, 1)
            self.ram(1, 0x20)
            self.pair(2, 0)
        else:
            self.ram(register, 0x20, store)
            self.add_er(2, 1)
            self.ram(register + 1, 0x20, store)

    def goto_if(self, condition, target):
        self.seq += 1
        skip = f"skip_{self.seq}"
        opposite = {"eq": "ne", "ne": "eq", "lt": "ge", "ge": "lt"}[condition]
        self.branch(opposite, skip)
        self.jump(target)
        self.label(skip)

    def return_(self):
        self.raw("1f fe")


def _encoder():
    c = _Codec(ENCODE_ADDRESS)
    c.raw("ce f8 6e f4 7e f8")
    c.pair(8, 0)
    c.pair(10, 2)
    c.pair(12, 4)
    c.raw("e0 e1 e0 e1 e0 e1 1a ae")
    c.word_slot(6, _DESC, True)
    c.word_slot(8, _ADDR, True)
    c.mov(0, 0)
    c.slot(0, _POS, True)
    c.copy(0, 8)
    c.and_(0, 1)
    c.goto_if("ne", "enc_odd")
    c.pair(0, 10)
    c.mov_er(2, INSTRUCTION_RECORDS_ADDRESS & 0xffff)
    c.raw("27 f0")
    c.goto_if("lt", "enc_operand")
    c.mov_er(2, (INSTRUCTION_RECORDS_ADDRESS & 0xffff) + 16 * len(ENTRIES))
    c.raw("27 f0")
    c.goto_if("ge", "enc_operand")
    c.add(0, -(INSTRUCTION_RECORDS_ADDRESS & 15))
    c.and_(0, 15)
    c.goto_if("ne", "enc_operand")
    c.ram(0, 0xa0, segment=8)
    c.slot(0, _KIND, True)
    c.add_er(10, 2)
    c.ram(0, 0xa0, segment=8)
    c.slot(0, _BASE, True)
    c.add_er(10, 1)
    c.ram(0, 0xa0, segment=8)
    c.slot(0, _HIGH, True)
    c.add_er(10, 1)
    c.pair(8, 14)
    c.add_er(8, _NIB)
    # Copy and validate each active field. The eighth nibble is SEG/FF.
    c.mov(6, 0)
    c.label("enc_fields")
    c.ram(0, 0xc0, segment=0)
    c.ram(0, 0x80, True, segment=0)
    c.cmp(6, 7)
    c.goto_if("eq", "enc_fields_done")
    c.ram(7, 0xa0, segment=8)
    c.cmp(7, 0)
    c.goto_if("eq", "enc_field_next")
    c.cmp(0, 16)
    c.goto_if("ge", "enc_operand")
    c.cmp(7, 2)
    c.goto_if("ne", "enc_not_er")
    c.and_(0, 1)
    c.goto_if("ne", "enc_operand")
    c.label("enc_not_er")
    c.cmp(7, 3)
    c.goto_if("ne", "enc_not_bit")
    c.cmp(0, 8)
    c.goto_if("ge", "enc_operand")
    c.label("enc_not_bit")
    c.cmp(7, 5)
    c.goto_if("ne", "enc_not_xr")
    c.and_(0, 3)
    c.goto_if("ne", "enc_operand")
    c.label("enc_not_xr")
    c.cmp(7, 6)
    c.goto_if("ne", "enc_field_next")
    c.and_(0, 7)
    c.goto_if("ne", "enc_operand")
    c.label("enc_field_next")
    c.add_er(8, 1)
    c.add_er(10, 1)
    c.add_er(12, 1)
    c.add(6, 1)
    c.jump("enc_fields")
    c.label("enc_fields_done")
    c.slot(0, _NIB)
    c.slot(0, _A, True)
    c.slot(0, _NIB + 1)
    c.slot(0, _B, True)
    c.slot(0, _KIND)
    c.cmp(0, EI7)
    c.goto_if("ne", "enc_target")
    c.slot(0, _NIB + 1)
    c.cmp(0, 8)
    c.goto_if("ge", "enc_operand")
    c.label("enc_target")
    c.slot(0, _KIND)
    c.cmp(0, BR)
    c.goto_if("ne", "enc_far_check")
    c.call("branch_target")
    c.cmp(0, 0)
    c.goto_if("ne", "enc_failed")
    c.jump("enc_assemble")
    c.label("enc_far_check")
    c.cmp(0, FAR)
    c.goto_if("ne", "enc_sys_check")
    c.mov(0, 0)
    c.call("pack")
    c.copy(9, 0)
    c.mov(0, 2)
    c.call("pack")
    c.copy(8, 0)
    c.and_(0, 1)
    c.goto_if("ne", "enc_odd")
    c.jump("enc_assemble")
    c.label("enc_sys_check")
    c.cmp(0, FAR_SYS)
    c.goto_if("ne", "enc_assemble")
    c.slot(0, _NIB + 4)
    c.and_(0, 1)
    c.goto_if("ne", "enc_odd")
    c.label("enc_assemble")
    c.call("assemble")
    c.mov(9, 2)
    c.slot(0, _KIND)
    c.cmp(0, SUB_IMM)
    c.goto_if("ne", "enc_size_normal")
    c.mov(9, 8)
    c.jump("enc_segment")
    c.label("enc_size_normal")
    for kind in (R_ABS, R_DISP, ER_ABS, ER_DISP, FAR, FAR_SYS):
        c.cmp(0, kind)
        c.goto_if("eq", "enc_size_four")
    c.jump("enc_segment")
    c.label("enc_size_four")
    c.mov(9, 4)
    c.label("enc_segment")
    c.slot(0, _KIND)
    c.cmp(0, R_ABS)
    c.goto_if("lt", "enc_copy")
    c.cmp(0, BR)
    c.goto_if("ge", "enc_copy")
    c.slot(0, _NIB + 7)
    c.cmp(0, 255)
    c.goto_if("eq", "enc_copy")
    c.cmp(0, 16)
    c.goto_if("ge", "enc_operand")
    # Shift the complete 2/4-byte memory instruction right by one word.
    for dst in (57, 56, 55, 54):
        c.slot(0, dst - 2)
        c.slot(0, dst, True)
    c.slot(0, _NIB + 7)
    c.slot(0, 52, True)
    c.mov(0, 0xe3)
    c.slot(0, 53, True)
    c.add(9, 2)
    c.label("enc_copy")
    c.word_slot(0, _ADDR)
    c.copy(2, 9)
    c.mov(3, 0)
    c.raw("26 f0")
    c.branch("ge", "enc_copy_ready")
    c.pair(0, 0)
    c.goto_if("ne", "enc_outside")
    c.label("enc_copy_ready")
    c.word_slot(10, _DESC)
    c.copy(5, 9)
    c.pair(8, 14)
    c.add_er(8, 52)
    c.copy(6, 5)
    c.label("enc_copy_byte")
    c.ram(0, 0x80, segment=0)
    c.ram(0, 0xa0, True, segment=0)
    c.add_er(8, 1)
    c.add_er(10, 1)
    c.add(6, -1)
    c.cmp(6, 0)
    c.goto_if("ne", "enc_copy_byte")
    c.copy(2, 5)
    c.mov_er(0, 0)
    c.jump("enc_exit")
    for label, status in (("enc_operand", 1), ("enc_odd", 2), ("enc_outside", 3)):
        c.label(label)
        c.mov(0, status)
        c.jump("enc_failed")
    c.label("enc_failed")
    c.mov(1, 0)
    c.mov(2, 0)
    c.label("enc_exit")
    c.raw("20 e1 20 e1 20 e1 3e f8 2e f4 8e f2")
    _encode(c)
    return c


def _encode(c):
    c.label("pack")
    c.copy(6, 0)
    c.mov(7, 0)
    c.pair(2, 14)
    c.add_er(2, _NIB)
    c.op(0x66, 0xf2)
    c.ram(8, 0x20)
    c.shift(8, 4)
    c.add(6, 1)
    c.pair(2, 14)
    c.add_er(2, _NIB)
    c.op(0x66, 0xf2)
    c.ram(0, 0x20)
    c.op(0x83, 0x80)  # OR R0,R8
    c.return_()

    c.label("branch_target")
    c.raw("ce f8")
    c.mov(0, 0)
    c.call("pack")
    c.slot(0, _DISP, True)
    c.mov(0, 2)
    c.call("pack")
    c.copy(8, 0)
    c.slot(9, _DISP)
    c.copy(0, 8)
    c.and_(0, 1)
    c.goto_if("ne", "branch_odd")
    c.word_slot(0, _ADDR)
    c.slot(6, _POS)
    c.op(0x61, 0x80)  # ADD R0,R6 includes the virtual page offset.
    c.op(0x00, 0x61)  # ADDC R1,#0
    c.add_er(0, 2)
    c.raw("08 88 19 89")  # SUB R8,R0; SUBC R9,R1
    c.cmp(9, 0)
    c.goto_if("eq", "branch_forward")
    c.cmp(9, 255)
    c.goto_if("ne", "branch_range")
    c.shift(8, 1, right=True)
    c.or_(8, 0x80)
    c.jump("branch_ready")
    c.label("branch_forward")
    c.cmp(8, 255)
    c.goto_if("eq", "branch_range")
    c.shift(8, 1, right=True)
    c.label("branch_ready")
    c.slot(8, _DISP, True)
    c.mov(0, 0)
    c.raw("8e f2")
    c.label("branch_odd")
    c.mov(0, 2)
    c.jump("branch_fail")
    c.label("branch_range")
    c.mov(0, 4)
    c.label("branch_fail")
    c.slot(0, _DISP, True)
    c.raw("8e f2")
    c.label("assemble")
    c.raw("ce f8")
    c.slot(0, _BASE)
    c.slot(0, 52, True)
    c.slot(0, _HIGH)
    c.slot(0, 53, True)
    c.slot(6, _KIND)
    for kind, label in (
        (IMM, "asm_imm"), (SUB_IMM, "asm_sub_imm"),
        (RR, "asm_pair"), (EE, "asm_pair"),
        (EI7, "asm_ei7"), (SHIFT, "asm_shift"), (ER_R, "asm_er_r"),
        (ONE_R, "asm_one"), (ONE_ER, "asm_one"),
        (ONE_XR, "asm_one"), (ONE_QR, "asm_one"),
        (R_ABS, "asm_abs"), (ER_ABS, "asm_abs"),
        (R_IND, "asm_pair"), (ER_IND, "asm_pair"),
        (R_DISP, "asm_disp"), (ER_DISP, "asm_disp"),
        (BR, "asm_branch"), (FAR, "asm_far"), (FAR_SYS, "asm_sys"),
        (TB, "asm_shift"), (SP_IMM, "asm_sp_imm"),
        (EXTBW, "asm_extbw"), (ER_SP, "asm_one"), (SP_ER, "asm_sp_er"),
    ):
        c.cmp(6, kind)
        c.goto_if("eq", label)
    c.jump("asm_done")

    c.label("asm_imm")
    c.slot(7, _A)
    c.slot(0, 53)
    c.op(0x73, 0x80)  # OR R0,R7
    c.slot(0, 53, True)
    c.mov(0, 1)
    c.jump("asm_pack_imm")
    c.label("asm_sp_imm")
    c.mov(0, 0)
    c.label("asm_pack_imm")
    c.call("pack")
    c.slot(0, 52, True)
    c.jump("asm_done")

    c.label("asm_sub_imm")
    c.mov(0, 1)
    c.call("pack")
    c.slot(0, 54, True)
    c.slot(7, _A)
    c.cmp(7, 0)
    c.goto_if("ne", "sub_tmp_zero")
    c.mov(6, 1)
    c.jump("sub_tmp_ready")
    c.label("sub_tmp_zero")
    c.mov(6, 0)
    c.label("sub_tmp_ready")
    c.mov(0, 0x4e)  # PUSH scratch
    c.slot(0, 52, True)
    c.copy(0, 6)
    c.or_(0, 0xf0)
    c.slot(0, 53, True)
    c.copy(0, 6)     # MOV scratch,#immediate
    c.slot(0, 55, True)
    c.copy(0, 6)
    c.shift(0, 4)
    c.or_(0, 8)      # SUB destination,scratch (writeback)
    c.slot(0, 56, True)
    c.slot(0, _A)
    c.or_(0, 0x80)
    c.slot(0, 57, True)
    c.mov(0, 0x0e)  # POP scratch; flags from SUB survive
    c.slot(0, 58, True)
    c.copy(0, 6)
    c.or_(0, 0xf0)
    c.slot(0, 59, True)
    c.jump("asm_done")

    c.label("asm_pair")
    c.call("asm_dest")
    c.slot(7, _BASE)
    c.slot(0, _B)
    c.shift(0, 4)
    c.op(0x03, 0x87)  # OR R7,R0
    c.slot(7, 52, True)
    c.jump("asm_done")

    c.label("asm_ei7")
    c.call("asm_dest")
    c.mov(0, 1)
    c.call("pack")
    c.or_(0, 0x80)
    c.slot(0, 52, True)
    c.jump("asm_done")

    c.label("asm_shift")
    c.call("asm_dest")
    c.slot(7, _BASE)
    c.slot(0, _B)
    c.shift(0, 4)
    c.op(0x03, 0x87)
    c.slot(7, 52, True)
    c.jump("asm_done")

    c.label("asm_er_r")
    c.call("asm_dest")
    c.slot(7, _BASE)
    c.slot(0, _B)
    c.shift(0, 4)
    c.op(0x03, 0x87)
    c.slot(7, 52, True)
    c.jump("asm_done")

    c.label("asm_one")
    c.call("asm_dest")
    c.jump("asm_done")

    c.label("asm_sp_er")
    c.slot(7, _BASE)
    c.slot(0, _A)
    c.shift(0, 4)
    c.op(0x03, 0x87)
    c.slot(7, 52, True)
    c.jump("asm_done")

    c.label("asm_extbw")
    c.call("asm_dest")
    c.jump("asm_sp_er")

    c.label("asm_abs")
    c.call("asm_dest")
    c.mov(0, 1)
    c.jump("asm_word")
    c.label("asm_disp")
    c.call("asm_dest")
    c.slot(7, _BASE)
    c.slot(0, _B)
    c.shift(0, 4)
    c.op(0x03, 0x87)
    c.slot(7, 52, True)
    c.mov(0, 2)
    c.label("asm_word")
    c.copy(9, 0)
    c.call("pack")
    c.slot(0, 55, True)  # immediate word high byte
    c.copy(0, 9)
    c.add(0, 2)
    c.call("pack")
    c.slot(0, 54, True)  # immediate word low byte
    c.jump("asm_done")

    c.label("asm_branch")
    c.slot(0, _DISP)
    c.slot(0, 52, True)  # signed 8-bit displacement in words from PC+2
    c.jump("asm_done")

    c.label("asm_far")
    c.mov(0, 0)
    c.jump("asm_word")
    c.label("asm_sys")
    c.slot(0, _NIB)
    c.or_(0, 0xf0)
    c.slot(0, 53, True)
    c.mov(0, 1)
    c.jump("asm_word")

    c.label("asm_dest")
    c.slot(7, _A)
    c.slot(0, _HIGH)
    c.op(0x73, 0x80)
    c.slot(0, 53, True)
    c.return_()
    c.label("asm_done")
    c.raw("8e f2")



def _reader():
    c = _Codec(LENGTH_ADDRESS)
    c.jump("s1_length")
    c.jump("source_length")
    c.label("s1_length")
    c.raw("ce f8 5e f2 6e f4")
    c.pair(0, 2)
    c.and_(0, 1)
    c.goto_if("ne", "s1_bad")
    c.pair(0, 2)
    c.mov_er(4, 0x4000)
    c.raw("47 f0")
    c.goto_if("lt", "s1_bad")
    c.mov_er(4, 0x5ff0)
    c.mov(2, 8)
    c.call("source_length")
    c.jump("s1_exit")
    c.label("s1_bad")
    c.mov_er(0, 0xffff)
    c.label("s1_exit")
    c.raw("2e f4 1e f2 8e f2")
    c.label("source_length")
    c.raw("ce f8 6e f4 7e f8")
    c.pair(8, 0)
    c.pair(10, 4)
    c.copy(12, 2)
    c.mov(13, 0)
    c.mov(14, 0)
    c.mov(7, 2)
    c.call("fits")
    c.cmp(0, 0)
    c.goto_if("ne", "source_bad")
    c.mov(6, 0)
    c.call("read")
    c.copy(4, 0)
    c.mov(6, 1)
    c.call("read")
    c.copy(5, 0)
    # Immediate, register and reuse-DSR forms (manual 1-18).
    c.cmp(5, 0xe3)
    c.goto_if("eq", "prefixed")
    c.cmp(5, 0xfe)
    c.branch("ne", "prefix_register")
    c.cmp(4, 0x9f)
    c.goto_if("eq", "prefixed")
    c.label("prefix_register")
    c.cmp(5, 0x90)
    c.branch("ne", "unprefixed")
    c.copy(0, 4)
    c.and_(0, 0x0f)
    c.cmp(0, 0x0f)
    c.goto_if("eq", "prefixed")
    c.label("unprefixed")
    c.call("word_length")
    # PUSH scratch; MOV scratch,#imm; SUB destination,scratch; POP scratch.
    c.cmp(4, 0x4e)
    c.goto_if("ne", "source_span")
    c.copy(0, 5)
    c.and_(0, 0xfe)
    c.cmp(0, 0xf0)
    c.goto_if("ne", "source_span")
    c.mov(7, 8)
    c.call("fits")
    c.cmp(0, 0)
    c.goto_if("ne", "source_two")
    c.copy(15, 5)
    c.and_(15, 1)
    c.mov(6, 3)
    c.call("read")
    c.op(0xf7, 0x80)
    c.goto_if("ne", "source_two")
    c.mov(6, 4)
    c.call("read")
    c.copy(6, 15)
    c.shift(6, 4)
    c.or_(6, 8)
    c.op(0x67, 0x80)
    c.goto_if("ne", "source_two")
    c.mov(6, 5)
    c.call("read")
    c.copy(6, 0)
    c.and_(6, 0xf0)
    c.cmp(6, 0x80)
    c.goto_if("ne", "source_two")
    c.and_(0, 15)
    c.cmp(0, 0)
    c.branch("eq", "macro_r0")
    c.cmp(15, 0)
    c.goto_if("ne", "source_two")
    c.jump("macro_pop")
    c.label("macro_r0")
    c.cmp(15, 1)
    c.goto_if("ne", "source_two")
    c.label("macro_pop")
    c.mov(6, 6)
    c.call("read")
    c.cmp(0, 0x0e)
    c.goto_if("ne", "source_two")
    c.mov(6, 7)
    c.call("read")
    c.or_(15, 0xf0)
    c.op(0xf7, 0x80)
    c.goto_if("ne", "source_two")
    c.mov(14, 1)
    c.mov(7, 8)
    c.jump("source_span")
    c.label("source_two")
    c.mov(7, 2)
    c.jump("source_span")
    c.label("prefixed")
    c.mov(7, 4)
    c.call("fits")
    c.cmp(0, 0)
    c.goto_if("ne", "source_bad")
    c.mov(6, 2)
    c.call("read")
    c.copy(4, 0)
    c.mov(6, 3)
    c.call("read")
    c.copy(5, 0)
    # DSR prefixes must be followed by an L/ST, never another prefix.
    c.copy(0, 5)
    c.and_(0, 0xf0)
    c.cmp(0, 0x90)
    c.branch("eq", "prefix_memory")
    c.cmp(0, 0xa0)
    c.goto_if("ne", "source_bad")
    c.copy(0, 4)
    c.and_(0, 0x0e)
    c.cmp(0, 8)
    c.goto_if("ne", "source_bad")
    c.jump("prefix_length")
    c.label("prefix_memory")
