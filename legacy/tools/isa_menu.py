"""On-calculator native nX-U8 instruction picker for a staged flash page.

ER0 points at 16 staged RAM bytes; ER2 holds the S1 page base, R5 selects
the byte, and ER6 points at the caller's ten-byte descriptor (old length,
new length, eight new bytes). On cancel ER0 is -1; on success it is zero
and only the descriptor has changed. The sector writer performs any
length-changing insertion and branch relocation.

FUNCTION uses native 5x7 numbered menus: 1..6 opens a category, 1..4
chooses an instruction on the current page, and LEFT/RIGHT changes pages.
"""

from u8_emit import Code
from address_input import HEX_KEY_ADDRESS
from flash_layout import ISA_ENTRY_ADDRESS, INSTRUCTION_RECORDS_ADDRESS
from instruction_table import (R_ABS, ER_ABS, BR, FAR, FAR_SYS, EI7,
                               RECORD_SEGMENT, COUNTS_ADDRESS, STARTS_ADDRESS)
from instruction_codec import ENCODE_ADDRESS, LENGTH_ADDRESS, SOURCE_LENGTH_ADDRESS
from ui_text import UI_TEXT_ADDRESS, DATA_SPANS



# Frame slots. Text at the front of the frame is also the ROM LCD line buffer.
_PAGE, _DESC, _ADDR = 32, 34, 36
_POS, _GROUP, _ITEM, _KIND, _BASE = 38, 39, 40, 41, 42
_OLD, _NEW, _A, _B, _HIGH, _DISP, _FIELD, _COUNT = 43, 44, 45, 46, 47, 48, 49, 50
_FIRST = 60
_REC, _NAME = 78, 80
_NIB = 64


class _Menu(Code):
    def __init__(self):
        super().__init__(ISA_ENTRY_ADDRESS)
        self.seq = 0
        self.refs = []

    def ref(self, register, label):
        self.refs.append((len(self.data), "mov", label))
        self.op(0, register, 0, register + 1)

    def build(self):
        data = bytearray(super().build())
        for pos, kind, label in self.refs:
            address = self.labels[label] & 0xffff
            if kind == "mov":
                data[pos], data[pos + 2] = address & 255, address >> 8
            else:
                data[pos:pos + 2] = address.to_bytes(2, "little")
        return bytes(data)

    def op(self, *values):
        self.db(*values)

    def copy(self, dst, src):
        self.op(src << 4, 0x80 | dst)

    def pair(self, dst, src):
        self.op((src << 4) | 5, 0xf0 | dst)

    def add(self, reg, value):
        self.op(value & 255, 0x10 | reg)

    def and_(self, reg, value):
        self.op(value, 0x20 | reg)

    def or_(self, reg, value):
        self.op(value, 0x30 | reg)
    def shift(self, reg, count, right=False):
        self.op((count << 4) | (0x0c if right else 0x0a), 0x90 | reg)

    def cmp(self, reg, value):
        self.op(value, 0x70 | reg)

    def ram(self, reg, ptr, store=False, segment=None):
        if segment is not None:
            self.op(segment, 0xe3)
        self.op(ptr | int(store), 0x90 | reg)

    def add_er(self, register, value):
        if value > 63:
            self.op(0xa0, 0xe0 | register)
            value -= 32
        self.op(0x80 | value, 0xe0 | register)

    def slot(self, reg, slot, store=False):
        self.pair(2, 14)
        self.add_er(2, slot)
        self.ram(reg, 0x20, store)

    def word_slot(self, register, slot, store=False):
        self.pair(2, 14)
        self.add_er(2, slot)
        if register == 2:
            self.ram(0, 0x20)
            self.add_er(2, 1)
            self.ram(1, 0x20)
            self.pair(2, 0)
        else:
            self.ram(register, 0x20, store)
            self.add_er(2, 1)
            self.ram(register + 1, 0x20, store)

    def goto_if(self, condition, target):
        self.seq += 1
        skip = f"skip_{self.seq}"
        opposite = {"eq": "ne", "ne": "eq", "lt": "ge", "ge": "lt"}[condition]
        self.branch(opposite, skip)
        self.jump(target)
        self.label(skip)

    def text(self, value):
        self.data.extend(value.encode("ascii") + b"\0")

    def return_(self):
        self.raw("1f fe")


def _build():
    c = _Menu()
    c.label("entry")
    c.raw("ce f8 6e f4 5e f6 7e f8 5e fc 5e fe")  # LR, XR4, ER6, QR8, ER12, ER14
    c.pair(8, 6)
    c.pair(10, 0)
    c.copy(7, 5)
    c.pair(12, 2)
    c.raw("e0 e1 e0 e1 e0 e1 1a ae")  # 96-byte stack frame, ER14=SP
    c.word_slot(10, _PAGE, True)
    c.word_slot(8, _DESC, True)
    c.word_slot(12, _ADDR, True)
    c.slot(7, _POS, True)
    for slot in (_FIELD, _A, _B, *range(_NIB, _NIB + 6)):
        c.mov(0, 0)
        c.slot(0, slot, True)
    # Cross-page instructions are described, not written, by this routine.
    c.slot(0, _POS)
    c.cmp(0, 16)
    c.goto_if("ge", "cancel")
    c.slot(0, _POS)
    c.and_(0, 1)
    c.goto_if("ne", "cancel")  # native opcodes start on even PC
    c.label("categories")
    c.call("draw_categories")
    c.call("key")
    c.cmp(0, 0xfa)
    c.goto_if("eq", "cancel")
    c.cmp(0, ord("1"))
    c.goto_if("lt", "categories")
    c.cmp(0, ord("7"))
    c.goto_if("ge", "categories")
    c.add(0, -ord("1"))
    c.slot(0, _GROUP, True)
    c.mov(0, 0)
    c.slot(0, _FIRST, True)
    c.jump("browse")

    c.label("browse")
    c.call("draw_menu")
    c.call("key")
    c.cmp(0, 0xfa)
    c.goto_if("eq", "categories")
    c.cmp(0, 0xfc)
    c.goto_if("eq", "page_left")
    c.cmp(0, 0xfd)
    c.goto_if("eq", "page_right")
    c.cmp(0, ord("1"))
    c.goto_if("lt", "browse")
    c.cmp(0, ord("5"))
    c.goto_if("ge", "browse")
    c.add(0, -ord("1"))
    c.slot(8, _FIRST)
    c.op(0x81, 0x80)  # ADD R0,R8
    c.copy(8, 0)
    c.call("item_count")
    c.copy(0, 8)
    c.op(0x77, 0x80)  # CMP R0,R7
    c.goto_if("ge", "browse")
    c.slot(0, _ITEM, True)
    c.jump("selected")
    c.label("page_left")
    c.slot(0, _FIRST)
    c.cmp(0, 4)
    c.goto_if("lt", "page_end")
    c.add(0, -4)
    c.jump("page_store")
    c.label("page_right")
    c.slot(0, _FIRST)
    c.add(0, 4)
    c.copy(8, 0)
    c.call("item_count")
    c.copy(0, 8)
    c.op(0x77, 0x80)
    c.goto_if("ge", "page_begin")
    c.label("page_store")
    c.slot(0, _FIRST, True)
    c.jump("browse")
    c.label("page_begin")
    c.mov(0, 0)
    c.jump("page_store")
    c.label("page_end")
    c.call("item_count")
    c.copy(0, 7)
    c.add(0, -1)
    c.and_(0, 0xfc)
    c.jump("page_store")

    # Resolve the chosen table record, then collect operand fields one at a time.
    c.label("selected")
    c.call("record")
    c.slot(0, _KIND)
    c.slot(1, _BASE)
    c.mov(0, 0)
    for slot in (_FIELD, _A, _B, *range(52, 56), *range(_NIB, _NIB + 8)):
        c.slot(0, slot, True)
    c.mov(0, 255)
    c.slot(0, _NIB + 7, True)
    c.call("old_length")
    c.slot(0, _OLD, True)
    c.label("operand")
    c.call("field_kind")  # R0: 0 done, 1 register, 2 ER, 3 bit, 4 hex nibble
    c.cmp(0, 0)
    c.goto_if("eq", "segment")
    c.slot(0, _COUNT, True)
    c.call("draw_operand")
    c.label("operand_key")
    c.call("key")
    c.cmp(0, 0xfa)
    c.goto_if("eq", "browse")
    c.cmp(0, 0xfc)
    c.goto_if("eq", "operand_prev")
    c.cmp(0, 0xfd)
    c.goto_if("eq", "operand_next")
    c.cmp(0, 0xfe)
    c.goto_if("eq", "operand_down")
    c.cmp(0, 0xff)
    c.goto_if("eq", "operand_up")
    c.cmp(0, 0xfb)
    c.goto_if("eq", "operand_next")
    # The key wrapper returns ASCII 0..9 and hexadecimal A..F.
    c.cmp(0, ord("0"))
    c.goto_if("lt", "operand_key")
    c.cmp(0, ord("9") + 1)
    c.goto_if("ge", "operand_letter")
    c.add(0, -ord("0"))
    c.jump("operand_digit")
    c.label("operand_letter")
    c.cmp(0, ord("A"))
    c.goto_if("lt", "operand_key")
    c.cmp(0, ord("F") + 1)
    c.goto_if("ge", "operand_key")
    c.add(0, 10 - ord("A"))
    c.label("operand_digit")
    c.call("set_field")
    c.cmp(0, 0)
    c.goto_if("ne", "operand_key")
    c.slot(0, _FIELD)
    c.add(0, 1)
    c.slot(0, _FIELD, True)
    c.call("field_kind")
    c.cmp(0, 0)
    c.goto_if("ne", "operand")
    c.slot(0, _FIELD)
    c.add(0, -1)
    c.slot(0, _FIELD, True)
    c.call("draw_operand")
    c.jump("operand_key")
    c.label("operand_down")
    c.mov(1, 255)
    c.jump("operand_change")
    c.label("operand_up")
    c.mov(1, 1)
    c.label("operand_change")
    c.call("change_field")
    c.call("draw_operand")
    c.jump("operand_key")
    c.label("operand_prev")
    c.slot(0, _FIELD)
    c.cmp(0, 0)
    c.goto_if("eq", "operand_key")
    c.add(0, -1)
    c.slot(0, _FIELD, True)
    c.jump("operand")
    c.label("operand_next")
    c.slot(0, _FIELD)
    c.add(0, 1)
    c.slot(0, _FIELD, True)
    c.jump("operand")

    c.label("segment")
    c.slot(0, _KIND)
    c.cmp(0, R_ABS)
    c.goto_if("lt", "encode")
    c.cmp(0, BR)
    c.goto_if("ge", "encode")
    c.label("segment_draw")
    c.call("draw_segment")
    c.label("segment_key")
    c.call("key")
    c.cmp(0, 0xfa)
    c.goto_if("eq", "browse")
    c.cmp(0, 0xfb)
    c.goto_if("eq", "encode")
    c.raw("49 70 75 51")  # DEL: measured scanner event 7549h.
    c.goto_if("eq", "segment_clear")
    c.cmp(0, ord("0"))
    c.goto_if("lt", "segment_key")
    c.cmp(0, ord("9") + 1)
    c.goto_if("ge", "segment_letter")
    c.add(0, -ord("0"))
    c.jump("segment_store")
    c.label("segment_letter")
    c.cmp(0, ord("A"))
    c.goto_if("lt", "segment_key")
    c.cmp(0, ord("F") + 1)
    c.goto_if("ge", "segment_key")
    c.add(0, 10 - ord("A"))
    c.jump("segment_store")
    c.label("segment_clear")
    c.mov(0, 255)
    c.label("segment_store")
    c.slot(0, _NIB + 7, True)
    c.jump("segment_draw")
    c.label("encode")
    c.call("assemble")
    c.cmp(0, 0)
    c.goto_if("ne", "bad_target")
    c.call("draw_result")
    c.label("confirm")
    c.call("key")
    c.cmp(0, 0xfa)
    c.goto_if("eq", "browse")
    c.cmp(0, 0xfc)
    c.goto_if("eq", "result_back")
    c.cmp(0, 0xfb)
    c.goto_if("eq", "commit")
    c.jump("confirm")
    c.label("result_back")
    c.slot(0, _FIELD)
    c.cmp(0, 0)
    c.goto_if("eq", "confirm")
    c.add(0, -1)
    c.slot(0, _FIELD, True)
    c.jump("operand")
    c.label("bad_target")
    c.call("draw_bad_target")
    c.label("bad_target_key")
    c.call("key")
    c.cmp(0, 0)
    c.goto_if("eq", "bad_target_key")
    c.slot(0, _FIELD)
    c.add(0, -1)
    c.slot(0, _FIELD, True)
    c.jump("operand")
    c.label("commit")
    c.word_slot(8, _DESC)
    c.slot(0, _OLD)
    c.ram(0, 0x80, True)
    c.add_er(8, 1)
    c.slot(0, _NEW)
    c.ram(0, 0x80, True)
    c.add_er(8, 1)
    c.mov(7, 8)
    c.pair(2, 14)
    c.add_er(2, 52)
    c.label("commit_loop")
    c.ram(0, 0x20)
    c.ram(0, 0x80, True)
    c.add_er(8, 1)
    c.add_er(2, 1)
    c.add(7, -1)
    c.cmp(7, 0)
    c.goto_if("ne", "commit_loop")
    c.mov_er(0, 0)
    c.jump("exit")
    c.label("cancel")
    c.mov_er(0, 0xffff)
    c.label("exit")
    c.raw("20 e1 20 e1 20 e1 1e fe 1e fc 3e f8 1e f6 2e f4 8e f2")

    # Keep the caller's page pointer across the shared hexadecimal scanner.
    c.label("key")
    c.raw("ce f8 5e f4")
    c.call(HEX_KEY_ADDRESS)
    c.raw("1e f4 8e f2")
    _routines(c)
    _codec_adapter(c)
    _display(c)
    _tables(c)
    return c


def isa_code():
    """Return the picker payload at its layout-owned Flash address."""
    code = _build()
    return ((ISA_ENTRY_ADDRESS - 0x80000, code.build()),)




def _tables(c):
    start = c.address + len(c.data)
    for row, text in enumerate(("1:ARITH 2:MOVE", "3:BR    4:LOADST", "5:STACK 6:MISC")):
        c.label(f"category_row_{row}")
        c.text(text)
    c.label("category_title")
    c.text("FUNCTION")
    for label, message in (
        ("operand_bad_text", "BAD OPERAND"),
        ("branch_odd_text", "ODD BR TARGET"),
        ("branch_outside_text", "NOT IN S1 PROG"),
        ("branch_range_text", "BR OUT OF RANGE"),
    ):
        c.label(label)
        c.text(message)
    DATA_SPANS.append((start, c.address + len(c.data) - start))


def _routines(c):
    c.label("item_count")
    c.mov_er(0, COUNTS_ADDRESS & 0xffff)
    c.slot(6, _GROUP)
    c.mov(7, 0)
    c.op(0x66, 0xf0)
    c.ram(7, 0x00, segment=RECORD_SEGMENT)
    c.return_()

    c.label("record")
    c.mov_er(0, STARTS_ADDRESS & 0xffff)
    c.slot(6, _GROUP)
    c.mov(7, 0)
    c.op(0x66, 0xf0)
    c.ram(6, 0x00, segment=RECORD_SEGMENT)
    c.slot(7, _ITEM)
    c.op(0x71, 0x86)  # ADD R6,R7
    c.copy(2, 6)
    c.mov(3, 0)
    c.mov(0, 16)
    c.op(0x04, 0xf2)  # MUL ER2,R0
    c.mov_er(0, INSTRUCTION_RECORDS_ADDRESS & 0xffff)
    c.op(0x26, 0xf0)
    c.word_slot(0, _REC, True)
    c.ram(6, 0x00, segment=RECORD_SEGMENT)
    c.add_er(0, 2)
    c.ram(7, 0x00, segment=RECORD_SEGMENT)
    c.slot(6, _KIND, True)
    c.slot(7, _BASE, True)
    c.add_er(0, 1)
    c.ram(7, 0x00, segment=RECORD_SEGMENT)
    c.slot(7, _HIGH, True)
    c.add_er(0, 9)
    c.ram(6, 0x00, segment=RECORD_SEGMENT)
    c.add_er(0, 1)
    c.ram(7, 0x00, segment=RECORD_SEGMENT)
    c.copy(0, 6)
    c.copy(1, 7)
    c.word_slot(0, _NAME, True)
    c.slot(0, _KIND)
    c.slot(1, _BASE)
    c.return_()


    c.label("field_kind")
    c.word_slot(0, _REC)
    c.add_er(0, 4)
    c.slot(6, _FIELD)
    c.mov(7, 0)
    c.op(0x66, 0xf0)
    c.ram(0, 0x00, segment=RECORD_SEGMENT)
    c.return_()


    c.label("set_field")
    c.copy(1, 0)
    c.slot(7, _COUNT)
    c.cmp(7, 5)
    c.goto_if("ne", "set_not_xr")
    c.and_(0, 3)
    c.goto_if("ne", "set_invalid")
    c.label("set_not_xr")
    c.cmp(7, 6)
    c.goto_if("ne", "set_not_qr")
    c.copy(0, 1)
    c.and_(0, 7)
    c.goto_if("ne", "set_invalid")
    c.label("set_not_qr")
    c.cmp(7, 2)
    c.goto_if("ne", "set_not_er")
    c.copy(0, 1)
    c.and_(0, 1)
    c.goto_if("ne", "set_invalid")
    c.label("set_not_er")
    c.cmp(7, 3)
    c.goto_if("ne", "set_hex_check")
    c.cmp(1, 8)
    c.goto_if("ge", "set_invalid")
    c.label("set_hex_check")
    c.slot(6, _FIELD)
    c.cmp(7, 4)
    c.goto_if("ne", "set_register")
    c.add(6, _NIB)
    c.slot(7, _KIND)
    c.cmp(7, EI7)
    c.goto_if("ne", "set_far")
    c.cmp(6, _NIB + 1)
    c.goto_if("ne", "set_far")
    c.cmp(1, 8)
    c.goto_if("ge", "set_invalid")
    c.label("set_far")
    for kind, last in ((FAR, 3), (FAR_SYS, 4), (ER_ABS, 4)):
        skip = f"set_even_{kind}"
        c.cmp(7, kind)
        c.goto_if("ne", skip)
        c.cmp(6, _NIB + last)
        c.goto_if("ne", skip)
        c.copy(0, 1)
        c.and_(0, 1)
        c.goto_if("ne", "set_invalid")
        c.label(skip)
    c.jump("set_store")
    c.label("set_register")
    c.cmp(6, 0)
    c.goto_if("eq", "set_a")
    c.mov(6, _B)
    c.jump("set_store")
    c.label("set_a")
    c.mov(6, _A)
    c.label("set_store")
    c.mov(7, 0)
    c.pair(2, 14)
    c.op(0x66, 0xf2)
    c.ram(1, 0x20, True)
    c.mov(0, 0)
    c.return_()
    c.label("set_invalid")
    c.mov(0, 255)
    c.return_()
    c.label("change_field")
    c.slot(7, _COUNT)
    c.cmp(7, 4)
    c.goto_if("eq", "change_hex")
    c.slot(6, _FIELD)
    c.cmp(6, 0)
    c.goto_if("eq", "change_a")
    c.mov(6, _B)
    c.jump("change_loaded")
    c.label("change_a")
    c.mov(6, _A)
    c.jump("change_loaded")
    c.label("change_hex")
    c.slot(6, _FIELD)
    c.add(6, _NIB)
    c.label("change_loaded")
    c.mov(7, 0)
    c.pair(2, 14)
    c.op(0x66, 0xf2)
    c.ram(0, 0x20)
    c.slot(7, _COUNT)
    c.cmp(7, 5)
    c.goto_if("ne", "change_not_xr")
    c.shift(1, 2)
    c.jump("change_byte")
    c.label("change_not_xr")
    c.cmp(7, 6)
    c.goto_if("ne", "change_not_qr")
    c.shift(1, 3)
    c.jump("change_byte")
    c.label("change_not_qr")
    c.cmp(7, 2)
    c.goto_if("ne", "change_byte")
    c.shift(1, 1)
    c.label("change_byte")
    c.cmp(7, 4)
    c.goto_if("ne", "change_step_done")
    c.slot(7, _KIND)
    c.cmp(7, FAR)
    c.goto_if("ne", "change_step_sys")
    c.cmp(6, _NIB + 3)
    c.goto_if("eq", "change_step_even")
    c.label("change_step_sys")
    c.cmp(7, FAR_SYS)
    c.goto_if("ne", "change_step_abs")
    c.cmp(6, _NIB + 4)
    c.goto_if("eq", "change_step_even")
    c.label("change_step_abs")
    c.cmp(7, ER_ABS)
    c.goto_if("ne", "change_step_done")
    c.cmp(6, _NIB + 4)
    c.goto_if("ne", "change_step_done")
    c.label("change_step_even")
    c.shift(1, 1)
    c.label("change_step_done")
    c.slot(7, _COUNT)
    c.op(0x11, 0x80)  # ADD R0,R1
    c.cmp(7, 3)
    c.goto_if("eq", "change_bit")
    c.cmp(7, 2)
    c.goto_if("eq", "change_er")
    c.cmp(7, 5)
    c.goto_if("eq", "change_xr")
    c.cmp(7, 6)
    c.goto_if("eq", "change_qr")
    c.and_(0, 15)
    c.slot(7, _KIND)
    c.cmp(7, EI7)
    c.goto_if("ne", "change_far")
    c.cmp(6, _NIB + 1)
    c.goto_if("eq", "change_seven")
    c.label("change_far")
    c.cmp(7, FAR)
    c.goto_if("ne", "change_sys")
    c.cmp(6, _NIB + 3)
    c.goto_if("eq", "change_even")
    c.label("change_sys")
    c.cmp(7, FAR_SYS)
    c.goto_if("ne", "change_abs_er")
    c.cmp(6, _NIB + 4)
    c.goto_if("eq", "change_even")
    c.label("change_abs_er")
    c.cmp(7, ER_ABS)
    c.goto_if("ne", "store_field")
    c.cmp(6, _NIB + 4)
    c.goto_if("ne", "store_field")
    c.label("change_even")
    c.and_(0, 14)
    c.jump("store_field")
    c.label("change_seven")
    c.and_(0, 7)
    c.jump("store_field")
    c.label("change_bit")
    c.and_(0, 7)
    c.jump("store_field")
    c.label("change_er")
    c.and_(0, 14)
    c.jump("store_field")
    c.label("change_xr")
    c.and_(0, 12)
    c.jump("store_field")
    c.label("change_qr")
    c.and_(0, 8)
    c.label("store_field")
    c.mov(7, 0)
    c.pair(2, 14)
    c.op(0x66, 0xf2)
    c.ram(0, 0x20, True)
    c.return_()

def _codec_adapter(c):
    c.label("old_length")
    c.raw("ce f8 6e f4")
    c.word_slot(0, _PAGE)
    c.pair(4, 0)
    c.add_er(4, 16)
    c.slot(6, _POS)
    c.mov(7, 0)
    c.raw("66 f0")
    c.mov(2, 0)
    c.call(SOURCE_LENGTH_ADDRESS)
    c.cmp(1, 255)
    c.goto_if("ne", "old_length_done")
    # A staged page can end inside an instruction; its tail is still in S1.
    c.word_slot(0, _ADDR)
    c.slot(6, _POS)
    c.mov(7, 0)
    c.raw("66 f0 05 f2")
    c.call(LENGTH_ADDRESS)
    c.cmp(1, 255)
    c.goto_if("ne", "old_length_done")
    c.mov_er(0, 2)  # Keep erased/invalid selections editable as one word.
    c.label("old_length_done")
    c.raw("2e f4 8e f2")

    c.label("assemble")
    c.raw("ce f8")
    # Register fields share the public nibble array with immediate fields.
    for index, slot in ((0, _A), (1, _B)):
        skip = f"codec_nibble_{index}"
        c.word_slot(0, _REC)
        c.add_er(0, 4 + index)
        c.ram(0, 0x00, segment=RECORD_SEGMENT)
        c.cmp(0, 4)
        c.goto_if("eq", skip)
        c.slot(0, slot)
        c.slot(0, _NIB + index, True)
        c.label(skip)
    c.mov(0, 0)
    for slot in range(52, 60):
        c.slot(0, slot, True)
    c.word_slot(0, _ADDR)
    c.slot(6, _POS)
    c.mov(7, 0)
    c.raw("66 f0")
    c.pair(8, 0)
    c.word_slot(2, _REC)
    c.pair(4, 14)
    c.add_er(4, _NIB)
    c.pair(6, 14)
    c.add_er(6, 52)
    c.pair(0, 8)
    c.call(ENCODE_ADDRESS)
    c.copy(7, 2)
    c.slot(0, _DISP, True)
    c.slot(7, _NEW, True)
    c.raw("8e f2")




def _display(c):
    c.label("draw_segment")
    c.raw("ce f8")
    c.call(0x0409a)
    c.call("old_line")
    c.call("name_line")
    c.pair(10, 14)
    for char in "SEG ":
        c.mov(0, ord(char))
        c.ram(0, 0xa0, True)
        c.add_er(10, 1)
    c.slot(0, _NIB + 7)
    c.cmp(0, 255)
    c.goto_if("ne", "segment_value")
    c.mov(0, ord("-"))
    c.ram(0, 0xa0, True)
    c.add_er(10, 1)
    c.jump("segment_char")
    c.label("segment_value")
    c.call("hexchar")
    c.label("segment_char")
    c.ram(0, 0xa0, True)
    c.add_er(10, 1)
    c.mov(0, 0)
    c.ram(0, 0xa0, True)
    c.mov(1, 17)
    c.call("lcd")
    c.call(0x043be)
    c.raw("8e f2")

    c.label("lcd")
    c.mov(0, 7)
    c.jump("lcd_font")
    c.label("menu_lcd")
    c.mov(0, 8)  # ROM 5x7 ASCII, six-pixel character spacing
    c.label("lcd_font")
    c.raw("ce f8")
    c.slot(0, 76, True)
    c.db(0x10, 0x90, 0xa0, 0x80)
    c.slot(0, 74, True)
    c.db(0x10, 0x90, 0xa2, 0x80)
    c.slot(0, 75, True)
    c.slot(0, 76)
    c.db(0x11, 0x90, 0xa0, 0x80)
    c.mov(0, 1)
    c.db(0x11, 0x90, 0xa2, 0x80)
    c.slot(1, 51, True)
    c.mov(0, 0)
    c.slot(1, 51)
    c.pair(2, 14)
    c.raw("5e f4")
    c.call(0x041da)
    c.raw("1e f4")
    c.slot(0, 75)
    c.db(0x11, 0x90, 0xa2, 0x80)
    c.slot(0, 74)
    c.db(0x11, 0x90, 0xa0, 0x80)
    c.raw("8e f2")

    # Flash text is copied to the caller's segment-zero line buffer.
    c.label("show")
    c.mov(0, 7)
    c.jump("show_font")
    c.label("menu_show")
    c.mov(0, 8)
    c.label("show_font")
    c.raw("ce f8")
    c.pair(8, 2)
    c.slot(0, 76, True)
    c.slot(1, 51, True)
    c.pair(0, 14)
    c.pair(2, 8)
    c.mov_er(6, 17)
    c.call(UI_TEXT_ADDRESS)
    c.slot(1, 51)
    c.slot(0, 76)
    c.call("lcd_font")
    c.raw("8e f2")  # POP PC, returning through the saved LR

    c.label("hexchar")
    c.cmp(0, 10)
    c.goto_if("ge", "hex_letter")
    c.add(0, ord("0"))
    c.return_()
    c.label("hex_letter")
    c.add(0, ord("A") - 10)
    c.return_()

    c.label("hexbyte")
    c.raw("ce f8")
    c.copy(7, 0)
    c.shift(0, 4, right=True)
    c.call("hexchar")
    c.ram(0, 0xa0, True)
    c.add_er(10, 1)
    c.copy(0, 7)
    c.and_(0, 15)
    c.call("hexchar")
    c.ram(0, 0xa0, True)
    c.add_er(10, 1)
    c.raw("8e f2")

    c.label("old_line")
    c.raw("ce f8")
    c.pair(10, 14)
    c.call("old_length")
    c.slot(0, _OLD, True)
    c.word_slot(0, _ADDR)
    c.slot(6, _POS)
    c.op(0x61, 0x80)
    c.op(0x00, 0x61)
    c.copy(8, 0)
    c.copy(0, 1)
    c.call("hexbyte")
    c.copy(0, 8)
    c.call("hexbyte")
    c.mov(0, ord(" "))
    c.ram(0, 0xa0, True)
    c.add_er(10, 1)
    c.mov(9, 0)
    c.label("old_bytes")
    c.slot(0, _POS)
    c.op(0x91, 0x80)  # ADD R0,R9
    c.cmp(0, 16)
    c.goto_if("ge", "old_bytes_done")
    c.word_slot(0, _PAGE)
    c.slot(6, _POS)
    c.op(0x91, 0x86)  # ADD R6,R9
    c.mov(7, 0)
    c.op(0x66, 0xf0)
    c.ram(0, 0x00)
    c.call("hexbyte")
    c.add(9, 1)
    c.slot(0, _OLD)
    c.op(0x07, 0x89)  # CMP R9,R0
    c.goto_if("lt", "old_bytes")
    c.label("old_bytes_done")
    c.mov(0, 0)
    c.ram(0, 0xa0, True)
    c.mov(1, 1)
    c.call("lcd")
    c.raw("8e f2")

    c.label("name_line")
    c.raw("ce f8")
    c.word_slot(2, _NAME)
    c.mov(1, 9)
    c.call("show")
    c.raw("8e f2")

    c.label("menu_copy")
    c.raw("ce f8")
    c.pair(0, 10)
    c.pair(2, 6)
    c.mov_er(6, 15)
    c.call(UI_TEXT_ADDRESS)
    c.raw("8e f2")


    # ER2: bank-F name, R6: printed number, R1: LCD row.
    c.label("menu_row")
    c.raw("ce f8")
    c.pair(8, 2)
    c.slot(1, 51, True)
    c.pair(10, 14)
    c.copy(0, 6)
    c.add(0, ord("0"))
    c.ram(0, 0xa0, True)
    c.add_er(10, 1)
    c.mov(0, ord(":"))
    c.ram(0, 0xa0, True)
    c.add_er(10, 1)
    c.pair(6, 8)
    c.mov(9, 14)
    c.call("menu_copy")
    c.slot(1, 51)
    c.call("menu_lcd")
    c.raw("8e f2")

    c.label("draw_categories")
    c.raw("ce f8")
    c.call(0x0409a)
    c.ref(2, "category_title")
    c.mov(1, 1)
    c.call("menu_show")
    for row, y in enumerate((9, 17, 25)):
        c.ref(2, f"category_row_{row}")
        c.mov(1, y)
        c.call("menu_show")
    c.call(0x043be)
    c.raw("8e f2")

    c.label("draw_menu")
    c.raw("ce f8")
    c.call(0x0409a)
    for row, y in enumerate((1, 9, 17, 25)):
        skip = f"menu_row_skip_{row}"
        c.slot(0, _FIRST)
        c.add(0, row)
        c.copy(8, 0)
        c.call("item_count")
        c.copy(0, 8)
        c.op(0x77, 0x80)  # CMP R0,R7
        c.goto_if("ge", skip)
        c.slot(0, _ITEM, True)
        c.call("record")
        c.word_slot(2, _NAME)
        c.mov(6, row + 1)
        c.mov(1, y)
        c.call("menu_row")
        c.label(skip)
    c.call(0x043be)
    c.raw("8e f2")

    c.label("draw_operand")
    c.raw("ce f8")
    c.call(0x0409a)
    c.call("old_line")
    c.call("name_line")
    c.pair(10, 14)
    c.slot(7, _COUNT)
    c.mov(0, ord("R"))
    c.cmp(7, 2)
    c.goto_if("ne", "operand_not_er")
    c.mov(0, ord("E"))
    c.label("operand_not_er")
    c.cmp(7, 3)
    c.goto_if("ne", "operand_not_bit")
    c.mov(0, ord("B"))
    c.label("operand_not_bit")
    c.cmp(7, 4)
    c.goto_if("ne", "operand_label")
    c.mov(0, ord("H"))
    c.slot(7, _KIND)
    c.cmp(7, BR)
    c.goto_if("ne", "operand_label")
    c.mov(0, ord("T"))
    c.label("operand_label")
    c.ram(0, 0xa0, True)
    c.add_er(10, 1)
    c.slot(9, _FIELD)
    c.copy(0, 9)
    c.add(0, 1)
    c.call("hexchar")
    c.ram(0, 0xa0, True)
    c.add_er(10, 1)
    c.mov(0, ord("="))
    c.ram(0, 0xa0, True)
    c.add_er(10, 1)
    c.slot(7, _COUNT)
    c.cmp(7, 4)
    c.goto_if("eq", "operand_hex")
    c.cmp(9, 0)
    c.goto_if("eq", "operand_a")
    c.slot(0, _B)
    c.jump("operand_value")
    c.label("operand_a")
    c.slot(0, _A)
    c.jump("operand_value")
    c.label("operand_hex")
    c.pair(2, 14)
    c.add_er(2, _NIB)
    c.copy(0, 9)
    c.mov(1, 0)
    c.op(0x06, 0xf2)
    c.ram(0, 0x20)
    c.label("operand_value")
    c.call("hexchar")
    c.ram(0, 0xa0, True)
    c.add_er(10, 1)
    for char in " EXE":
        c.mov(0, ord(char))
        c.ram(0, 0xa0, True)
        c.add_er(10, 1)
    c.mov(0, 0)
    c.ram(0, 0xa0, True)
    c.mov(1, 17)
    c.call("lcd")
    c.call(0x043be)
    c.raw("8e f2")

    c.label("draw_bad_target")
    c.raw("ce f8")
    c.call(0x0409a)
    c.call("old_line")
    c.call("name_line")
    c.slot(0, _DISP)
    c.cmp(0, 1)
    c.goto_if("ne", "bad_target_text")
    c.ref(2, "operand_bad_text")
    c.jump("bad_show")
    c.label("bad_target_text")
    c.cmp(0, 2)
    c.goto_if("ne", "bad_outside_text")
    c.ref(2, "branch_odd_text")
    c.jump("bad_show")
    c.label("bad_outside_text")
    c.cmp(0, 3)
    c.goto_if("ne", "bad_range_text")
    c.ref(2, "branch_outside_text")
    c.jump("bad_show")
    c.label("bad_range_text")
    c.ref(2, "branch_range_text")
    c.label("bad_show")
    c.mov(1, 17)
    c.call("show")
    c.call(0x043be)
    c.raw("8e f2")

    c.label("draw_result")
    c.raw("ce f8")
    c.call(0x0409a)
    c.call("old_line")
    c.call("name_line")
    c.call(0x043be)
    c.pair(10, 14)
    c.mov(9, 0)
    c.label("result_bytes")
    c.pair(2, 14)
    c.add_er(2, 52)
    c.copy(0, 9)
    c.mov(1, 0)
    c.op(0x06, 0xf2)
    c.ram(0, 0x20)
    c.call("hexbyte")
    c.mov(0, ord(" "))
    c.ram(0, 0xa0, True)
    c.add_er(10, 1)
    c.add(9, 1)
    c.slot(0, _NEW)
    c.op(0x07, 0x89)  # CMP R9,R0
    c.goto_if("ge", "result_end")
    c.cmp(9, 4)
    c.goto_if("ne", "result_bytes")
    c.mov(0, 0)
    c.ram(0, 0xa0, True)
    c.mov(1, 17)
    c.call("lcd")
    c.pair(10, 14)
    c.mov(9, 4)
    c.jump("result_bytes")
    c.label("result_end")
    for char in "EXE":
        c.mov(0, ord(char))
        c.ram(0, 0xa0, True)
        c.add_er(10, 1)
    c.mov(0, 0)
    c.ram(0, 0xa0, True)
    c.slot(0, _NEW)
    c.cmp(0, 5)
    c.goto_if("ge", "result_second")
    c.mov(1, 17)
    c.jump("result_show")
    c.label("result_second")
    c.mov(1, 25)
    c.label("result_show")
    c.call("lcd")
    c.call(0x043be)
    c.raw("8e f2")
