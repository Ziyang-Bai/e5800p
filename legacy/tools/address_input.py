"""Emit the ASM address prompt and hexadecimal key translation."""

from u8_emit import Code
from flash_layout import GOTO_ADDRESS, HEX_KEY_ADDRESS, MEMORY_GOTO_ADDRESS, SCANNER_ADDRESS
from ui_text import text_copy

RAM_BEGIN, RAM_END = 0x8000, 0x8e00


def address_code():
    c = Code(GOTO_ADDRESS)

    def far_if(condition, target):
        skip = f"skip_{len(c.fixups)}"
        c.branch({"eq": "ne", "ne": "eq", "lt": "ge", "ge": "lt"}[condition], skip)
        c.jump(target)
        c.label(skip)

    def ptr(offset=0):
        c.raw("e5 f2")
        if offset:
            c.db(0x80 | offset, 0xe2)

    def text(value, y):
        ptr()
        text_copy(c, value, 26)
        ptr()
        c.mov(0, 0)
        c.mov(1, y)
        c.call(0x041da)

    c.jump("address")
    c.jump("hex_key")
    c.jump("memory")
    c.label("hex_key")
    c.raw("ce f8 6e f4")
    c.call(SCANNER_ADDRESS)
    c.raw("fa 70")
    c.branch("ge", "key_done")
    c.raw("02 70 7d 51")
    c.branch("eq", "key_done")
    c.raw("49 70 75 51")  # Preserve DEL for the ISA segment-prefix prompt.
    c.branch("eq", "key_done")
    c.raw("00 71")
    c.branch("eq", "key_ascii")
    c.mov_er(0, 0)  # Modifier events carry a 75h/7Dh class, ASCII has R1=0.
    c.jump("key_done")
    c.label("key_ascii")
    for raw, digit in zip("STUNOP", "ABCDEF"):
        c.db(ord(raw), 0x70)
        c.branch("ne", f"key_{digit}")
        c.mov(0, ord(digit))
        c.jump("key_done")
        c.label(f"key_{digit}")
    c.label("key_done")
    c.raw("2e f4 8e f2")

    # ER0: initial address, R2: require an even PC. Return ER0, R2=accepted.
    c.label("address")
    c.raw("ce f8 6e f4 7e f8 5e fc 5e fe e0 e1 1a ae")
    c.raw("05 f8 20 8c 00 0d")
    c.raw("10 90 a0 80")
    ptr(28)
    c.raw("21 90 10 90 a2 80 81 e2 21 90")
    c.mov(0, 7)
    c.raw("11 90 a0 80")
    c.mov(0, 1)
    c.raw("11 90 a2 80")
    c.mov(6, 0)
    c.mov(7, 0)
    c.label("draw")
    c.call(0x0409a)
    text("GOTO ADDRESS", 1)
    ptr()
    text_copy(c, "8:", 26)
    ptr(2)
    c.raw("90 80")
    c.call("hexbyte")
    c.raw("80 80")
    c.call("hexbyte")
    c.mov(0, 0)
    c.raw("21 90")
    ptr()
    c.mov(0, 0)
    c.mov(1, 9)
    c.call(0x041da)
    c.raw("00 77")
    c.branch("eq", "hint")
    c.raw("01 77")
    c.branch("ne", "odd_hint")
    text("4000..5FEF", 17)
    c.jump("footer")
    c.label("odd_hint")
    text("EVEN ADDRESS", 17)
    c.jump("footer")
    c.label("hint")
    text("HEX 4 DIGITS", 17)
    c.label("footer")
    text("EXE OK EXIT BACK", 25)
    c.call(0x043be)
    c.label("input")
    c.call(HEX_KEY_ADDRESS)
    c.db(0xfa, 0x70)
    far_if("eq", "cancel")
    c.db(0xfb, 0x70)
    far_if("eq", "accept")
    c.db(0xfc, 0x70)
    far_if("eq", "backspace")
    c.db(ord("0"), 0x70)
    far_if("lt", "input")
    c.db(ord("9") + 1, 0x70)
    c.branch("ge", "letter")
    c.db(-ord("0") & 255, 0x10)
    c.jump("digit")
    c.label("letter")
    c.db(ord("A"), 0x70)
    far_if("lt", "input")
    c.db(ord("F") + 1, 0x70)
    far_if("ge", "input")
    c.db((10 - ord("A")) & 255, 0x10)
    c.label("digit")
    c.raw("04 76")
    c.branch("lt", "digit_count")
    c.mov(6, 0)
    c.label("digit_count")
    c.raw("00 76")
    c.branch("ne", "append")
    c.mov_er(8, 0)
    c.label("append")
    c.raw("80 83 4c 93 4a 98 4a 99 33 89 03 88")  # ER8 = (ER8 << 4) | R0
    c.raw("01 16")
    c.mov(7, 0)
    c.jump("draw")
    c.label("backspace")
    c.raw("00 76")
    far_if("eq", "input")
    c.raw("90 83 4a 93 4c 98 4c 99 33 88 ff 16")  # ER8 >>= 4
    c.mov(7, 0)
    c.jump("draw")
    c.label("accept")
    c.raw("00 76")
    c.branch("eq", "check_range")
    c.raw("04 76")
    far_if("ne", "draw")
    c.label("check_range")
    c.raw("85 f0")
    c.mov_er(2, 0x4000)
    c.raw("27 f0")
    far_if("lt", "range_error")
    c.mov_er(2, 0x5ff0)
    c.raw("27 f0")
    far_if("ge", "range_error")
    c.raw("00 7c")
    c.branch("eq", "accepted")
    c.raw("80 80 01 20")
    far_if("ne", "odd_error")
    c.label("accepted")
    c.mov(4, 1)
    c.jump("finish")
    c.label("range_error")
    c.mov(7, 1)
    c.jump("draw")
    c.label("odd_error")
    c.mov(7, 2)
    c.jump("draw")
    c.label("cancel")
    c.mov(4, 0)
    c.label("finish")
    ptr(29)
    c.raw("20 90 11 90 a2 80")
    ptr(28)
    c.raw("20 90 11 90 a0 80 85 f0 40 82")
    c.raw("20 e1 1e fe 1e fc 3e f8 2e f4 8e f2")

    # Hex: ER0=offset, R2=DSR. Returns ER0=offset, R2=DSR, R3=accepted.
    c.label("memory")
    c.raw("ce f8 6e f4 7e f8 5e fc 5e fe d0 e1 1a ae")
    c.raw("05 f8 20 8d")
    c.raw("10 90 a0 80")
    ptr(28)
    c.raw("21 90 10 90 a2 80 81 e2 21 90")
    c.mov(0, 8)
    c.raw("11 90 a0 80")
    c.mov(0, 1)
    c.raw("11 90 a2 80")
    c.label("memory_menu")
    c.call(0x0409a)
    for line, y in (("1:FLASH", 1), ("2:SRAM", 9), ("3:RAM", 17),
                    ("EXIT BACK", 25)):
        text(line, y)
    c.call(0x043be)
    c.label("memory_menu_key")
    c.call(HEX_KEY_ADDRESS)
    c.db(0xfa, 0x70)
    far_if("eq", "memory_cancel")
    for digit, target in (("1", "memory_flash"), ("2", "memory_sram"),
                          ("3", "memory_ram")):
        c.db(ord(digit), 0x70)
        far_if("eq", target)
    c.jump("memory_menu_key")
    c.label("memory_flash")
    c.mov(12, 0)
    c.mov(10, 5)
    c.db(8, 0x7d)
    c.branch("ge", "memory_ready")
    c.mov(13, 8)
    c.mov_er(8, 0x4000)
    c.jump("memory_ready")
    c.label("memory_sram")
    c.mov(12, 1)
    c.mov(10, 4)
    c.db(4, 0x7d)
    c.branch("eq", "memory_ready")
    c.mov(13, 4)
    c.mov_er(8, 0)
    c.jump("memory_ready")
    c.label("memory_ram")
    c.mov(12, 2)
    c.mov(10, 4)
    c.db(0, 0x7d)
    c.branch("eq", "memory_ready")
    c.mov(13, 0)
    c.mov_er(8, RAM_BEGIN)
    c.label("memory_ready")
    c.mov(6, 0)
    c.mov(7, 0)
    c.label("memory_draw")
    c.call(0x0409a)
    c.db(0, 0x7c)
    c.branch("ne", "memory_title_sram")
    text("GOTO FLASH", 1)
    c.jump("memory_address")
    c.label("memory_title_sram")
    c.db(1, 0x7c)
    c.branch("ne", "memory_title_ram")
    text("GOTO SRAM", 1)
    c.jump("memory_address")
    c.label("memory_title_ram")
    text("GOTO RAM", 1)
    c.label("memory_address")
    ptr()
    c.raw("d0 80")
    c.call("nibble")
    c.raw("21 90 81 e2")
    c.mov(0, ord(":"))
    c.raw("21 90 81 e2 90 80")
    c.call("hexbyte")
    c.raw("80 80")
    c.call("hexbyte")
    c.mov(0, 0)
    c.raw("21 90")
    ptr()
    c.mov(0, 0)
    c.mov(1, 9)
    c.call(0x041da)
    c.db(0, 0x77)
    c.branch("eq", "memory_range")
    text("ADDRESS RANGE", 17)
    c.jump("memory_footer")
    c.label("memory_range")
    c.db(0, 0x7c)
    c.branch("ne", "memory_range_sram")
    text("8:0000..F:FFFF", 17)
    c.jump("memory_footer")
    c.label("memory_range_sram")
    c.db(1, 0x7c)
    c.branch("ne", "memory_range_ram")
    text("0000..7FFF", 17)
    c.jump("memory_footer")
    c.label("memory_range_ram")
    text("8000..8DFF", 17)
    c.label("memory_footer")
    text("EXE OK EXIT BACK", 25)
    c.call(0x043be)
    c.label("memory_input")
    c.call(HEX_KEY_ADDRESS)
    for key, target in ((0xfa, "memory_cancel"), (0xfb, "memory_accept"),
                        (0xfc, "memory_backspace")):
        c.db(key, 0x70)
        far_if("eq", target)
    c.db(ord("0"), 0x70)
    far_if("lt", "memory_input")
    c.db(ord("9") + 1, 0x70)
    c.branch("ge", "memory_letter")
    c.db(-ord("0") & 255, 0x10)
    c.jump("memory_digit")
    c.label("memory_letter")
    c.db(ord("A"), 0x70)
    far_if("lt", "memory_input")
    c.db(ord("F") + 1, 0x70)
    far_if("ge", "memory_input")
    c.db((10 - ord("A")) & 255, 0x10)
    c.label("memory_digit")
    c.raw("a7 86")
    c.branch("lt", "memory_digit_count")
    c.mov(6, 0)
    c.label("memory_digit_count")
    c.db(0, 0x76)
    c.branch("ne", "memory_append")
    c.mov_er(8, 0)
    c.db(0, 0x7c)
    c.branch("ne", "memory_append")
    c.mov(13, 0)
    c.label("memory_append")
    c.db(0, 0x7c)
    c.branch("ne", "memory_append_word")
    c.raw("90 83 4c 93 4a 9d 33 8d")
    c.label("memory_append_word")
    c.raw("80 83 4c 93 4a 98 4a 99 33 89 03 88 01 16")
    c.mov(7, 0)
    c.jump("memory_draw")
    c.label("memory_backspace")
    c.db(0, 0x76)
    far_if("eq", "memory_input")
    c.raw("90 83 4a 93 4c 98 4c 99 33 88")
    c.db(0, 0x7c)
    c.branch("ne", "memory_backspace_done")
    c.raw("d0 83 4a 93 33 89 4c 9d")
    c.label("memory_backspace_done")
    c.raw("ff 16")
    c.mov(7, 0)
    c.jump("memory_draw")
    c.label("memory_accept")
    c.db(0, 0x76)
    c.branch("eq", "memory_check")
    c.raw("a7 86")
    far_if("ne", "memory_draw")
    c.label("memory_check")
    c.db(0, 0x7c)
    c.branch("ne", "memory_check_sram")
    c.db(8, 0x7d)
    far_if("lt", "memory_error")
    c.db(16, 0x7d)
    far_if("ge", "memory_error")
    c.jump("memory_accepted")
    c.label("memory_check_sram")
    c.raw("85 f0")
    c.db(1, 0x7c)
    c.branch("ne", "memory_check_ram")
    c.mov_er(2, 0x8000)
    c.raw("27 f0")
    far_if("ge", "memory_error")
    c.jump("memory_accepted")
    c.label("memory_check_ram")
    c.mov_er(2, RAM_BEGIN)
    c.raw("27 f0")
    far_if("lt", "memory_error")
    c.mov_er(2, RAM_END)
    c.raw("27 f0")
    far_if("ge", "memory_error")
    c.label("memory_accepted")
    c.mov(4, 1)
    c.jump("memory_finish")
    c.label("memory_error")
    c.mov(7, 1)
    c.jump("memory_draw")
    c.label("memory_cancel")
    c.mov(4, 0)
    c.label("memory_finish")
    ptr(29)
    c.raw("20 90 11 90 a2 80")
    ptr(28)
    c.raw("20 90 11 90 a0 80 85 f0 d0 82 40 83")
    c.raw("30 e1 1e fe 1e fc 3e f8 2e f4 8e f2")

    c.label("hexbyte")
    c.raw("ce f8 00 85 4c 90")
    c.call("nibble")
    c.raw("21 90 81 e2 50 80 0f 20")
    c.call("nibble")
    c.raw("21 90 81 e2 8e f2")
    c.label("nibble")
    c.db(10, 0x70)
    c.branch("lt", "number")
    c.db(ord("A") - 10, 0x10)
    c.raw("1f fe")
    c.label("number")
    c.db(ord("0"), 0x10)
    c.raw("1f fe")
    return GOTO_ADDRESS - 0x80000, c.build()
