class _Mode(Code):
    def __init__(self):
        super().__init__(BASIC_ADDRESS)
        self.seq = 0
        self.refs = []
        self.words = []
        self.patches = []

    def ref(self, reg, label):
        self.refs.append((len(self.data), label))
        self.db(0, reg, 0, reg + 1)

    def pointer(self, label):
        self.words.append((len(self.data), label))
        self.word(0)

    def pair(self, dst, src):
        self.db(src << 4 | 5, 0xf0 | dst)

    def rr(self, dst, src, op=0):
        self.db(src << 4 | op, 0x80 | dst)

    def imm(self, reg, value, op=0x10):
        self.db(value & 255, op | reg)

    def add(self, reg, value):
        while value:
            step = max(-64, min(63, value))
            self.db(0x80 | (step & 127), 0xe0 | reg)
            value -= step

    def sp(self, value):
        while value:
            step = max(-128, min(127, value))
            self.db(step & 255, 0xe1)
            value -= step

    def cmp(self, reg, value):
        self.imm(reg, value, 0x70)

    def cond(self, condition, target):
        self.seq += 1
        skip = f"cond_{self.seq}"
        self.branch({"eq": "ne", "ne": "eq", "lt": "ge", "ge": "lt"}[condition], skip)
        self.jump(target)
        self.label(skip)

    def mem(self, reg, ptr, store=False, word=False, bank=None, disp=None, segment=None):
        if segment is not None:
            self.db(segment, 0xe3)
        elif bank is None:
            self.raw("00 e3")
        else:
            self.db(bank << 4 | 15, 0x90)
        low = 8 if disp is not None else (2 if word else 0)
        high = 0xa0 if word and disp is not None else 0x90
        self.db(ptr << 4 | low | int(store), high | reg)
        if disp is not None:
            self.word(disp & 65535)

    def slot(self, reg, offset, store=False, word=False):
        self.mem(reg, 14, store, word, disp=offset)

    def addr(self, reg, offset):
        self.pair(reg, 14)
        self.add(reg, offset)

    def absolute(self, reg, address, store=False, word=False):
        self.raw("00 e3")
        self.db(0x10 | (2 if word else 0) | int(store), 0x90 | reg)
        self.word(address)

    def push(self, reg):
        self.db(0x5e, 0xf0 | reg)

    def pop(self, reg):
        self.db(0x1e, 0xf0 | reg)

    def ret(self):
        self.raw("1f fe")

    def hook(self, address, signature, label, call=False):
        self.patches.append((address, bytes.fromhex(signature), label, call))

    def finish(self):
        data = bytearray(self.build())
        for pos, label in self.refs:
            address = self.labels[label] & 65535
            data[pos], data[pos + 2] = address & 255, address >> 8
        for pos, label in self.words:
            data[pos:pos + 2] = (self.labels[label] & 65535).to_bytes(2, "little")
        if self.address + len(data) > BASIC_STOP:
            raise ValueError(f"BASIC mode exceeds its region: {len(data)} bytes")
        patches = []
        for address, old, label, call in self.patches:
            out = Code(address)
            (out.call if call else out.jump)(self.labels[label])
            patches.append((address, old, out.build()))
        return ((self.address - 0x80000, bytes(data)),), tuple(patches)


def _tokens(c):
    c.hook(0xc70ec, "01 fc d8 30", "admit", True)
    c.hook(0xc75f2, "01 fc d8 30", "admit", True)
    c.label("admit")
    c.raw("ce f8 5e f4")
    c.pair(4, 0)
    c.mem(0, 4, bank=2)
    c.cmp(0, 0xf9)
    c.branch("ne", "admit_native")
    c.mem(0, 4, bank=2, disp=1)
    for name in (name for name in TOKEN_NAMES if name in FUNCTIONS):
        c.cmp(0, TOKENS[name] & 255)
        c.cond("eq", "admit_yes")
    c.label("admit_native")
    c.pair(0, 4)
    c.call(0xc30d8)
    c.raw("1e f4 8e f2")
    c.label("admit_yes")
    c.mov_er(0, 1)
    c.raw("1e f4 8e f2")

    c.hook(0xdfc02, "ce f8 5e fc", "spell")
    c.label("spell")
    c.cmp(1, 0xfe)
    c.branch("ne", "spell_token")
    c.mem(0, 2, True)
    c.mov(0, 0)
    c.mem(0, 2, True, disp=1)
    c.pair(0, 2)
    c.ret()
    c.label("spell_token")
    c.cmp(1, 0xf9)
    c.branch("ne", "spell_native")
    c.cmp(0, 0xe0)
    c.branch("lt", "spell_native")
    c.cmp(0, 0xf9)
    c.branch("ge", "spell_native")
    c.raw("ce f8 6e f4")
    c.pair(4, 2)
    c.imm(0, -0xe0)
    c.mov(1, 0)
    c.raw("1b 91 1a 90")
    c.ref(6, "names")
    c.raw("06 f6")
    c.mem(6, 6, word=True, segment=15)
    c.label("spell_copy")
    c.mem(0, 6, segment=15)
    c.mem(0, 2, True)
    c.add(6, 1)
    c.add(2, 1)
    c.cmp(0, 0)
    c.branch("ne", "spell_copy")
    c.pair(0, 4)
    c.raw("2e f4 8e f2")
    c.label("spell_native")
    c.raw("ce f8 5e fc")
    c.jump(0xdfc06)


