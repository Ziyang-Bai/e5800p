def _entry(c):
    c.hook(0xc71fe, "5b 70 00 51", "function")
    c.label("function")
    c.cmp(1, 0xf9)
    c.branch("ne", "function_native")
    c.cmp(0, 0xe0)
    c.branch("lt", "function_native")
    c.cmp(0, 0xf9)
    c.branch("ge", "function_native")
    c.raw("6e f4 7e f8")
    c.pair(12, 14)
    c.sp(-16)
    c.raw("1a ae")
    c.imm(0, -0xe0)
    c.slot(0, 12, True)
    c.mov(0, 1)
    c.slot(0, 13, True)
    c.slot(8, 0, True, True)
    c.slot(10, 2, True)
    c.mem(0, 12, word=True, disp=6)
    c.slot(0, 4, True, True)
    c.mem(0, 12, disp=8)
    c.slot(0, 6, True)
    c.mem(0, 12, word=True, disp=10)
    c.slot(0, 8, True, True)
    c.mov(0, 0)
    c.slot(0, 10, True)
    c.pair(2, 14)
    c.call("command")
    c.sp(16)
    c.raw("3e f8 2e f4")
    c.pair(4, 0)
    c.jump(0xc72ce)
    c.label("function_native")
    c.raw("5b 70 00 51")
    c.jump(0xc7202)

    # The root has already resolved its depth slice but has not classified/fetched.
    c.hook(0xcd696, "85 f0 a0 82", "statement")
    c.label("statement")
    c.mem(0, 8, word=True, bank=10)
    c.mem(2, 8, bank=10, disp=2)
    c.mem(3, 0, bank=2)
    c.cmp(3, 0xf9)
    c.cond("ne", "statement_native")
    c.mem(3, 0, bank=2, disp=1)
    c.cmp(3, 0xe0)
    c.cond("lt", "statement_native")
    c.cmp(3, 0xf9)
    c.cond("ge", "statement_native")
    for name in (name for name in TOKEN_NAMES if name in FUNCTIONS):
        c.cmp(3, TOKENS[name] & 255)
        c.cond("eq", "statement_expression")
    c.slot(0, 14, word=True)
    c.mov(2, 1)
    c.mem(2, 0, True, disp=0x26)
    c.raw("6e f4 7e f8")
    c.pair(12, 14)
    c.sp(-16)
    c.raw("1a ae")
    c.imm(3, -0xe0)
    c.slot(3, 12, True)
    c.mov(0, 0)
    c.slot(0, 13, True)
    c.slot(8, 0, True, True)
    c.slot(10, 2, True)
    for target, source in ((4, 6), (8, 10)):
        c.mem(0, 12, word=True, disp=source)
        c.slot(0, target, True, True)
        c.mem(0, 12, disp=source + 2)
        c.slot(0, target + 2, True)
    c.pair(2, 14)
    c.call("command")
    c.sp(16)
    c.raw("3e f8 2e f4")
    c.rr(4, 0)
    c.jump(0xcd7ca)
    c.label("statement_expression")
    c.mov_er(0, 2)
    c.jump(0xcd69e)
    c.label("statement_native")
    c.raw("85 f0 a0 82")
    c.jump(0xcd69a)


def _command(c):
    c.label("command")
    c.raw("ce f8 6e f4 7e f8")
    c.pair(12, 2)
    c.raw("1a a0")
    c.mov_er(2, STACK_LOW + _FRAME + 900)
    c.raw("27 f0")
    c.cond("lt", "command_no_stack")
    c.sp(-_FRAME)
    c.raw("1a ae")
    for target, source in ((_P, 0), (_T, 4), (_OUT, 8)):
        c.mem(0, 12, word=True, disp=source)
        c.slot(0, target, True, True)
        c.mem(0, 12, disp=source + 2)
        c.slot(0, target + 2, True)
    c.mem(0, 12, disp=12)
    c.slot(0, _TOKEN, True)
    c.mem(0, 12, disp=13)
    c.slot(0, _FUNC, True)
    c.mov_er(0, 0x8000)
    c.addr(2, _MATH)
    c.mov_er(4, 112)
    c.call("near_copy")
    c.absolute(0, 0x8086, word=True)
    c.slot(0, _WORK, True, True)
    c.addr(2, _ARGS)
    c.mov_er(4, 28)
    c.mov(0, 0)
    c.label("command_clear")
    c.mem(0, 2, True)
    c.add(2, 1)
    c.add(4, -1)
    c.branch("ne", "command_clear")
    c.slot(0, _INDEX, True)
    c.call("cursor")
    c.slot(0, _ORIGIN, True, True)
    c.slot(2, _ORIGIN + 2, True)
    c.slot(3, _FUNC)
    c.cmp(3, 0)
    c.branch("ne", "command_cached")
    c.slot(0, _T, word=True)
    c.slot(2, _T + 2)
    c.mov(3, 1)
    c.mem(3, 0, True, bank=2)
    c.call("fetch")
    c.jump("command_ready")
    c.label("command_cached")
    c.slot(0, _ORIGIN, word=True)
    c.add(0, -2)
    c.slot(0, _ORIGIN, True, True)
    c.label("command_ready")
    c.slot(0, _TOKEN)
    c.cmp(0, 23)
    c.cond("eq", "command_asm")
    c.cmp(0, 24)
    c.cond("eq", "syntax")
    c.mov(1, 0)
    c.ref(2, "arg_counts")
    c.raw("06 f2")
    c.mem(0, 2, segment=15)
    c.slot(0, _COUNT, True)
    c.call("fetch_spaces")
    c.slot(3, _FUNC)
    c.cmp(3, 0)
    c.branch("eq", "command_arguments")
    c.cmp(0, 0x28)
    c.cond("ne", "syntax")
    c.call("fetch_spaces")
    c.label("command_arguments")
    c.slot(3, _COUNT)
    c.cmp(3, 0)
    c.cond("eq", "command_end_args")
    c.label("argument")
    c.slot(0, _TOKEN)
    c.cmp(0, 21)
    c.branch("ne", "argument_number")
    c.slot(0, _INDEX)
    c.cmp(0, 2)
    c.cond("eq", "argument_text")
    c.label("argument_number")
    # Evaluator consumes the current cached first token exactly once.
    c.mov_er(0, 0)
    c.push(0)
    c.push(0)
    c.addr(0, _NUMBER)
    c.push(0)
    c.slot(0, _T + 2)
    c.mov(1, 0)
    c.push(0)
    c.slot(0, _T, word=True)
    c.push(0)
    c.slot(0, _P, word=True)
    c.slot(2, _P + 2)
    c.slot(3, _FUNC)
    c.cmp(3, 0)
    c.branch("eq", "argument_statement")
    c.call("evaluate_argument")
    c.jump("argument_evaluated")
    c.label("argument_statement")
    c.call(EVALUATE)
    c.label("argument_evaluated")
    c.sp(10)
    c.cmp(0, 1)
    c.cond("ne", "argument_native_error")
    c.slot(0, _TOKEN)
    c.mov(1, 0)
    c.mov_er(2, 6)
    c.raw("24 f0")  # MUL ER0,R2; six type bytes per command.
    c.slot(2, _INDEX)
    c.mov(3, 0)
    c.raw("26 f0")
    c.ref(2, "arg_types")
    c.raw("06 f2")
    c.mem(2, 2, segment=15)
    c.mov(3, 0)
    c.slot(4, _INDEX)
    c.mov(5, 0)
    c.raw("2b 95 2a 94")
    c.addr(0, _ARGS)
    c.raw("06 f4")
    c.addr(0, _NUMBER)
    c.call(NUMBER_TO_INTEGER_ADDRESS)
    c.pair(0, 0)
    c.cond("ne", "command_error")
    c.label("argument_done")
    c.slot(0, _INDEX)
    c.imm(0, 1)
    c.slot(0, _INDEX, True)
    c.slot(1, _COUNT)
    c.rr(0, 1, 7)
    c.cond("eq", "command_end_args")
    c.call("cached")
    c.cmp(0, 0x29)
    c.branch("ne", "argument_comma")
    c.slot(0, _TOKEN)
    c.cmp(0, 4)
    c.cond("eq", "command_end_args")
    c.label("argument_comma")
    c.call("cached")
    c.cmp(0, 0x2c)
    c.cond("ne", "syntax")
    c.call("fetch_spaces")
    c.jump("argument")
    c.label("command_end_args")
    c.call("cached")
    c.slot(3, _FUNC)
    c.cmp(3, 0)
    c.branch("eq", "command_boundary")
    c.cmp(0, 0x29)
    c.cond("ne", "syntax")
    c.call("fetch")
    c.jump("command_dispatch")
    c.label("command_boundary")
    for char in (0, 0x0c, 0x0d, 0x3a):
        c.cmp(0, char)
        c.cond("eq", "command_dispatch")
    c.jump("syntax")
    c.label("command_dispatch")
    c.slot(0, _TOKEN)
    c.mov(1, 0)
    c.addr(2, _ARGS)
    c.addr(4, _VALUE)
    c.cmp(0, 15)
    c.branch("ne", "dispatch_not_flash")
    c.call(FLASH_WRITE_ADDRESS)
    c.jump("dispatch_return")
    c.label("dispatch_not_flash")
    c.cmp(0, 12)
    c.branch("eq", "dispatch_graphics")
    c.cmp(0, 16)
    c.branch("ge", "dispatch_graphics")
    c.call(MEMORY_ADDRESS)
    c.jump("dispatch_return")
    c.label("dispatch_graphics")
    c.call(GRAPHICS_ADDRESS)
    c.label("dispatch_return")
    c.pair(0, 0)
    c.cond("ne", "command_error")
    c.addr(0, _VALUE)
    c.addr(2, _NUMBER)
    c.call(INTEGER_TO_NUMBER_ADDRESS)
    c.pair(0, 0)
    c.cond("ne", "command_error")
    c.call("copy_result")
    c.mov_er(0, 1)
    c.jump("command_out")

    c.label("argument_text")
    c.call("cached")
    c.cmp(0, 0x22)
    c.cond("ne", "syntax")
    c.mov_er(8, 0)
    c.label("text_char")
    c.call("fetch")
    c.cmp(0, 0x22)
    c.branch("eq", "text_end")
    c.cmp(0, 0x20)
    c.cond("lt", "syntax")
    c.cmp(0, 0x60)
    c.cond("ge", "syntax")
    c.cmp(8, 32)
    c.cond("ge", "syntax")
    c.addr(2, _TEXT)
    c.raw("86 f2")
    c.mem(0, 2, True)
    c.add(8, 1)
    c.jump("text_char")
    c.label("text_end")
    c.addr(2, _TEXT)
    c.raw("86 f2")
    c.mov(0, 0)
    c.mem(0, 2, True)
    c.addr(0, _TEXT)
    c.slot(0, _ARGS + 8, True, True)
    c.slot(8, _ARGS + 16, True, True)
    c.call("fetch_spaces")
    c.jump("argument_done")

    c.label("syntax")
    c.mov_er(0, 2)
    c.label("command_error")
    c.cmp(1, 1)
    c.branch("ne", "command_native_error")
    c.ref(0, "write_error")
    c.call("error_screen")
    c.mov_er(0, 6)
    c.label("command_native_error")
    c.slot(0, _VALUE, True, True)
    c.slot(0, _ORIGIN, word=True)
    c.slot(2, _ORIGIN + 2)
    c.call("set_cursor")
    c.slot(0, _VALUE, word=True)
    c.slot(2, _OUT + 2)
    c.mov(3, 0)
    c.push(2)
    c.slot(2, _OUT, word=True)
    c.push(2)
    c.call(ERROR_WRITE)
    c.sp(4)
    c.jump("command_out")
    c.label("argument_native_error")
    c.call("copy_result")
    c.mov_er(0, 0)
    c.label("command_out")
    c.slot(0, _VALUE, True, True)
    c.addr(0, _MATH)
    c.mov_er(2, 0x8000)
    c.mov_er(4, 112)
    c.call("near_copy")
    c.slot(0, _WORK, word=True)
    c.absolute(0, 0x8086, True, True)
    c.slot(0, _VALUE, word=True)
    c.sp(_FRAME)
    c.raw("3e f8 2e f4 8e f2")
    c.label("command_no_stack")
    c.mem(2, 12, disp=10)
    c.mov(3, 0)
    c.push(2)
    c.mem(2, 12, word=True, disp=8)
    c.push(2)
    c.mov_er(0, 6)
    c.call(ERROR_WRITE)
    c.sp(4)
    c.raw("3e f8 2e f4 8e f2")


def _evaluate_argument(c):
    # C7B6E's private stacks with a native caller-owned argument sentinel.
    # The caller has already fetched the first token. Its result buffer is
    # near RAM, so C701E can write there directly without a second 20B copy.
    # Descriptor/value/operator storage is 4 + 102 + 28 bytes, as at C7B88.
    c.label("evaluate_argument")
    c.raw("ce f8 5e fe 1a ae")
    c.sp(-134)
    c.raw("6e f8 5e fc 5e f4")
    c.pair(8, 0)
    c.rr(10, 2)
    c.mov(0, 0)
    c.slot(0, -130, True)
    c.mov(0, 1)
    c.slot(0, -28, True)
    c.mov(0, EVALUATE_ARGUMENT_SENTINEL)
    c.slot(0, -26, True)
    c.addr(0, -130)
    c.slot(0, -134, True, True)
    c.addr(0, -28)
    c.slot(0, -132, True, True)
    c.call(0x06298)
    c.mov_er(0, EVALUATE_ARGUMENT_FLAGS)
    c.push(0)
    c.addr(0, -134)
    c.push(0)
    c.slot(0, 10, word=True)
    c.push(0)
    c.slot(0, 8)
    c.mov(1, 0)
    c.push(0)
    c.slot(0, 6, word=True)
    c.push(0)
    c.pair(0, 8)
    c.rr(2, 10)
    c.call(EVALUATE_CORE)
    c.sp(10)
    c.mov(1, 0)
    c.raw("1e f4 1e fc 2e f8 ea a1 1e fe 8e f2")


def _cursor(c):
    c.label("near_copy")
    c.mem(6, 0)
    c.mem(6, 2, True)
    c.add(0, 1)
    c.add(2, 1)
    c.add(4, -1)
    c.branch("ne", "near_copy")
    c.ret()
    c.label("cursor")
    c.slot(2, _P + 2)
    c.slot(0, _P, word=True)
    c.mem(3, 0, bank=2, disp=2)
    c.mem(0, 0, word=True, bank=2)
    c.rr(2, 3)
    c.ret()
    c.label("set_cursor")
    c.slot(4, _P, word=True)
    c.slot(3, _P + 2)
    c.mem(0, 4, True, True, bank=3)
    c.mem(2, 4, True, bank=3, disp=2)
    c.ret()
    c.label("fetch_spaces")
    c.raw("ce f8")
    c.label("fetch_spaces_loop")
    c.call("fetch")
    c.cmp(0, 0x20)
    c.branch("eq", "fetch_spaces_loop")
    c.raw("8e f2")
    c.label("fetch")
    c.raw("ce f8")
    c.slot(0, _P + 2)
    c.mov(1, 0)
    c.push(0)
    c.slot(0, _P, word=True)
    c.push(0)
    c.slot(0, _T, word=True)
    c.slot(2, _T + 2)
    c.call(TOKEN_FETCH)
    c.sp(4)
    c.call("cached")
    c.raw("8e f2")
    c.label("cached")
    c.slot(2, _T + 2)
    c.slot(0, _T, word=True)
    c.mem(0, 0, bank=2)
    c.ret()
    c.label("copy_result")
    c.raw("ce f8")
    c.mov_er(0, 0)
