def _templates():
    groups = []
    for _, entries in CATEGORIES:
        group = []
        for kind, _, name in entries:
            text = re.sub(r"\b(XR|QR|ER|R)\b", r"\g<1>0", name)
            text = text.replace("ADDR", "0").replace("D[", "0[")
            text = text.replace("#", "#0").replace(".B", ".0")
            if kind in (14, 15):
                text += " LABEL"
            elif kind == 16:
                text += " 0"
            group.append((name, text.encode("ascii")))
        groups.append(group)
    groups[1].append(("MOV ER,#", b"MOV ER0,#0"))
    return groups


