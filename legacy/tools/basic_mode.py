    def string(value):
        value = value.encode("ascii") if isinstance(value, str) else value
        if value not in strings:
            strings[value] = f"text_{len(strings)}"
        return strings[value]

    def table(label, values):
        if len(c.data) & 1:
            c.db(0)
        c.label(label)
        for value in values:
            c.pointer(string(value))

    table("names", TOKEN_NAMES)
    c.label("arg_counts")
    c.data.extend(len(types) for types in ARGUMENT_TYPES)
    c.label("arg_types")
    for types in ARGUMENT_TYPES:
        c.data.extend((*types, *(0 for _ in range(6 - len(types)))))
    table("nx_page_name", ("NX",))
    table("nx_category_names", (name for name, _ in NX_CATEGORIES))
    for index, (_, names) in enumerate(NX_CATEGORIES):
        table(f"nx_items_{index}", names)
        c.label(f"nx_tokens_{index}")
        c.data.extend(TOKENS[name] & 255 for name in names)
    table("block_categories_names", ("OP", "REG", "SYM", "BLOCK"))
    table("op_categories", (name for name, _ in CATEGORIES))
    for key in ("regs", "symbols", "directives"):
        table("block_" + key, (name for name, _ in groups[key]))
        table("block_" + key + "_text", (text for _, text in groups[key]))
    for index, entries in enumerate(groups["ops"]):
        table(f"op_{index}", (name for name, _ in entries))
        table(f"op_{index}_text", (text for _, text in entries))
    reasons = ("BAD OPERAND", "DUP LABEL", "NO LABEL", "BR RANGE",
               "ADDRESS RANGE", "NO ENDASM")
