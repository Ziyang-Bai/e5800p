"""On-calculator instruction browser and bounded RAM assembly queue.

The original S1 stream remains unchanged until the queued replacement is
preflighted and committed through the S2 journal. The queue holds up to 64
new instruction bytes, including instructions that cross 16-byte pages.
"""

from isa_menu import ISA_ENTRY_ADDRESS
from address_input import GOTO_ADDRESS
from page_editor import EDITOR_ADDRESS
from sector_journal import RECOVER_ADDRESS
from instruction_insert import BATCH_ADDRESS
from instruction_view import DETAIL_ADDRESS, VIEW_ADDRESS
from instruction_codec import LENGTH_ADDRESS
from u8_emit import Code

from flash_layout import PROGRAM_ADDRESS, SCANNER_ADDRESS
from ui_text import text_copy


# Offsets in the program-mode frame. The menu descriptor remains ten bytes.
_SOURCE, _NEXT, _BASE = 42, 44, 46
_MOD, _DONE = 48, 49
_OLD, _NEW, _BYTES = 64, 65, 66
_TOP, _DETAIL = 130, 132


def program_code():
    c = Code(PROGRAM_ADDRESS)

    def pair(dst, src):
        c.db((src << 4) | 5, 0xf0 | dst)

    def reg(dst, src):
        c.db(src << 4, 0x80 | dst)

    def ptr(offset):
        pair(2, 14)
        c.mov_er(10, offset)
        c.db(0xa6, 0xf2)

    def get(offset, register=0):
        ptr(offset)
        c.db(0x20, 0x90 | register)

    def put(offset, register=0):
        ptr(offset)
        c.db(0x21, 0x90 | register)

    def get_word(offset):
        get(offset)
        get(offset + 1, 1)

    def put_word(offset):
        put(offset)
        put(offset + 1, 1)

    def forward_if(condition, target):
        opposite = {"eq": "ne", "ne": "eq", "lt": "ge", "ge": "lt"}[condition]
        skip = f"skip_{len(c.fixups)}"
        c.branch(opposite, skip)
        c.jump(target)
        c.label(skip)

    def flash(pointer, register=0):
        c.db(8, 0xe3, pointer << 4, 0x90 | register)

    def font_begin():
        c.db(0x10, 0x90, 0xa0, 0x80)
        put(50)
        c.db(0x10, 0x90, 0xa2, 0x80)
        put(51)
        c.mov(0, 7)
        c.db(0x11, 0x90, 0xa0, 0x80)
        c.mov(0, 1)
        c.db(0x11, 0x90, 0xa2, 0x80)

    def font_end():
        get(51)
        c.db(0x11, 0x90, 0xa2, 0x80)
        get(50)
        c.db(0x11, 0x90, 0xa0, 0x80)

    def message(text):
        ptr(16)
        text_copy(c, text, 26)
        c.call('message')


    c.label('entry')
    c.raw('ce f8 6e f4 7e f8 5e fc 5e fe')
    c.raw('e0 e1 e0 e1 e0 e1 e0 e1 e0 e1 1a ae')  # 160-byte frame
    pair(0, 12)
    reg(2, 5)
    c.mov(3, 0)
    c.raw('26 f0')
    for offset in (_SOURCE, _NEXT, _BASE, _TOP):
        put_word(offset)
    c.mov(0, 0)
    put(_MOD)
    put(_OLD)
    put(_NEW)
    put(_DETAIL)
    c.call(RECOVER_ADDRESS)
    c.raw('00 70')
    c.branch('eq', 'draw')
    message('RECOVER ERROR')
    c.label('recover_key')
    c.call(SCANNER_ADDRESS)
    c.raw('fa 70')
    c.branch('ne', 'recover_key')
    c.jump('exit')

    c.label('draw')
    get(_DETAIL)
    c.raw('00 70')
    forward_if('ne', 'draw_detail')
    get_word(_TOP)
    pair(8, 0)
    get_word(_SOURCE)
    pair(2, 0)
    pair(0, 8)
    c.call(VIEW_ADDRESS)
    c.raw('ff 71')  # R1 == ff means an invalid opcode boundary
    forward_if('eq', 'bad_instruction')
    pair(0, 2)
    put_word(_TOP)
    c.jump('drawn')
    c.label('draw_detail')
    get_word(_SOURCE)
    pair(2, 0)
    c.call(DETAIL_ADDRESS)
    c.raw('ff 71')
    forward_if('eq', 'bad_instruction')
    c.label('drawn')
    get(_DETAIL)
    c.raw('00 70')
    forward_if('ne', 'input')
    get(_NEW)
    c.raw('00 70')
    forward_if('eq', 'input')
    # Queue status replaces the bottom help row while edits are pending.
    c.call('queue_line')
    c.label('input')
    ptr(_MOD)
    c.raw('10 90 8d 80 21 90')  # snapshot ALPHA/SHIFT before key scan
    c.call(SCANNER_ADDRESS)
    c.raw('02 70 7d 51')  # FUNCTION logical key event: open nX-U8 OPTN picker.
    forward_if('eq', 'function')
    c.raw('00 70')
    c.branch('eq', 'input')
    for key in (0xfc, 0xfd):
        c.db(key, 0x70)
        forward_if('eq', 'view_key')
    for key, label in ((0xfa, 'exit_key'), (0xfb, 'confirm'),
                       (0xff, 'previous'), (0xfe, 'following')):
        c.db(key, 0x70)
        forward_if('eq', label)
    c.jump('input')
    c.label('function')
    get(_MOD)
    c.raw('08 20 00 70')
    forward_if('ne', 'goto')
    c.jump('select')
    c.label('view_key')
    reg(6, 0)
    get(_MOD)
    c.raw('08 20 00 70')
    forward_if('ne', 'switch_view')
    c.raw('fc 76')
    forward_if('eq', 'detail_back')
    c.mov(0, 1)
    put(_DETAIL)
    c.jump('draw')
    c.label('detail_back')
    c.mov(0, 0)
    put(_DETAIL)
    c.jump('draw')
    c.label('switch_view')
    c.raw('10 90 8d 80 f3 20 11 90 8d 80')
    get(_NEW)
    c.raw('00 70')
    forward_if('ne', 'save_first')
    c.mov(0, 0)
    put(_DETAIL)
    get_word(_NEXT)
    c.call(EDITOR_ADDRESS)
    reg(7, 2)
    put_word(_NEXT)
    put_word(_SOURCE)
    put_word(_TOP)
    c.raw('01 77')
    forward_if('eq', 'exit')
    c.raw('02 77')
    forward_if('eq', 'select')
    c.jump('draw')
    c.label('goto')
    c.raw('10 90 8d 80 f3 20 11 90 8d 80')
    get(_NEW)
    c.raw('00 70')
    forward_if('ne', 'save_first')
    c.mov(0, 0)
    put(_DETAIL)
    get_word(_NEXT)
    c.mov(2, 1)
    c.call(GOTO_ADDRESS)
    c.raw('00 72')
    forward_if('eq', 'draw')
    put_word(_NEXT)
    put_word(_SOURCE)
    put_word(_TOP)
    c.jump('draw')

    c.label('confirm')
    get(_MOD)
    c.raw('08 20 00 70')
    forward_if('eq', 'check_alpha')
    c.jump('commit')
    c.label('check_alpha')
    get(_MOD)
    c.raw('04 20 00 70')
    forward_if('eq', 'select')
    get(_NEW)
    c.raw('00 70')
    forward_if('ne', 'save_first')
    c.mov_er(0, 0x4000)
    c.mov(2, 8)
    c.raw('2f 90 00 90 ff 70')
    forward_if('eq', 'empty')
    c.raw('6e f4 7e f8')
    c.call(0x84000)
    c.raw('3e f8 2e f4')
    c.jump('draw')
    c.label('empty')
    message('EMPTY PROGRAM')
    c.jump('input')

    c.label('previous')
    get(_NEW)
    c.raw('00 70')
    forward_if('ne', 'save_first')
    get_word(_NEXT)
    c.mov_er(2, 0x4000)
    c.raw('27 f0')
    forward_if('eq', 'draw')
    c.mov_er(0, 0x4000)
    put_word(_BASE)
    c.label('scan_back')
    get_word(_BASE)
    pair(2, 0)
    c.call(LENGTH_ADDRESS)
    c.raw('ff 71')
    forward_if('eq', 'bad_instruction')
    reg(6, 0)
    get_word(_BASE)
    reg(2, 6)
    c.mov(3, 0)
    c.raw('26 f0')
    pair(4, 0)
    get_word(_NEXT)
    c.raw('07 f4')
    forward_if('ge', 'back_ready')
    pair(0, 4)
    put_word(_BASE)
    c.jump('scan_back')
    c.label('back_ready')
    get_word(_BASE)
    put_word(_NEXT)
    put_word(_SOURCE)
    c.jump('draw')

    c.label('following')
    get(_NEW)
    c.raw('00 70')
    forward_if('ne', 'save_first')
    get_word(_NEXT)
    pair(2, 0)
    c.call(LENGTH_ADDRESS)
    c.raw('ff 71')
    forward_if('eq', 'bad_instruction')
    reg(6, 0)
    get_word(_NEXT)
    reg(2, 6)
    c.mov(3, 0)
    c.raw('26 f0')
    c.mov_er(2, 0x5ff0)
    c.raw('27 f0')
    forward_if('ge', 'draw')
    put_word(_NEXT)
    put_word(_SOURCE)
    c.jump('draw')

    c.label('select')
    c.mov(0, 0)
    put(_DETAIL)
    get_word(_SOURCE)
    put_word(_TOP)
    get(_NEW)
    c.raw('00 70')
    forward_if('ne', 'selected_source')
    get_word(_SOURCE)
    put_word(_BASE)
    c.label('selected_source')
    get_word(_SOURCE)
    pair(2, 0)
    c.call(LENGTH_ADDRESS)
    c.raw('ff 71')
    forward_if('eq', 'bad_instruction')
    put(_DONE)
    # The ISA menu expects the old instruction in a 16-byte RAM page. Put
    # its first two bytes at the virtual cursor for old-length classification.
    get_word(_NEXT)
    reg(7, 0)
    c.raw('0f 27')  # virtual offset
    pair(2, 14)
    c.mov(0, 16)
    c.label('clear_page')
    c.mov(6, 0xff)
    c.db(0x21, 0x96, 0x81, 0xe2, 0xff, 0x10)
    c.branch('ne', 'clear_page')
    get_word(_SOURCE)
    pair(8, 0)
    get_word(_NEXT)
    reg(7, 0)
    c.raw('0f 27')
    c.mov(6, 2)
    c.label('fill_page')
    pair(2, 14)
    reg(0, 7)
    c.mov(1, 0)
    c.raw('06 f2')
    flash(8)
    c.raw('21 90 81 e8 01 17 ff 16')
    c.branch('ne', 'fill_page')
    get_word(_NEXT)
    c.raw('f0 20')  # virtual page base
    pair(2, 0)
    ptr(32)
    pair(6, 2)
    get_word(_NEXT)
    reg(5, 0)
    c.raw('0f 25 f0 20')
    pair(2, 0)
    pair(0, 14)
    c.call(ISA_ENTRY_ADDRESS)
    c.raw('00 70')
    forward_if('ne', 'draw')
    get_word(_NEXT)
    get(33, 2)
    c.mov(3, 0)
    c.raw('26 f0')
    c.mov_er(2, 0x5ff0)
    c.raw('27 f0')
    forward_if('lt', 'new_space')
    forward_if('ne', 'space_error')
    c.label('new_space')
    get_word(_SOURCE)
    get(_DONE, 2)
    c.mov(3, 0)
    c.raw('26 f0')
    c.mov_er(2, 0x5ff0)
    c.raw('27 f0')
    forward_if('lt', 'source_space')
    forward_if('ne', 'space_error')
    c.label('source_space')
    get(33)
    reg(7, 0)
    get(_NEW)
    c.raw('71 80')  # R0 += new instruction length in R7
    c.raw('41 70')
    forward_if('ge', 'commit_then_append')
    get(_OLD)
    get(_DONE, 7)
    c.mov(1, 0)
    c.raw('71 80 00 61 00 71')  # old span plus next old instruction
    forward_if('ne', 'commit_then_append')
    c.raw('ff 70')
    forward_if('lt', 'append')
    c.jump('commit_then_append')
    c.label('commit_then_append')
    c.call('write_batch')
    c.raw('00 70')
    forward_if('ne', 'write_error')
    get_word(_NEXT)
    put_word(_SOURCE)
    put_word(_BASE)
    put_word(_TOP)
    c.mov(0, 0)
    put(_OLD)
    put(_NEW)

    c.label('append')
    get(_OLD)
    get(_DONE, 7)
    c.raw('71 80')
    put(_OLD)
    get(_NEW)
    get(33, 7)
    c.raw('71 80')
    put(_NEW)
    get(_NEW)
    get(33, 7)
    c.raw('78 80')  # offset before this instruction
    reg(6, 0)
    pair(8, 14)
    c.mov_er(0, 34)
    c.raw('06 f8')  # ER8 = descriptor bytes
    pair(10, 14)
    c.mov_er(0, _BYTES)
    c.raw('06 fa')
    reg(0, 6)
    c.mov(1, 0)
    c.raw('06 fa')  # ER10 = end of queued bytes
    c.label('copy_instruction')
    pair(2, 8)
    c.raw('20 90')
    pair(2, 10)
    c.raw('21 90 81 e8 81 ea ff 17')
    c.branch('ne', 'copy_instruction')
    c.label('copied')
    get_word(_SOURCE)
    get(_DONE, 2)
    c.mov(3, 0)
    c.raw('26 f0')
    put_word(_SOURCE)
    put_word(_TOP)
    get_word(_NEXT)
    get(33, 2)
    c.mov(3, 0)
    c.raw('26 f0')
    put_word(_NEXT)
    c.jump('draw')

    c.label('commit')
    get(_NEW)
    c.raw('00 70')
    forward_if('eq', 'draw')
    c.call('write_batch')
    c.raw('00 70')
    forward_if('ne', 'write_error')
    get_word(_NEXT)
    put_word(_SOURCE)
    put_word(_BASE)
    put_word(_TOP)
    c.mov(0, 0)
    put(_OLD)
    put(_NEW)
    c.jump('draw')

    c.label('write_batch')
    c.raw('ce f8')
    ptr(_OLD)
    pair(6, 2)
    get_word(_BASE)
    pair(2, 0)
    c.call(BATCH_ADDRESS)
    c.raw('8e f2')

    c.label('exit_key')
    get(_DETAIL)
    c.raw('00 70')
    forward_if('ne', 'detail_back')
    get(_NEW)
    c.raw('00 70')
    forward_if('eq', 'exit')
    message('EXE SAVE EXIT NO')
    c.label('confirm_exit')
    c.call(SCANNER_ADDRESS)
    c.raw('fb 70')
    forward_if('eq', 'commit_and_exit')
    c.raw('fa 70')
    c.branch('ne', 'confirm_exit')
    get_word(_BASE)
    put_word(_NEXT)
    c.jump('exit')
    c.label('commit_and_exit')
    c.call('write_batch')
    c.raw('00 70')
    forward_if('ne', 'write_error')
    c.jump('exit')
    c.label('bad_instruction')
    message('BAD OPCODE')
    c.call('queue_line')
    c.jump('input')
    c.label('save_first')
    message('SAVE FIRST')
    c.jump('input')
    c.label('write_error')
    message('WRITE ERROR')
    c.jump('input')
    c.label('space_error')
    message('PROGRAM FULL')
    c.jump('input')
    c.label('queue_line')
    c.raw('ce f8')
    get_word(_NEXT)
    reg(8, 0)
    reg(9, 1)
    get(_NEW, 6)
    ptr(16)
    text_copy(c, 'NEXT ', 26)
    ptr(21)
    for r, bits in ((9, 4), (9, 0), (8, 4), (8, 0)):
        reg(0, r)
        if bits:
            c.db(0x4c, 0x90)
        c.db(0x0f, 0x20)
        c.call('hex_digit')
        c.raw('21 90 81 e2')
    text_copy(c, ' Q', 17)
    ptr(27)
    reg(8, 6)
    for bits in (4, 0):
        reg(0, 8)
        if bits:
            c.db(0x4c, 0x90)
        c.db(0x0f, 0x20)
        c.call('hex_digit')
        c.raw('21 90 81 e2')
    c.mov(0, 0)
    c.raw('21 90')
    font_begin()
    ptr(16)
    c.mov(0, 0)
    c.mov(1, 25)
    c.call(0x041da)
    ptr(16)
    text_copy(c, 'P', 26)
    ptr(16)
    c.mov(0, 90)
    c.mov(1, 25)
    c.call(0x041da)
    c.call(0x043be)
    font_end()
    c.raw('8e f2')

    c.label('hex_digit')
    c.db(0x0a, 0x70)
    forward_if('ge', 'hex_letter')
    c.db(ord('0'), 0x10)
    c.raw('1f fe')
    c.label('hex_letter')
    c.db(ord('A') - 10, 0x10)
    c.raw('1f fe')

    c.label('message')
    c.raw('ce f8')
    c.call(0x0409a)
    font_begin()
    ptr(16)
    c.mov(0, 0)
    c.mov(1, 9)
    c.call(0x041da)
    ptr(16)
    text_copy(c, 'P', 26)
    ptr(16)
    c.mov(0, 90)
    c.mov(1, 25)
    c.call(0x041da)
    c.call(0x043be)
    font_end()
    c.raw('8e f2')

    c.label('exit')
    get_word(_NEXT)
    pair(2, 0)
    c.raw('20 e1 20 e1 20 e1 20 e1 20 e1 1e fe 1e fc 3e f8 2e f4 8e f2')
    return (PROGRAM_ADDRESS - 0x80000, c.build())
