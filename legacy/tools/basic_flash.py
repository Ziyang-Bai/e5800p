"""Stream bytes to NOR Flash; erase commands and storage ownership belong to callers.

Replace: ER0=offset, ER2=count, ER4=bank-F reader, ER6=state, R8=bank.
The reader receives ER0=state/R2=reset or next and returns R0=byte/R1=status.
Both entries preserve ER2, XR4 and R8..R15. No bank is used as a backup.
"""

from u8_emit import Code
from basic_native import STACK_LOW
from basic_memory import READ_RANGE_ADDRESS

FLASH_REPLACE_ADDRESS = 0xf6e68
FLASH_WRITE_ADDRESS = FLASH_REPLACE_ADDRESS + 4
FLASH_STOP = 0xf7e68
WRITE_ERROR = 0x100

_D, _N, _READER, _STATE, _SEG, _CHANGED, _BUF = 0, 2, 4, 6, 8, 9, 16


class _Flash(Code):
    def pair(self, dst, src):
        self.db((src << 4) | 5, 0xf0 | dst)

    def byte(self, reg, slot, store=False):
        self.db(0xe9 if store else 0xe8, 0x90 | reg)
        self.word(slot)

    def word_slot(self, reg, slot, store=False):
        self.db(0xe9 if store else 0xe8, 0xa0 | reg)
        self.word(slot)

    def ptr(self, reg, slot):
        self.pair(reg, 14)
        self.db(0x80 | slot, 0xe0 | reg)

    def go(self, condition, target):
        label = f"near_{len(self.fixups)}"
        self.branch({"eq": "ne", "ne": "eq", "lt": "ge", "ge": "lt"}[condition], label)
        self.jump(target)
        self.label(label)

    def must(self, target="failed"):
        self.raw("05 f0")
        self.go("ne", target)


def flash_code():
    c = _Flash(FLASH_REPLACE_ADDRESS)
    c.jump("replace")
    c.jump("write")
    c.label("replace")
    c.raw("ce f8 5e f2 6e f4 7e f8")
    c.raw("e0 e1 1a ae")
    c.word_slot(0, _D, True)
    c.word_slot(2, _N, True)
    c.word_slot(4, _READER, True)
    c.word_slot(6, _STATE, True)
    c.byte(8, _SEG, True)
    c.raw("1a a0")
    c.mov_er(2, STACK_LOW + 256)
    c.raw("27 f0")
    c.go("lt", "failed")
    c.word_slot(2, _N)
    c.raw("25 f2")
    c.go("eq", "success")
    c.db(8, 0x78)
    c.go("lt", "failed")
    c.db(16, 0x78)
    c.go("ge", "failed")
    c.word_slot(0, _D)
    c.raw("ff e2 26 f0 80 82 00 62")
    c.db(16, 0x72)
    c.go("ge", "failed")
    c.mov(0, 0)
    c.byte(0, _CHANGED, True)
    c.mov(2, 0)
    c.call("reader")
    c.raw("00 71")
    c.go("ne", "failed")
    c.word_slot(8, _D)
    c.word_slot(10, _N)
    c.byte(12, _SEG)
    c.label("preflight")
    c.mov(2, 1)
    c.call("reader")
    c.raw("00 71")
    c.go("ne", "failed")
    c.raw("00 84 cf 90 80 92 47 82")
    c.branch("eq", "same")
    c.mov(0, 1)
    c.byte(0, _CHANGED, True)
    c.label("same")
    # NOR programming changes 1 bits to 0; an erase is an explicit caller operation.
    c.raw("42 82 47 82")
    c.go("ne", "failed")
    c.raw("81 e8")
    c.branch("ne", "preflight_next")
    c.db(1, 0x1c)
    c.label("preflight_next")
    c.raw("ff ea a5 fa")
    c.go("ne", "preflight")
    c.call("reader_end")
    c.must()
    c.byte(0, _CHANGED)
    c.raw("00 70")
    c.go("eq", "success")
    c.mov(2, 0)
    c.call("reader")
    c.raw("00 71")
    c.go("ne", "failed")
    c.label("chunk")
    c.word_slot(8, _D)
    c.word_slot(10, _N)
    c.ptr(12, _BUF)
    c.mov_er(6, 0)
    c.label("fill")
    c.mov(2, 1)
    c.call("reader")
    c.raw("00 71")
    c.go("ne", "failed")
    c.raw("c1 90 81 ec 81 e6 81 e8 ff ea a5 fa")
    c.branch("eq", "program_chunk")
    c.raw("85 f8")
    c.branch("eq", "program_chunk")
    c.db(16, 0x76)
    c.branch("lt", "fill")
    c.label("program_chunk")
    c.word_slot(0, _D)
    c.byte(2, _SEG)
    c.mov(3, 0)
    c.ptr(4, _BUF)
    c.call("program")
    c.must()
    c.word_slot(10, _N, True)
    c.word_slot(10, _D)
    c.word_slot(8, _D, True)
    c.byte(12, _SEG)
    c.raw("85 f8")
    c.branch("ne", "verify")
    c.raw("c0 80 01 10")
    c.byte(0, _SEG, True)
    c.label("verify")
    c.raw("40 90 cf 90 a0 92 27 80")
    c.go("ne", "failed")
    c.raw("81 e4 81 ea ff e6 65 f6")
    c.branch("ne", "verify")
    c.word_slot(0, _N)
    c.raw("05 f0")
    c.go("ne", "chunk")
    c.call("reader_end")
    c.must()
    c.label("success")
    c.mov_er(0, 0)
    c.jump("exit")
    c.label("failed")
    c.mov_er(0, 0xffff)
    c.label("exit")
    c.raw("20 e1 3e f8 2e f4 1e f2 8e f2")

    c.label("reader")
    c.raw("ce f8 5e f8")
    c.word_slot(0, _STATE)
    c.word_slot(8, _READER)
    c.raw("83 f0 1e f8 8e f2")
    c.label("reader_end")
    c.raw("ce f8")
    c.mov(2, 1)
    c.call("reader")
    c.raw("01 71")
    c.branch("ne", "reader_long")
    c.mov_er(0, 0)
    c.raw("8e f2")
    c.label("reader_long")
    c.mov_er(0, 0xffff)
    c.raw("8e f2")

    c.label("program")
    c.raw("ce f8 6e f4 7e f8 5e f6")
    c.mov(8, 0)
    c.raw("4e f8 5e f4")
    c.call(0x4e86)
    c.raw("06 e1 3e f8 2e f4 8e f2")

    c.label("write")
    c.raw("ce f8 5e f2 6e f4 7e f8")
    c.pair(8, 2)
    c.raw("1a a0")
    c.mov_er(2, STACK_LOW + 384)
    c.raw("27 f0")
    c.go("lt", "write_stack")
    c.raw("e8 e1 1a ae")
    c.word_slot(4, 16, True)
    c.raw("88 a0 0a 00 05 f0")
    c.go("ne", "write_arg")
    c.raw("88 a0 02 00")
    c.mov_er(2, 16)
    c.raw("27 f0")
    c.go("ge", "write_arg")
    c.word_slot(0, 14, True)
    c.raw("82 90")
    c.word_slot(0, 12, True)
    c.raw("88 a2 06 00")
    c.mov_er(0, 256)
    c.raw("07 f2")
    c.go("ge", "write_arg")
    c.word_slot(2, 2, True)
    c.raw("88 a0 04 00")
    c.word_slot(0, 0, True)
    c.raw("88 a4 08 00")
    c.word_slot(4, 4, True)
    c.call(READ_RANGE_ADDRESS)
    c.must("write_arg")
    c.word_slot(0, 12)
    c.word_slot(2, 4)
    reader_fix = len(c.data)
    c.mov(4, 0)
    c.mov(5, 0)
    c.pair(6, 14)
    c.word_slot(8, 14)
    c.call(FLASH_REPLACE_ADDRESS)
    c.must("write_failed")
    c.word_slot(4, 16)
    c.mov_er(0, 0)
    c.raw("41 90 81 e4 41 90 81 e4 41 90 81 e4 41 90")
    c.jump("write_exit")
    c.label("write_arg")
    c.mov_er(0, 4)
    c.jump("write_exit")
    c.label("write_failed")
    c.mov_er(0, WRITE_ERROR)
    c.label("write_exit")
    c.raw("18 e1 3e f8 2e f4 1e f2 8e f2")
    c.label("write_stack")
    c.mov_er(0, 6)
    c.raw("3e f8 2e f4 1e f2 8e f2")

    reader = c.address + len(c.data)
    c.label("ram_reader")
    c.raw("6e f4")
    c.pair(4, 0)
    c.raw("00 72")
    c.branch("ne", "ram_next")
    c.raw("42 90 49 a0 06 00 48 a0 02 00 49 a0 08 00 48 a0 04 00 49 a0 0a 00")
    c.mov_er(0, 0)
    c.jump("ram_out")
    c.label("ram_next")
    c.raw("48 a2 0a 00 25 f2")
    c.branch("eq", "ram_end")
    c.raw("48 a6 06 00 48 93 08 00 3f 90 60 90 81 e6 49 a6 06 00")
    c.branch("ne", "ram_count")
    c.raw("48 a2 08 00 81 e2 49 a2 08 00")
    c.label("ram_count")
    c.raw("48 a2 0a 00 ff e2 49 a2 0a 00")
    c.mov(1, 0)
    c.jump("ram_out")
    c.label("ram_end")
    c.mov(0, 0)
    c.mov(1, 1)
    c.label("ram_out")
    c.raw("2e f4 1f fe")
    code = bytearray(c.build())
    code[reader_fix] = reader & 255
    code[reader_fix + 2] = (reader >> 8) & 255
    if len(code) > FLASH_STOP - FLASH_REPLACE_ADDRESS:
        raise ValueError("BASIC Flash writer exceeds its allocation")
    return (FLASH_REPLACE_ADDRESS - 0x80000, bytes(code))
