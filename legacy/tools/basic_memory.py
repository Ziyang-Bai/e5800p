"""BASIC integer, hardware-mapped memory and returning far CALL primitives.

Dispatch: ER0=token index, ER2=near six LE32 arguments, ER4=LE32 result.
NUMBER_TO_INTEGER: ER0=near native20, ER2=0:uint8/1:uint16/2:uint20/
3:int16/4:uint24, ER4=near LE32 output (signed values are sign extended).
INTEGER_TO_NUMBER: ER0=near unsigned LE32, ER2=near native20 output.
READ_RANGE: ER0=offset, R2=8-bit segment, ER4=uint16 length, zero is empty.
All entries preserve XR4/R8..R15. Status is 0, 4 (argument), or 6
(stack); result buffers change only on success. Dispatch expects
width-normalized arguments; FLASHWRITE is dispatched by the caller.

Data accesses accept all 24-bit addresses, including SFRs; only complete
range overflow is rejected. Hardware determines read/write behavior.
CALL accepts any even 20-bit code address, without journal recovery.
Dispatch checks 276 bytes below entry SP, converters 64.
CALL's 168-byte owned frame excludes native/arbitrary user frames. Writers
must not overwrite the active stack or argument/result buffers. Called
code must balance SP and return with RT, preserving its execution level.
"""

from u8_emit import Code
from basic_native import STACK_LOW

MEMORY_ADDRESS = 0xfb530
NUMBER_TO_INTEGER_ADDRESS = 0xfb534
INTEGER_TO_NUMBER_ADDRESS = 0xfb538
READ_RANGE_ADDRESS = 0xfb53c
CALL_BRIDGE_ADDRESS = 0x80400
MEMORY_STOP = 0xfc530
DISPATCH_FRAME_SIZE = 28
CONVERTER_FRAME_SIZE = 32
CALL_FRAME_SIZE = 168  # Includes the bridge's four-byte target frame; excludes user code.
READ_RANGE_FRAME_SIZE = 2


class _Memory(Code):
    def __init__(self, address):
        super().__init__(address)
        self.seq = 0

    def pair(self, dst, src):
        self.db(src << 4 | 5, 0xf0 | dst)

    def rr(self, dst, src, op=0):
        self.db(src << 4 | op, 0x80 | dst)

    def imm(self, reg, value, op=0x10):
        self.db(value & 255, op | reg)

    def add(self, reg, value):
        while value:
            step = max(-64, min(63, value))
            self.db(0x80 | (step & 0x7f), 0xe0 | reg)
            value -= step

    def cmp(self, reg, value):
        self.imm(reg, value, 0x70)

    def cond(self, condition, label):
        self.seq += 1
        skip = f"skip_{self.seq}"
        self.branch({"eq": "ne", "ne": "eq", "lt": "ge", "ge": "lt"}[condition], skip)
        self.jump(label)
        self.label(skip)

    def mem(self, reg, ptr, store=False, word=False, bank=None, disp=None):
        if bank is None:
            self.raw("00 e3")
        else:
            self.db(bank << 4 | 15, 0x90)
        if disp is None:
            self.db(ptr << 4 | (2 if word else 0) | int(store), 0x90 | reg)
        else:
            self.db(ptr << 4 | 8 | int(store), (0xa0 if word else 0x90) | reg)
        if disp is not None:
            self.word(disp & 0xffff)

    def slot(self, reg, offset, store=False, word=False):
        self.mem(reg, 14, store, word, disp=offset)

    def arg(self, reg, index, high=False):
        self.mem(reg, 8, word=True, disp=index * 4 + (2 if high else 0))

    def absolute(self, reg, addr, store=False):
        self.raw("00 e3")
        self.db(0x10 | int(store), 0x90 | reg)
        self.word(addr)

    def shift(self, reg, count, kind=0xa):
        self.db(count << 4 | kind, 0x90 | reg)

    def ret(self):
        self.raw("1f fe")

    def converter(self, label, reverse=False):
        self.label(label)
        self.raw("ce f8 6e f4 7e f8")
        self.pair(8, 0)
        self.pair(12, 2 if reverse else 4)
        if not reverse:
            self.pair(10, 2)
        self.raw("1a a0")
        self.mov_er(2, STACK_LOW + 48)
        self.raw("27 f0")
        self.cond("lt", "conv_memory")
        self.raw("f0 e1 1a ae")


def _range(c):
    c.label("read_range")
    c.raw("5e f4")
    c.pair(4, 4)
    c.branch("eq", "range_ok")
    c.add(4, -1)
    c.raw("46 f0")
    c.imm(2, 0, 0x60)
    c.branch("lt", "range_bad")
    c.label("range_ok")
    c.mov_er(0, 0)
    c.branch("al", "range_out")
    c.label("range_bad")
    c.mov_er(0, 4)
    c.label("range_out")
    c.raw("1e f4")
    c.ret()


def _dispatch(c):
    c.label("dispatch")
    c.raw("ce f8 6e f4 7e f8")
    c.raw("03 a6 ce f1 5e f6")  # PSW, EA, then PSW in a word slot.
    c.pair(8, 2)
    c.pair(12, 4)
    c.rr(10, 0)
    c.raw("1a a0")
    c.mov_er(2, STACK_LOW + 256)
    c.raw("27 f0")
    c.cond("lt", "entry_memory")
    c.raw("f8 e1 1a ae")
    for token, label in ((0, "peek"), (1, "peek"), (2, "poke"), (3, "poke"),
                         (4, "call"), (5, "bit_and"), (6, "bit_or"),
                         (7, "bit_xor"), (8, "shift_left"), (9, "shift_right"),
                         (10, "inkey"), (11, "ticks"), (13, "copy"), (14, "fill")):
        c.cmp(10, token)
        c.cond("eq", label)
    c.jump("argument")

    for label, write in (("peek", False), ("poke", True)):
        c.label(label)
        c.rr(11, 10)
        c.imm(11, 1, 0x20)
        c.imm(11, 1)
        c.arg(0, 0)
        c.arg(2, 0, True)
        c.mov(4, 0)
        c.rr(4, 11)
        c.mov(5, 0)
        c.call("read_range")
        c.pair(0, 0)
        c.cond("ne", "argument")
        c.arg(4, 0)
        c.arg(6, 0, True)
        if write:
            c.arg(0, 1)
            c.mem(0, 4, True, bank=6)
            c.cmp(11, 1)
            c.branch("eq", "poke_done")
            c.add(4, 1)
            c.imm(6, 0, 0x60)
            c.mem(1, 4, True, bank=6)
            c.label("poke_done")
            c.jump("zero")
        else:
            c.mov_er(0, 0)
            c.mem(0, 4, bank=6)
            c.cmp(11, 1)
            c.branch("eq", "peek_done")
            c.add(4, 1)
            c.imm(6, 0, 0x60)
            c.mem(1, 4, bank=6)
            c.label("peek_done")
            c.jump("word_result")

    c.label("copy")
    c.arg(10, 2)
    c.pair(10, 10)
    c.cond("eq", "zero")
    c.arg(0, 1)
    c.arg(2, 1, True)
    c.pair(4, 10)
    c.call("read_range")
    c.pair(0, 0)
    c.cond("ne", "argument")
    c.arg(0, 0)
    c.arg(2, 0, True)
    c.call("read_range")
    c.pair(0, 0)
    c.cond("ne", "argument")
    c.arg(4, 0)
    c.arg(6, 0, True)
    c.arg(0, 1)
    c.arg(2, 1, True)
    c.rr(7, 2)
    c.pair(8, 0)
    c.mov(3, 0)
    c.rr(6, 7, 7)
    c.branch("lt", "copy_loop")
    c.branch("ne", "copy_reverse")
    c.raw("87 f4")
    c.branch("lt", "copy_loop")
    c.label("copy_reverse")
    c.add(10, -1)
    c.raw("a6 f4")
    c.imm(6, 0, 0x60)
    c.raw("a6 f8")
    c.imm(7, 0, 0x60)
    c.add(10, 1)
    c.mov(3, 1)
    c.label("copy_loop")
    c.mem(0, 8, bank=7)
    c.mem(0, 4, True, bank=6)
    c.add(10, -1)
    c.cond("eq", "zero")
    c.cmp(3, 0)
    c.branch("ne", "copy_back")
    c.add(4, 1)
    c.imm(6, 0, 0x60)
    c.add(8, 1)
    c.imm(7, 0, 0x60)
    c.branch("al", "copy_loop")
    c.label("copy_back")
    c.add(4, -1)
    c.imm(6, -1, 0x60)
    c.add(8, -1)
    c.imm(7, -1, 0x60)
    c.branch("al", "copy_loop")

    c.label("fill")
    c.arg(10, 1)
    c.pair(10, 10)
    c.cond("eq", "zero")
    c.arg(0, 0)
    c.arg(2, 0, True)
    c.pair(4, 10)
    c.call("read_range")
    c.pair(0, 0)
    c.cond("ne", "argument")
    c.arg(4, 0)
    c.arg(6, 0, True)
    c.arg(0, 2)
    c.label("fill_loop")
    c.mem(0, 4, True, bank=6)
    c.add(4, 1)
    c.imm(6, 0, 0x60)
    c.add(10, -1)
    c.branch("ne", "fill_loop")
    c.jump("zero")

    for label, opcode in (("bit_and", 2), ("bit_or", 3), ("bit_xor", 4)):
        c.label(label)
        c.arg(0, 0)
        c.arg(2, 1)
        c.rr(0, 2, opcode)
        c.rr(1, 3, opcode)
        c.jump("word_result")
    for label, right in (("shift_left", False), ("shift_right", True)):
        c.label(label)
        c.arg(0, 0)
        c.arg(2, 1)
        c.cmp(3, 0)
        c.cond("ne", "argument")
        c.cmp(2, 16)
        c.cond("ge", "argument")
        c.cmp(2, 0)
        c.cond("eq", "word_result")
        c.label(label + "_loop")
        if right:
            c.shift(0, 1, 0xd)
            c.shift(1, 1, 0xc)
        else:
            c.shift(1, 1, 0xb)
            c.shift(0, 1)
        c.imm(2, -1)
        c.branch("ne", label + "_loop")
        c.jump("word_result")

    c.label("ticks")
    c.mov_er(0, 0)
    c.absolute(0, 0xf00c)
    c.jump("word_result")
    c.label("inkey")
    c.mov_er(0, 0)
    c.slot(0, 0, True, True)
    c.raw("03 a0")
    c.slot(0, 2, True)
    c.imm(0, 0xf7, 0x20)
    c.raw("0b a0")
    c.absolute(0, 0xf044)
    c.slot(0, 3, True)
    c.pair(0, 14)
    c.call(0x12864)
    c.slot(0, 3)
    c.absolute(0, 0xf044, True)
    c.slot(0, 2)
    c.raw("0b a0")
    c.slot(2, 0, word=True)
    c.mov_er(0, 0)
    c.cmp(2, 0)
    c.cond("eq", "word_result")
    c.mov(0, 1)
    c.label("key_column")
    c.rr(4, 3)
    c.imm(4, 1, 0x20)
    c.branch("ne", "key_row")
    c.shift(3, 1, 0xc)
    c.imm(0, 16)
    c.branch("al", "key_column")
    c.label("key_row")
    c.rr(4, 2)
    c.imm(4, 1, 0x20)
    c.cond("ne", "word_result")
    c.shift(2, 1, 0xc)
    c.imm(0, 1)
    c.branch("al", "key_row")

    _call(c)
    c.label("zero")
    c.mov_er(0, 0)
    c.label("word_result")
    c.mov_er(2, 0)
    c.mem(0, 12, True, True)
    c.mem(2, 12, True, True, disp=2)
    c.mov_er(0, 0)
    c.jump("dispatch_out")
    c.label("argument")
    c.mov_er(0, 4)
    c.jump("dispatch_out")
    c.label("memory")
    c.mov_er(0, 6)
    c.label("dispatch_out")
    c.raw("08 e1")
    c.label("entry_out")
    c.raw("1e f2 8e f1 3e f8 2e f4 2b a0 8e f2")
    c.label("entry_memory")
    c.mov_er(0, 6)
    c.jump("entry_out")


def _call(c):
    c.label("call")
    c.arg(0, 0, True)
    c.cmp(1, 0)
    c.cond("ne", "argument")
    c.cmp(0, 16)
    c.cond("ge", "argument")
    c.arg(0, 0)
    c.rr(2, 0)
    c.imm(2, 1, 0x20)
    c.cond("ne", "argument")
    c.raw("7e f0 7e f8 88 e1")
    c.raw("1a a2")
    for addr, size in ((0x8000, 112), (0x8086, 2), (0x80a0, 3)):
        c.mov_er(0, addr)
        c.mov(5, size)
        c.label(f"call_save_{addr:x}")
        c.mem(4, 0)
        c.mem(4, 2, True)
        c.add(0, 1)
        c.add(2, 1)
        c.imm(5, -1)
        c.branch("ne", f"call_save_{addr:x}")
    c.arg(0, 1)
    c.arg(2, 2)
    c.arg(4, 3)
    c.arg(6, 4)
    c.arg(10, 0, True)
    c.arg(8, 0)
    c.call(CALL_BRIDGE_ADDRESS)
    c.raw("1a a2")
    c.add(2, 136)
    c.mem(0, 2, True, True)
    c.raw("1a a2")
    for addr, size in ((0x8000, 112), (0x8086, 2), (0x80a0, 3)):
        c.mov_er(0, addr)
        c.mov(5, size)
        c.label(f"call_restore_{addr:x}")
        c.mem(4, 2)
        c.mem(4, 0, True)
        c.add(0, 1)
        c.add(2, 1)
        c.imm(5, -1)
        c.branch("ne", f"call_restore_{addr:x}")
    c.raw("78 e1 3e f8 3e f0")
    c.slot(0, 0, word=True)
    c.jump("word_result")


def _to_integer(c):
    c.converter("to_integer")
    c.slot(10, 0, True)
    c.cmp(11, 0)
    c.cond("ne", "conv_argument")
    c.cmp(10, 5)
    c.cond("ge", "conv_argument")
    c.pair(2, 8)
    c.add(2, 10)
    c.mov(6, 10)
    c.label("imaginary")
    c.mem(0, 2)
    c.cmp(0, 0)
    c.cond("ne", "conv_argument")
    c.add(2, 1)
    c.imm(6, -1)
    c.branch("ne", "imaginary")
    c.mov_er(4, 0)
    c.mov_er(6, 0)
    c.mem(0, 8)
    c.cmp(0, 0)
    c.branch("ne", "nonzero")
    c.pair(2, 8)
    c.mov(6, 10)
    c.label("native_zero")
    c.mem(0, 2)
    c.cmp(0, 0)
    c.cond("ne", "conv_argument")
    c.add(2, 1)
    c.imm(6, -1)
    c.branch("ne", "native_zero")
    c.jump("integer_result")
    c.label("nonzero")
    c.cmp(0, 10)
    c.cond("ge", "conv_argument")
    c.mem(0, 8, disp=9)
    c.mov(1, 0)
    c.cmp(0, 5)
    c.branch("lt", "positive")
    c.imm(0, -5)
    c.mov(1, 1)
    c.label("positive")
    c.slot(1, 1, True)
    c.cmp(0, 1)
    c.cond("ne", "conv_argument")
    c.mem(7, 8, disp=8)
    c.cmp(7, 8)
    c.cond("ge", "conv_argument")
    c.mov(10, 0)
    c.label("digit")
    c.cmp(10, 0)
    c.branch("eq", "digit_low")
    c.rr(0, 10)
    c.imm(0, 1, 0x20)
    c.branch("eq", "digit_low")
    c.add(8, 1)
    c.mem(3, 8)
    c.shift(3, 4, 0xc)
    c.branch("al", "digit_ready")
    c.label("digit_low")
    c.mem(3, 8)
    c.imm(3, 15, 0x20)
    c.label("digit_ready")
    c.cmp(3, 10)
    c.cond("ge", "conv_argument")
    c.rr(0, 7)
    c.imm(0, 1)
    c.rr(10, 0, 7)
    c.branch("lt", "accumulate")
    c.cmp(3, 0)
    c.cond("ne", "conv_argument")
    c.jump("digit_next")
    c.label("accumulate")
    c.cmp(4, 0x99)
    c.imm(5, 0x99, 0x50)
    c.imm(6, 0x19, 0x50)
    c.branch("lt", "multiply")
    c.cond("ne", "conv_argument")
    c.cmp(3, 6)
    c.cond("ge", "conv_argument")
    c.label("multiply")
    c.pair(0, 4)
    c.rr(2, 6)
    c.shift(6, 1, 0xb)
    c.shift(5, 1, 0xb)
    c.shift(4, 1)
    c.shift(2, 3, 0xb)
    c.shift(1, 3, 0xb)
    c.shift(0, 3)
    c.rr(4, 0, 1)
    c.rr(5, 1, 6)
    c.rr(6, 2, 6)
    c.rr(4, 3, 1)
    c.imm(5, 0, 0x60)
    c.imm(6, 0, 0x60)
    c.label("digit_next")
    c.imm(10, 1)
    c.cmp(10, 15)
    c.cond("lt", "digit")
    c.mov(7, 0)
    c.slot(0, 0)
    c.cmp(0, 4)
    c.branch("eq", "unsigned_result")
    c.cmp(0, 2)
    c.branch("ne", "narrow_result")
    c.cmp(6, 16)
    c.cond("ge", "conv_argument")
    c.jump("unsigned_result")
    c.label("narrow_result")
    c.cmp(6, 0)
    c.cond("ne", "conv_argument")
    c.cmp(0, 3)
    c.branch("eq", "signed_result")
    c.cmp(0, 1)
    c.branch("eq", "unsigned_result")
    c.cmp(5, 0)
    c.cond("ne", "conv_argument")
    c.label("unsigned_result")
    c.slot(0, 1)
    c.cmp(0, 0)
    c.cond("ne", "conv_argument")
    c.jump("integer_result")
    c.label("signed_result")
    c.slot(0, 1)
    c.cmp(0, 0)
    c.branch("ne", "negative_result")
    c.cmp(5, 0x80)
    c.cond("ge", "conv_argument")
    c.jump("integer_result")
    c.label("negative_result")
    c.cmp(4, 0)
    c.imm(5, 0x80, 0x50)
    c.branch("lt", "negate")
    c.cond("ne", "conv_argument")
    c.label("negate")
    c.imm(4, 255, 0x40)
    c.imm(5, 255, 0x40)
    c.add(4, 1)
    c.mov_er(6, 0xffff)
    c.label("integer_result")
    c.mem(4, 12, True, True)
    c.mem(6, 12, True, True, disp=2)
    c.mov_er(0, 0)
    c.jump("conv_out")


def _to_number(c):
    c.converter("to_number", True)
    c.mem(4, 8, word=True)
    c.mem(6, 8, word=True, disp=2)
    c.pair(8, 14)
    c.mov(10, 0)
    c.label("decimal_divide")
    c.mov(1, 0)
    for reg in (7, 6, 5, 4):
        c.rr(0, reg)
        c.mov(2, 10)
        c.raw("29 f0")
        c.rr(reg, 0)
        c.rr(1, 2)
    c.mem(2, 8, True)
    c.add(8, 1)
    c.imm(10, 1)
    c.rr(0, 4)
    for reg in (5, 6, 7):
        c.rr(0, reg, 3)
    c.branch("ne", "decimal_divide")
    c.pair(2, 12)
    c.mov(0, 0)
    c.mov(1, 20)
    c.label("number_clear")
    c.mem(0, 2, True)
    c.add(2, 1)
    c.imm(1, -1)
    c.branch("ne", "number_clear")
    c.rr(0, 10)
    c.imm(0, -1)
    c.mem(0, 12, True, disp=8)
    c.add(8, -1)
    c.mem(0, 8)
    c.cmp(0, 0)
    c.branch("eq", "number_done")
    c.mov(1, 1)
    c.mem(1, 12, True, disp=9)
    c.mem(0, 12, True)
    c.imm(10, -1)
    c.branch("eq", "number_done")
    c.label("number_pair")
    c.add(12, 1)
    c.add(8, -1)
    c.mem(3, 8)
    c.shift(3, 4)
    c.imm(10, -1)
    c.branch("eq", "number_last")
    c.add(8, -1)
    c.mem(0, 8)
    c.rr(3, 0, 3)
    c.imm(10, -1)
    c.label("number_last")
    c.mem(3, 12, True)
    c.cmp(10, 0)
    c.branch("ne", "number_pair")
    c.label("number_done")
    c.mov_er(0, 0)
    c.jump("conv_out")
    c.label("conv_argument")
    c.mov_er(0, 4)
    c.label("conv_out")
    c.raw("10 e1 3e f8 2e f4 8e f2")
    c.label("conv_memory")
    c.mov_er(0, 6)
    c.raw("3e f8 2e f4 8e f2")


def memory_code():
    c = _Memory(MEMORY_ADDRESS)
    for label in ("dispatch", "to_integer", "to_number", "read_range"):
        c.jump(label)
    _range(c)
    _dispatch(c)
    _to_integer(c)
    _to_number(c)
    data = c.build()
    if MEMORY_ADDRESS + len(data) > MEMORY_STOP:
        raise ValueError(f"BASIC memory exceeds budget: {len(data)} > 4096")
    bridge = Code(CALL_BRIDGE_ADDRESS)
    # LARGE-model POP PC consumes PC.lo, PC.hi, CSR, padding (manual §1.6).
    # BL here has already set LR/LCSR to the wrapper; target RT returns there.
    bridge.raw("5e fa 5e f8 8e f2")  # PUSH ER10; PUSH ER8; POP PC.
    return ((MEMORY_ADDRESS - 0x80000, data),
            (CALL_BRIDGE_ADDRESS - 0x80000, bridge.build()))
