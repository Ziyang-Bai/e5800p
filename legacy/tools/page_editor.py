"""Build the fx-5800P ASM byte reader/writer in the legacy UI Flash pool.

ER0 supplies the initial S1 address. Returns a compatible S1 address and
R2 as the action: 0 switches to P, 1 exits ASM, 2 opens FUNCTION in P.
ER12 holds the page offset and R5 its byte; the DSR lives in the frame.
SP[0:32] stages data, SP[32:64] holds text, SP[64] flags unsaved changes.
The ROM display and key routines may modify scratch registers, so staged
state remains in the caller's stack frame.
"""

from u8_emit import Code
from address_input import HEX_KEY_ADDRESS, MEMORY_GOTO_ADDRESS, RAM_BEGIN, RAM_END
from small_font import SMALL_TEXT_ADDRESS

from flash_layout import EDITOR_ADDRESS
from sector_journal import COMMIT_ADDRESS, RECOVER_ADDRESS
from ui_text import text_copy
_SEG, _KIND, _PC = 76, 77, 78
_MASK, _CURSOR = 80, 84
_HELD_KEY, _KEY_SAMPLE, _HELD_MATRIX, _REPEATING = 85, 86, 88, 90


def editor_code():
    a = Code(EDITOR_ADDRESS)

    def far_if(condition, target):
        opposite = {"eq": "ne", "ne": "eq", "lt": "ge", "ge": "lt"}[condition]
        after = f"skip_far_{len(a.fixups)}"
        a.branch(opposite, after)
        a.jump(target)
        a.label(after)


    def page_ptr():
        a.raw("1a a2 50 80 00 01 06 f2")  # ER2 = SP + R5

    def text_ptr():
        a.raw("1a a2")                 # ER2 = SP
        a.mov_er(0, 32)
        a.raw("06 f2")                 # ER2 += 32

    def slot(offset, store=False, base=None):
        a.raw("5e f0")
        a.raw("1a a2" if base is None else "85 f2")
        a.mov_er(0, offset + (2 if base is None else 0))
        a.raw("06 f2 1e f0")
        a.db(0x21 if store else 0x20, 0x90)

    def set_dirty(value):
        a.raw("1a a2")
        a.mov_er(0, 64)
        a.raw("06 f2")
        a.mov(0, value)
        a.raw("21 90")

    def dirty():
        slot(64)
        a.raw("00 70")  # set Z

    def move_byte():
        slot(71)
        a.raw("01 70")
        far_if("eq", "write_hint")
        a.mov(0, 0)
        slot(71, True)

    def font(size):
        a.mov(0, size)
        a.raw("11 90 a0 80")
        a.mov(0, 1)
        a.raw("11 90 a2 80")

    def newline(text, y):
        if y != 1:
            raise ValueError('Error line must start at y=1')
        text_ptr()
        text_copy(a, text, 32)
        a.call('newline')

    a.label("entry")
    a.raw("ce f8 6e f4 7e f8 5e fe e0 e1 e0 e1 e0 e1")
    a.mov_er(2, 0x5ff0)
    a.raw("27 f0")
    a.branch("lt", "entry_address")
    a.mov_er(0, 0x5fef)  # A queue ending at 5FF0 selects the final editable byte.
    a.label("entry_address")
    a.raw("05 f8")
    slot(_PC, True)
    a.raw("90 80")
    slot(_PC + 1, True)
    a.raw("85 f0")
    a.raw("00 85 1f 25 05 fc e0 2c")  # ER0 absolute address -> page and byte cursor
    a.raw("10 90 a0 80")
    slot(65, True)
    a.raw("10 90 a2 80")
    slot(66, True)
    a.mov(0, 0)
    slot(70, True)  # R=0, W=1
    slot(71, True)  # number of typed nibbles
    slot(_HELD_KEY, True)
    a.mov(0, 8)
    slot(_SEG, True)
    a.mov(0, 0)
    slot(_KIND, True)
    a.call(RECOVER_ADDRESS)
    a.raw("00 70")
    a.branch("eq", "load")
    a.jump("recover_error")

    a.label("load")
    a.call("can_write")
    a.raw("00 70")
    a.branch("ne", "load_mode")
    a.mov(0, 0)
    slot(70, True)
    a.label("load_mode")
    slot(_SEG)
    a.raw("00 87 1a a2 2a f0 c5 f0")  # Page snapshot from the selected data segment.
    a.mov(8, 32)
    a.label("read_byte")
    a.raw("70 82 2f 90 00 93 51 93 81 e0 ff 18")
    a.branch("ne", "read_byte")
    set_dirty(0)
    for offset in range(_MASK, _MASK + 4):
        a.mov(0, 0)
        slot(offset, True)
    a.jump("draw")

    a.label("draw")
    a.call(0x0409a)
    font(7)
    a.mov(8, 0)
    a.mov(9, 1)  # Four byte rows at y=1,7,13,19; address remains at y=25.
    a.label("row")
    text_ptr()
    a.raw("2a f0 1a aa 80 80 00 01 06 fa")  # EA=text, ER10=SP+R8
    a.mov(7, 0)
    a.label("byte")
    a.mov(0, ord(" "))
    a.raw("51 90")
    a.raw("a0 90")  # L byte,[ER10]
    a.call("hexbyte")
    a.raw("51 90 51 91")
    a.raw("81 ea 01 17 08 77")
    a.branch("lt", "byte")
    a.mov(0, 0)
    a.raw("51 90")
    text_ptr()
    a.mov(0, 0)
    a.raw("90 81")  # y = R9
    a.call(SMALL_TEXT_ADDRESS)
    a.raw("08 18 06 19 19 79")  # offset += 8; stop at y=25
    a.branch("lt", "row")
    text_ptr()
    a.raw("2a f0")
    slot(_SEG)
    a.call("nibble")
    a.raw("51 90")
    a.mov(0, ord(":"))
    a.raw("51 90 c5 f8 50 80")
    a.mov(1, 0)
    a.raw("06 f8 90 80")  # ER8=ER12+R5; high address byte
    a.call("hexbyte")
    a.raw("51 90 51 91 80 80")
    a.call("hexbyte")
    a.raw("51 90 51 91")
    a.mov(0, ord(" "))
    a.raw("51 90 1a aa 50 80")
    a.mov(1, 0)
    a.raw("06 fa a0 90")  # selected byte from RAM
    a.raw("00 87")
    slot(71)
    a.raw("01 70")
    a.branch("ne", "current_value")
    slot(73)
    a.raw("4c 90")
    a.call("nibble")
    a.mov(1, ord("_"))
    a.jump("current_print")
    a.label("current_value")
    a.raw("70 80")
    a.call("hexbyte")
    a.label("current_print")
    a.raw("51 90 51 91")
    dirty()
    a.branch("eq", "clean")
    a.mov(0, ord("*"))
    a.jump("status_end")
    a.label("clean")
    a.mov(0, ord(" "))
    a.label("status_end")
    a.raw("51 90")
    a.mov(0, 0)
    a.raw("51 90")
    text_ptr()
    a.mov(0, 0)
    a.mov(1, 25)
    a.call(0x041da)
    slot(70)
    a.raw("00 70")
    a.branch("eq", "read_status")
    a.mov(0, ord("W"))
    a.jump("mode_status")
    a.label("read_status")
    a.mov(0, ord("R"))
    a.label("mode_status")
    a.raw("1a a2")
    a.mov_er(10, 32)
    a.raw("a6 f2 21 90 81 e2")
    a.mov(0, 0)
    a.raw("21 90")
    text_ptr()
    a.mov(0, 90)
    a.mov(1, 25)
    a.call(0x041da)
    a.call("cursor")
    a.call(0x043be)
    a.label("key")
    a.raw("10 90 8d 80")
    slot(72, True)
    a.call("read_key")
    a.raw("02 70 7d 51")
    far_if("eq", "function")
    a.raw("00 70")
    far_if("eq", "key")
    for key, label in ((0xfa, "cancel"), (0xfb, "confirm"), (0xfc, "left"),
                       (0xfd, "right"), (0xff, "up"), (0xfe, "down")):
        a.raw(f"{key:02x} 70")
        far_if("eq", label)
    a.raw("00 87")  # keep the typed character while reading W state
    slot(70)
    a.raw("00 70")
    far_if("eq", "key")
    a.raw("70 80 30 70")
    far_if("lt", "key")
    a.raw("3a 70")
    a.branch("ge", "letter_key")
    a.raw("d0 10")
    a.jump("typed_nibble")
    a.label("letter_key")
    a.raw("41 70")
    far_if("lt", "key")
    a.raw("47 70")
    far_if("ge", "key")
    a.raw("c9 10")
    a.label("typed_nibble")
    a.raw("00 87")
    slot(71)
    a.raw("01 70")
    a.branch("eq", "low_nibble")
    a.raw("70 80 4a 90")
    slot(73, True)
    a.mov(0, 1)
    slot(71, True)
    a.jump("draw")
    a.label("low_nibble")
    slot(73)
    a.raw("73 80")
    a.raw("00 87")
    page_ptr()
    a.raw("70 80 21 90")
    set_dirty(1)
    a.raw("50 80 3c 90 00 01 1a a2 06 f2")
    a.mov_er(0, _MASK)
    a.raw("06 f2 20 96 50 81 07 21")
    a.mov(0, 1)
    a.raw("1a 80 63 80 21 90")  # Only changed RAM/SRAM bytes are committed.
    a.mov(0, 2)
    slot(71, True)
    a.jump("draw")

    a.label("write_hint")
    a.jump("draw")
    a.label("confirm")
    slot(70)
    a.raw("00 70")
    a.branch("ne", "write_confirm")
    a.call("can_write")
    a.raw("00 70")
    far_if("eq", "read_only")
    a.mov(0, 1)
    slot(70, True)
    a.mov(0, 0)
    slot(71, True)
    a.jump("draw")
    a.label("write_confirm")
    slot(71)
    a.raw("01 70")
    far_if("eq", "write_hint")
    dirty()
    far_if("eq", "read_mode")
    slot(_KIND)
    a.raw("00 70")
    far_if("ne", "write_memory")
    a.raw("c5 f0 1a a2")
    a.call(COMMIT_ADDRESS)
    a.raw("00 70")
    far_if("ne", "write_error")
    a.jump("read_mode")
    a.label("write_memory")
    a.raw("50 80")
    slot(_CURSOR, True)
    slot(_SEG)
    a.raw("00 87 1a a8 c5 fa")
    a.mov(6, 0)
    a.label("memory_byte")
    a.raw("60 80 07 20")
    a.branch("ne", "memory_bit")
    a.raw("60 80 3c 90 00 01 1a a2 06 f2")
    a.mov_er(0, _MASK)
    a.raw("06 f2 20 94")
    a.label("memory_bit")
    a.raw("01 a4")
    a.branch("eq", "memory_next")
    a.raw("80 93 70 82 2f 90 a1 93")
    a.label("memory_next")
    a.raw("1c 94 81 e8 81 ea 01 16 20 76")
    a.branch("lt", "memory_byte")
    slot(_CURSOR)
    a.raw("00 85")
    a.label("read_mode")
    a.mov(0, 0)
    slot(70, True)
    slot(71, True)
    a.jump("load")
    a.label("cancel")
    slot(70)
    a.raw("00 70")
    a.branch("ne", "read_mode")
    a.mov(0, 1)  # leave ASM
    a.jump("finish")

    a.label("function")
    a.raw("10 90 8d 80 f3 20 11 90 8d 80")
    slot(71)
    a.raw("01 70")
    far_if("eq", "write_hint")
    slot(72)
    a.raw("08 20 00 70")
    a.branch("ne", "goto")
    dirty()
    far_if("ne", "save_first")
    a.mov(0, 2)  # switch to P and open FUNCTION
    a.jump("finish")
    a.label("goto")
    dirty()
    far_if("ne", "save_first")
    a.raw("c5 f0 50 82 00 03 26 f0 05 f8")
    slot(_SEG)
    a.raw("00 82 85 f0")
    a.call(MEMORY_GOTO_ADDRESS)
    a.raw("00 73")
    far_if("eq", "draw")
    a.raw("05 f8 20 87 70 80")
    slot(_SEG, True)
    a.raw("08 77")
    a.branch("lt", "goto_sram")
    a.mov(0, 0)
    a.jump("goto_kind")
    a.label("goto_sram")
    a.raw("04 77")
    a.branch("ne", "goto_ram")
    a.mov(0, 1)
    a.jump("goto_kind")
    a.label("goto_ram")
    a.mov(0, 2)
    a.label("goto_kind")
    slot(_KIND, True)
    a.raw("85 f0 00 85 1f 25 05 fc e0 2c")
    a.jump("read_mode")

    a.label("toggle")
    a.raw("10 90 8d 80 f3 20 11 90 8d 80")
    slot(71)
    a.raw("01 70")
    far_if("eq", "write_hint")
    dirty()
    far_if("ne", "save_first")
    a.mov(0, 0)  # switch back to P at the selected byte
    a.jump("finish")
    a.label("left")
    slot(72)
    a.raw("08 20 00 70")
    far_if("ne", "toggle")
    slot(71)
    a.raw("01 70")
    far_if("eq", "write_back")
    a.mov(0, 0)
    slot(71, True)
    a.raw("00 75")
    a.branch("eq", "left_page")
    a.raw("ff 15")
    a.jump("draw")
    a.label("left_page")
    a.mov(4, 31)
    a.jump("previous_page")
    a.label("right")
    slot(72)
    a.raw("08 20 00 70")
    far_if("ne", "toggle")
    move_byte()
    slot(70)
    a.raw("00 70")
    a.branch("eq", "right_data")
    slot(_KIND)
    a.raw("00 70")
    a.branch("ne", "right_data")
    slot(_SEG)
    a.raw("08 70")
    a.branch("ne", "right_data")
    a.mov_er(0, 0x5fe0)
    a.raw("07 fc")
    a.branch("ne", "right_data")
    a.raw("0f 75")
    far_if("ge", "draw")
    a.label("right_data")
    a.raw("1f 75")
    a.branch("eq", "right_page")
    a.raw("01 15")
    a.jump("draw")
    a.label("right_page")
    a.mov(4, 0)
    a.jump("next_page")
    a.label("write_back")
    a.mov(0, 0)
    slot(71, True)
    a.jump("draw")
    a.label("up")
    move_byte()
    a.raw("08 75")
    a.branch("lt", "up_page")
    a.raw("f8 15")
    a.jump("draw")
    a.label("up_page")
    a.raw("50 84 18 14")
    a.jump("previous_page")
    a.label("down")
    move_byte()
    slot(70)
    a.raw("00 70")
    a.branch("eq", "down_data")
    slot(_KIND)
    a.raw("00 70")
    a.branch("ne", "down_data")
    slot(_SEG)
    a.raw("08 70")
    a.branch("ne", "down_data")
    a.mov_er(0, 0x5fe0)
    a.raw("07 fc")
    a.branch("ne", "down_data")
    a.raw("08 75")
    far_if("ge", "draw")
    a.label("down_data")
    a.raw("18 75")
    a.branch("ge", "down_page")
    a.raw("08 15")
    a.jump("draw")
    a.label("down_page")
    a.raw("50 84 e8 14")
    a.jump("next_page")

    a.label("previous_page")
    a.call("at_begin")
    a.raw("00 70")
    far_if("ne", "draw")
    dirty()
    far_if("ne", "save_first")
    a.mov_er(0, 0)
    a.raw("07 fc")
    a.branch("ne", "previous_offset")
    slot(_SEG)
    a.raw("ff 10")
    slot(_SEG, True)
    a.label("previous_offset")
    a.raw("e0 ec 40 85")
    a.jump("load")
    a.label("next_page")
    a.call("at_end")
    a.raw("00 70")
    far_if("ne", "draw")
    dirty()
    far_if("ne", "save_first")
    a.mov_er(0, 0xffe0)
    a.raw("07 fc")
    a.branch("ne", "next_offset")
    slot(_SEG)
    a.raw("01 10")
    slot(_SEG, True)
    a.label("next_offset")
    a.raw("a0 ec 40 85")
    a.jump("load")

    a.label("write_error")
    newline("WRITE ERROR", 1)
    a.jump("key")
    a.label("read_only")
    newline("READ ONLY", 1)
    a.jump("key")
    a.label("save_first")
    newline("EXE SAVE FIRST", 1)
    a.jump("key")
    a.label("recover_error")
    newline("RECOVER ERROR", 1)
    a.label("error_key")
    a.call(HEX_KEY_ADDRESS)
    a.raw("fa 70")
    a.branch("ne", "error_key")
    a.mov(0, 1)
    a.label("finish")
    slot(74, True)
    slot(66)
    a.raw("11 90 a2 80")
    slot(65)
    a.raw("11 90 a0 80")
    slot(_SEG)
    a.raw("08 70")
    a.branch("ne", "return_pc")
    a.raw("c5 f0 50 86 00 07 66 f0")
    a.mov_er(2, 0x4000)
    a.raw("27 f0")
    a.branch("lt", "return_pc")
    a.mov_er(2, 0x5ff0)
    a.raw("27 f0")
    a.branch("ge", "return_pc")
    a.raw("05 f8")
    a.jump("return_action")
    a.label("return_pc")
    slot(_PC)
    a.raw("00 88")
    slot(_PC + 1)
    a.raw("00 89")
    a.label("return_action")
    slot(74)
    a.raw("00 82 85 f0")
    a.raw("20 e1 20 e1 20 e1 1e fe 3e f8 2e f4 8e f2")

    # These leaf probes preserve the page and cursor; R0 is their boolean result.
    a.label("can_write")
    slot(_KIND)
    a.raw("00 70")
    a.branch("ne", "probe_yes")
    slot(_SEG)
    a.raw("08 70")
    a.branch("ne", "probe_no")
    a.raw("c5 f0")
    a.mov_er(2, 0x4000)
    a.raw("27 f0")
    a.branch("lt", "probe_no")
    a.mov_er(2, 0x6000)
    a.raw("27 f0")
    a.branch("ge", "probe_no")
    a.mov_er(0, 0x5fe0)
    a.raw("07 fc")
    a.branch("ne", "probe_yes")
    a.raw("10 75")
    a.branch("ge", "probe_no")
    a.jump("probe_yes")
    a.label("at_begin")
    slot(_KIND)
    a.raw("02 70")
    a.branch("ne", "begin_external")
    a.mov_er(0, RAM_BEGIN)
    a.jump("probe_page")
    a.label("begin_external")
    a.raw("00 70")
    a.branch("ne", "begin_offset")
    slot(_SEG)
    a.raw("08 70")
    a.branch("ne", "probe_no")
    a.label("begin_offset")
    a.mov_er(0, 0)
    a.jump("probe_page")
    a.label("at_end")
    slot(_KIND)
    a.raw("00 70")
    a.branch("ne", "end_memory")
    slot(_SEG)
    a.raw("0f 70")
    a.branch("ne", "probe_no")
    a.mov_er(0, 0xffe0)
    a.jump("probe_page")
    a.label("end_memory")
    a.raw("01 70")
    a.branch("ne", "end_ram")
    a.mov_er(0, 0x7fe0)
    a.jump("probe_page")
    a.label("end_ram")
    a.mov_er(0, RAM_END - 32)
    a.label("probe_page")
    a.raw("07 fc")
    a.branch("ne", "probe_no")
    a.label("probe_yes")
    a.mov(0, 1)
    a.raw("1f fe")
    a.label("probe_no")
    a.mov(0, 0)
    a.raw("1f fe")

    a.label("read_key")
    a.raw("1a a8 ce f8 6e f4")  # ER8 anchors the caller's frame across ROM calls.
    slot(_HELD_KEY, base=8)
    a.raw("00 70")
    a.branch("eq", "new_key")
    a.call("same_held_key")
    a.raw("00 70")
    a.branch("eq", "new_key")
    slot(_REPEATING, base=8)
    a.raw("00 70")
    a.branch("eq", "repeat_initial_delay")
    a.mov(6, 8)
    a.jump("repeat_delay")
    a.label("repeat_initial_delay")
    a.mov(6, 24)
    a.label("repeat_delay")
    a.mov_er(0, 128)  # Short timer waits keep release and the next press responsive.
    a.call(0x05cc6)
    a.call("same_held_key")
    a.raw("00 70")
    a.branch("eq", "new_key")
    a.raw("ff 16")
    a.branch("ne", "repeat_delay")
    a.mov(0, 1)
    slot(_REPEATING, True, base=8)
    slot(_HELD_KEY, base=8)
    a.jump("key_return")
    a.label("new_key")
    a.mov(0, 0)
    slot(_HELD_KEY, True, base=8)
    a.call(HEX_KEY_ADDRESS)
    a.raw("fc 70")
    a.branch("lt", "key_return")
    a.raw("00 84")
    a.raw("85 f0")
    a.mov_er(2, _KEY_SAMPLE)
    a.raw("26 f0")
    a.call(0x12864)
    a.raw("00 70")
    a.branch("eq", "arrow_return")
    for i in range(2):
        slot(_KEY_SAMPLE + i, base=8)
        slot(_HELD_MATRIX + i, True, base=8)
    a.mov(0, 0)
    slot(_REPEATING, True, base=8)
    a.raw("40 80")
    slot(_HELD_KEY, True, base=8)
    a.label("arrow_return")
    a.raw("40 80")
    a.label("key_return")
    a.raw("2e f4 8e f2")

    a.label("same_held_key")
    a.raw("ce f8 85 f0")
    a.mov_er(2, _KEY_SAMPLE)
    a.raw("26 f0")
    a.call(0x12864)
    a.raw("00 70")
    a.branch("eq", "held_no")
    for i in range(2):
        slot(_KEY_SAMPLE + i, base=8)
        a.raw("00 84")
        slot(_HELD_MATRIX + i, base=8)
        a.raw("47 80")
        a.branch("ne", "held_no")
    a.mov(0, 1)
    a.raw("8e f2")
    a.label("held_no")
    a.mov(0, 0)
    a.raw("8e f2")

    a.label("hexbyte")
    a.raw("ce f8 00 83 4c 90")  # R3=byte, R0=high nibble
    a.call("nibble")
    a.raw("00 82 30 80 0f 20")
    a.call("nibble")
    a.raw("00 81 20 80 8e f2")
    a.label("nibble")
    a.raw("0a 70")
    a.branch("lt", "digit")
    a.raw("37 10 1f fe")
    a.label("digit")
    a.raw("30 10 1f fe")

    a.label("cursor")
    a.raw("50 88 18 28 00 09")  # Row offset = (R5 & 18h) * 9 framebuffer bytes.
    a.mov(1, 9)
    a.raw("14 f8")  # MUL ER8,R1
    a.raw("50 80 07 20 00 82 01 80 21 80 1c 90 00 01 86 f0")
    a.mov_er(2, 0x80ec)  # First byte row starts at y=1.
    a.raw("06 f2")  # first LCD-buffer byte of the selected 12-pixel cell
    a.raw("50 80 01 20")
    a.branch("eq", "cursor_even")
    a.mov(6, 0x0f)
    a.mov(7, 0xff)
