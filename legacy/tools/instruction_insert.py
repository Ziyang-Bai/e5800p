"""Journaled S1 replacement and branch relocation, with bounded shared decoding.

ER2=S1 PC, ER6={old span,new span,up to64 replacement bytes}. Both spans
are even, old2..254/new2..64. Returns ER0=0/FFFF; preserves ER2/XR4/ER6
and R8..R15. Decoding reads staged RAM, original S1 or backed-up S2 as
appropriate; after erase no length read follows the erased S1 sector.
"""

from sector_journal import (BACKUP_ADDRESS, CRC_UPDATE_ADDRESS, FINISH_ADDRESS,
                            RECOVER_ADDRESS, PROGRAM_RAM_ADDRESS)
from flash_layout import BATCH_ADDRESS, BATCH_EMIT_ADDRESS, BATCH_RELOCATE_ADDRESS
from instruction_codec import SOURCE_LENGTH_ADDRESS
from u8_emit import Code

BATCH_MAX_BYTES = 64


def batch_code():
    c = Code(BATCH_ADDRESS)
    main = c
    labels = c.labels
    chunks = [c]
    seq = 0

    def pair(dst, src):
        c.db((src << 4) | 5, 0xf0 | dst)

    def register(dst, src):
        c.db(src << 4, 0x80 | dst)

    def ptr(offset):
        pair(2, 14)
        if offset:
            c.db(0x80 | offset, 0xe2)  # ADD ER2,#offset, preserving R0/R1

    def get(offset, reg=0):
        ptr(offset)
        c.db(0x20, 0x90 | reg)

    def put(offset, reg=0):
        ptr(offset)
        c.db(0x21, 0x90 | reg)

    def get_word(offset):
        get(offset, 0)
        get(offset + 1, 1)

    def desc(offset, reg=0):
        get(31, 7)
        get_word(18)
        pair(2, 0)
        register(0, 7)
        c.mov(1, 0)
        c.raw("06 f2")
        c.db(0x80 | offset, 0xe2)
        c.db(0x20, 0x90 | reg)

    def put_word(offset):
        put(offset, 0)
        put(offset + 1, 1)
    def flash(pointer, reg=0):
        c.db(8, 0xe3, (pointer << 4), 0x90 | reg)

    def forward_if(condition, target):
        opposite = {"eq": "ne", "ne": "eq", "lt": "ge", "ge": "lt"}[condition]
        nonlocal seq
        seq += 1
        skip = f"skip_{seq}"
        c.branch(opposite, skip)
        c.jump(target)
        c.label(skip)

    # Stack: 0..15 output page, 16..17 CRC, 18..19 descriptor pointer,
    # 20..21 edit S2 address, 22 old length, 23 new length, 24 delta,
    # 25 current length, 26..27 source limit, 28..29 opcode, 30 pass,
    # 31 staged byte offset. Erased FFFF words retain their two-byte span.
    c.raw("ce f8")
    c.raw("5e f2")  # preserve the caller's full S1 address
    c.raw("6e f4 7e f8 5e fe e0 e1 1a ae")  # 32-byte frame
    pair(8, 2)
    pair(12, 8)
    c.mov_er(0, 0x2000)
    c.raw("06 fc")  # S1 address -> S2 coordinate
    pair(0, 6)
    put_word(18)
    pair(0, 12)
    put_word(20)
    pair(2, 6)
    c.raw("81 e2 20 90")
    c.raw("02 70")
    forward_if("lt", "invalid")
    c.db(BATCH_MAX_BYTES + 1, 0x70)
    forward_if("ge", "invalid")
    put(23)
    c.raw("01 20")
    forward_if("ne", "invalid")
    pair(2, 6)
    c.raw("20 90")
    c.raw("02 70")
    forward_if("lt", "invalid")
    put(22)
    c.raw("01 20")
    forward_if("ne", "invalid")
    # The selected S2 byte must address an aligned instruction in S1.
    pair(0, 12)
    c.raw("01 20")
    forward_if("ne", "invalid")
    pair(0, 12)
    c.raw("e0 11")  # S2 address high byte -> S1 address
    c.mov_er(2, 0x4000)
    c.raw("27 f0")
    forward_if("lt", "invalid")
    c.mov_er(2, 0x5ff0)
    c.raw("27 f0")
    forward_if("ge", "invalid")
    pair(10, 0)
    c.mov_er(8, 0x4000)
    c.label("boundary")
    c.raw("a7 f8")
    forward_if("eq", "boundary_ready")
    forward_if("ge", "invalid")
    c.call("s1_length")
    c.raw("ff 77")
    forward_if("eq", "invalid")
    register(2, 7)
    c.mov(3, 0)
    c.raw("26 f8")
    c.jump("boundary")
    c.label("boundary_ready")
    c.call("s1_length")
    c.raw("ff 77")
    forward_if("eq", "invalid")
    pair(0, 8)
    get(22, 2)
    c.mov(3, 0)
    c.raw("26 f0")
    c.mov_er(2, 0x5ff0)
    c.raw("27 f0")
    forward_if("lt", "old_inside")
    forward_if("ne", "invalid")
    c.label("old_inside")
    get(22, 0)
    register(2, 0)
    c.mov(3, 0)
    pair(10, 8)
    c.raw("26 fa")  # ER10 is the removed-span end; ER8 starts its boundary walk.
    c.label("old_span")
    c.raw("a7 f8")
    forward_if("eq", "old_ready")
    forward_if("ge", "invalid")
    c.call("s1_length")
    c.raw("ff 77")
    forward_if("eq", "invalid")
    register(2, 7)
    c.mov(3, 0)
    c.raw("26 f8")
    c.jump("old_span")
    c.label("old_ready")
    pair(8, 12)
    c.raw("e0 19")  # Restore the selected S1 address for subsequent span checks.
    get(23, 0)
    get(22, 2)
    c.raw("28 80")  # delta = new length - old length
    put(24)
    pair(0, 8)
    get(22, 2)
    c.mov(3, 0)
    c.raw("26 f0")
    c.mov_er(2, 0x5ff0)
    c.raw("27 f0")
    forward_if("lt", "span_valid")
    forward_if("ne", "invalid")
    c.label("span_valid")
    # Decode the complete staged RAM stream with the same bounded reader.
    c.mov(0, 0)
    put(31)
    c.label("staged_loop")
    c.call("staged_length")
    c.raw("ff 77")
    forward_if("eq", "invalid")
    put(25, 7)
    c.label("staged_opcode")
    # A far branch to an odd address would be rounded down by the CPU.
    get(25, 0)
    c.raw("04 70")
    forward_if("ne", "staged_ready")
    desc(3, 0)
    c.raw("f0 20 f0 70")
    forward_if("ne", "staged_ready")
    desc(2, 0)
    c.raw("0f 20 02 70")
    forward_if("ge", "staged_ready")
    desc(5, 0)
    c.raw("01 20")
    forward_if("ne", "invalid")
    c.label("staged_ready")
    # A new relative operand already names a destination in the new stream.
    desc(3, 1)
    c.raw("c0 71")
    forward_if("lt", "staged_branch_ready")
    c.raw("cf 71")
    forward_if("ge", "staged_branch_ready")
    desc(2, 4)
    register(0, 4)
    c.mov(5, 0)
    c.raw("80 20")
    forward_if("eq", "staged_sign")
    c.mov(5, 0xff)
    c.label("staged_sign")
    c.raw("46 f4")
    pair(0, 12)
    get(31, 2)
    c.mov(3, 0)
    c.raw("26 f0")
    c.raw("82 e0 06 f4")
    c.mov_er(2, 0x6000)
    c.raw("27 f0")
    forward_if("lt", "invalid")
    c.mov_er(2, 0x7ff0)
    c.raw("27 f0")
    forward_if("ge", "invalid")
    c.label("staged_branch_ready")
    c.label("staged_step")
    get(31, 0)
    get(25, 1)
    c.raw("11 80")
    put(31)
    get(23, 1)
    c.raw("17 80")
    forward_if("lt", "staged_loop")
    forward_if("ne", "invalid")
    # Growth must fit erased trailing padding before S1 is touched.
    get(24, 3)
    register(0, 3)
    c.raw("80 20")
    forward_if("ne", "no_growth")
    c.raw("00 73")
    forward_if("eq", "no_growth")
    c.mov_er(8, 0x5ff0)
    register(2, 3)
    c.mov(3, 0)
    c.raw("28 88 39 89")  # SUB R8,R2; SUBC R9,R3
    get(24, 3)
    c.label("tail")
    flash(8)
    c.raw("ff 70")
    forward_if("ne", "invalid")
    c.raw("81 e8 ff 13")
    c.branch("ne", "tail")
    c.label("no_growth")
    c.mov_er(8, 0x7ff0)
    get(24, 3)
    register(0, 3)
    c.raw("80 20")
    forward_if("ne", "limit_ready")
    c.raw("00 73")
    forward_if("eq", "limit_ready")
    register(2, 3)
    c.mov(3, 0)
    c.raw("28 88 39 89")
    c.label("limit_ready")
    pair(0, 8)
    put_word(26)
    pair(0, 12)
    get(22, 2)
    c.mov(3, 0)
    c.raw("26 f0")
    pair(4, 0)
    get_word(26)
    c.raw("07 f4")  # selected end must fit the source limit
    forward_if("lt", "source_ready")
    forward_if("ne", "invalid")
    c.label("source_ready")
    # Check every retained branch before changing either flash sector.
    c.mov(0, 0)
    put(30)
    c.mov_er(8, 0x6000)
    c.label("preflight")
    get_word(26)
    c.raw("07 f8")
    forward_if("ge", "preflight_done")
    c.raw("c7 f8")
    forward_if("eq", "preflight_skip")
    pair(2, 8)
    c.raw("e0 13")  # preflight reads S1, not a possibly stale S2
    flash(2)
    register(4, 0)
    c.raw("81 e2")
    flash(2, 1)
    register(5, 1)
    c.call("preflight_length")
    c.raw("ff 77")
    forward_if("eq", "invalid")
    put(25, 7)
    c.call("source_span")
    c.raw("00 70")
    forward_if("ne", "invalid")
    c.call("relocate")
    c.raw("00 70")
    forward_if("ne", "invalid")
    get(25, 2)
    c.mov(3, 0)
    c.raw("26 f8")
    c.jump("preflight")
    c.label("preflight_skip")
    get(22, 2)
    c.mov(3, 0)
    c.raw("26 f8")
    c.jump("preflight")
    c.label("preflight_done")
    c.mov(0, 1)
    put(30)
    c.call(BACKUP_ADDRESS)
    c.raw("00 70")
    forward_if("ne", "recover")
    c.mov_er(8, 0x6000)
    c.mov_er(10, 0x4000)
    c.mov(0, 0xff)
    c.mov(1, 0xff)
    put_word(16)

    c.label("instruction")
    get_word(26)
    c.raw("07 f8")
    forward_if("ge", "padding")
    c.raw("c7 f8")  # CMP ER8,ER12
    forward_if("ne", "ordinary")
    get(18, 4)
    get(19, 5)
    c.raw("82 e4")  # descriptor instruction bytes begin at +2
    get(23, 7)
    c.label("replacement")
    c.raw("40 90 81 e4")
    c.call("emit")
    c.raw("00 70")
    forward_if("ne", "recover")
    c.raw("ff 17")
    c.branch("ne", "replacement")
    get(22, 0)
    c.mov(1, 0)
    c.raw("06 f8")
    c.jump("instruction")

    c.label("ordinary")
    flash(8)
    register(4, 0)
    pair(2, 8)
    c.raw("81 e2")
    flash(2, 1)
    register(5, 1)
    c.call("backup_length")
    c.raw("ff 77")
    forward_if("eq", "recover")
    put(25, 7)
    c.call("source_span")
    c.raw("00 70")
    forward_if("ne", "recover")
    put(28, 4)
    put(29, 5)
    c.call("relocate")
    c.raw("00 70")
    forward_if("ne", "recover")
    c.raw("00 76")
    forward_if("eq", "plain")
    c.raw("01 76")
    forward_if("ne", "far_instruction")
    register(0, 4)
    c.call("emit")
    c.raw("00 70")
    forward_if("ne", "recover")
    get(29, 0)
    c.call("emit")
    c.raw("00 70")
    forward_if("ne", "recover")
    c.raw("82 e8")
    c.jump("instruction")

    c.label("far_instruction")
    get(28, 0)
    c.call("emit")
    c.raw("00 70")
    forward_if("ne", "recover")
    get(29, 0)
    c.call("emit")
    c.raw("00 70")
    forward_if("ne", "recover")
    register(0, 4)
    c.call("emit")
    c.raw("00 70")
    forward_if("ne", "recover")
    register(0, 5)
    c.call("emit")
    c.raw("00 70")
    forward_if("ne", "recover")
    c.raw("84 e8")
    c.jump("instruction")

    c.label("plain")
    get(25, 7)
    c.label("plain_byte")
    flash(8)
    c.raw("81 e8")
    c.call("emit")
    c.raw("00 70")
    forward_if("ne", "recover")
    c.raw("ff 17")
    c.branch("ne", "plain_byte")
    c.jump("instruction")

    c.label("padding")
    c.mov_er(0, 0x5ff0)
    c.raw("07 fa")
    forward_if("eq", "finish")
    c.mov(0, 0xff)
    c.call("emit")
    c.raw("00 70")
    forward_if("ne", "recover")
    c.jump("padding")
    c.label("finish")
    get_word(16)
    c.call(FINISH_ADDRESS)
    c.raw("00 70")
    forward_if("ne", "recover")
    c.jump("success")
    c.label("recover")
    c.call(RECOVER_ADDRESS)
    c.label("invalid")
    c.mov_er(0, 0xffff)
    c.jump("exit")
    c.label("success")
    c.mov_er(0, 0)
    c.label("exit")
    c.raw("ea a1 20 e1 1e fe 3e f8 2e f4")
    c.raw("1e f2")
    c.raw("8e f2")

    c = Code(BATCH_EMIT_ADDRESS)
    c.labels = labels
    chunks.append(c)
    # emit R0 to RAM buffer, update CRC, write/verify every full page.
    c.label("emit")
    c.raw("ce f8 6e f4")
    register(5, 0)
    c.mov_er(0, 0x5ff0)
    c.raw("07 fa")
    forward_if("ge", "emit_bad")
    pair(2, 14)
    register(0, 10)
    c.raw("0f 20")
    c.mov(1, 0)
    c.raw("06 f2 21 95")
    get_word(16)
    register(2, 5)
    c.call(CRC_UPDATE_ADDRESS)
    put_word(16)
    c.raw("81 ea")
    register(0, 10)
    c.raw("0f 20 00 70")
    forward_if("ne", "emit_good")
    pair(0, 10)
    c.raw("f0 e0")  # destination is page end: subtract 16
    pair(4, 14)
    c.mov_er(6, 16)
    c.call(PROGRAM_RAM_ADDRESS)
    c.raw("00 70")
    forward_if("ne", "emit_bad")
    pair(4, 14)
    pair(6, 10)
    c.raw("f0 e6")
    c.mov(3, 16)
    c.label("verify")
    flash(6)
    c.raw("40 91 17 80")
    forward_if("ne", "emit_bad")
    c.raw("81 e4 81 e6 ff 13")
    c.branch("ne", "verify")
    c.label("emit_good")
    c.mov_er(0, 0)
    c.jump("emit_exit")
    c.label("emit_bad")
    c.mov_er(0, 0xffff)
    c.label("emit_exit")
    c.raw("2e f4 8e f2")
    c = main

    c.label("source_span")
    pair(0, 8)
    get(25, 2)
    c.mov(3, 0)
    c.raw("26 f0")
    pair(6, 0)
    get_word(26)
    c.raw("07 f6")
    forward_if("lt", "span_ok")
    forward_if("ne", "span_bad")
    c.label("span_ok")
    c.mov_er(0, 0)
    c.raw("1f fe")
    c.label("span_bad")
    c.mov_er(0, 0xffff)
    c.raw("1f fe")

    c = Code(BATCH_RELOCATE_ADDRESS)
    c.labels = labels
    chunks.append(c)
    # Input R4/R5 is the opcode, R8 its S2 address. Output R6 is
    # 0=plain, 1=relative, 2=far; R4/R5 hold the rewritten operand.
    c.label("relocate")
    c.mov(6, 0)
    register(0, 5)
    c.raw("c0 70")
    forward_if("lt", "relocate_ok")
    c.raw("cf 70")
    forward_if("lt", "relative_target")
    c.raw("f8 70")
    forward_if("ne", "relocate_ok")  # only CSR 8 points into S1
    register(0, 4)
    c.raw("0f 20 02 70")
    forward_if("ge", "relocate_ok")
    c.mov(6, 2)
    get(30, 7)
    pair(2, 8)
    c.raw("00 77")
    forward_if("ne", "far_source")
    c.raw("e0 13")  # preflight has not copied S1 into S2
    c.label("far_source")
    c.raw("82 e2")
    flash(2, 4)
    c.raw("81 e2")
    flash(2, 5)
    c.raw("20 15")  # S1 target -> S2 coordinate for relocation
    register(0, 4)
    c.raw("01 20")
    forward_if("ne", "relocate_bad")
    c.jump("target_check")

    c.label("relative_target")
    c.mov(6, 1)
    register(0, 4)
    c.mov(5, 0)
    c.raw("80 20")
    forward_if("eq", "relative_sign")
    c.mov(5, 0xff)
    c.label("relative_sign")
    c.raw("46 f4")  # signed displacement in words -> byte offset
    pair(0, 8)
    c.raw("82 e0 06 f4")  # target = old PC + 2 + offset

    c.label("target_check")
    pair(0, 4)
    c.mov_er(2, 0x6000)
    c.raw("27 f0")
    forward_if("lt", "target_ready")
    c.mov_er(2, 0x7ff0)
    c.raw("27 f0")
    forward_if("ge", "target_ready")
    pair(0, 12)
    c.raw("07 f4")
    forward_if("lt", "target_ready")
    forward_if("eq", "target_ready")
    get(22, 2)
    c.mov(3, 0)
    c.raw("26 f0 07 f4")
    forward_if("lt", "relocate_bad")  # target inside removed instruction
    get(24, 2)
    c.mov(3, 0)
    register(0, 2)
    c.raw("80 20")
    forward_if("eq", "target_delta")
    c.mov(3, 0xff)
    c.label("target_delta")
    c.raw("26 f4")
    pair(0, 4)
    c.mov_er(2, 0x7ff0)
    c.raw("27 f0")
    forward_if("ge", "relocate_bad")

    c.label("target_ready")
    c.raw("02 76")
    forward_if("ne", "relative_finish")
    c.raw("e0 15")  # S2 coordinate -> CSR 8 program PC
    c.jump("relocate_ok")
    c.label("relative_finish")
    pair(0, 12)
    get(22, 2)
    c.mov(3, 0)
    c.raw("26 f0 07 f8")
    forward_if("lt", "source_ready_rel")
    get(24, 2)
    c.mov(3, 0)
    register(0, 2)
    c.raw("80 20")
    forward_if("eq", "source_delta")
    c.mov(3, 0xff)
    c.label("source_delta")
    pair(0, 8)
    c.raw("26 f0")
    c.jump("source_done_rel")
    c.label("source_ready_rel")
    pair(0, 8)
    c.label("source_done_rel")
    c.raw("82 e0 08 84 19 85")  # target - (new source + 2)
    register(0, 4)
    c.raw("01 20")
    forward_if("ne", "relocate_bad")
    c.raw("00 75")
    forward_if("eq", "relative_low")
    c.raw("ff 75")
    forward_if("ne", "relocate_bad")
    c.raw("1c 94 80 34")
    c.jump("relocate_ok")
    c.label("relative_low")
    c.raw("1c 94")
    c.label("relocate_ok")
    c.mov_er(0, 0)
    c.raw("1f fe")
    c.label("relocate_bad")
    c.mov_er(0, 0xffff)
    c.raw("1f fe")

    c = main
    c.label("s1_length")
    c.raw("ce f8 6e f4")
    pair(0, 8)
    c.mov_er(4, 0x5ff0)
    c.jump("source_length")
    c.label("preflight_length")
    c.raw("ce f8 6e f4")
    pair(0, 8)
    c.raw("e0 11")
    c.mov_er(4, 0x5ff0)
    c.jump("source_length")
    c.label("backup_length")
    c.raw("ce f8 6e f4")
    pair(0, 8)
    c.mov_er(4, 0x7ff0)
    c.label("source_length")
    c.mov(2, 8)
    c.jump("probe_length")
    c.label("staged_length")
    c.raw("ce f8 6e f4")
    get_word(18)
    c.raw("82 e0")
    pair(4, 0)
    get(23, 2)
    c.mov(3, 0)
    c.raw("26 f4")
    get(31, 2)
    c.mov(3, 0)
    c.raw("26 f0")
    c.mov(2, 0)
    c.label("probe_length")
    c.call(SOURCE_LENGTH_ADDRESS)
    register(3, 0)
    c.raw("2e f4")
    register(7, 3)
    c.raw("8e f2")
    return tuple((part.address - 0x80000, part.build()) for part in chunks)
