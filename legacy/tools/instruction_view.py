"""On-device nX-U8 instruction list and detail view.

ER2 is the absolute S1 PC. VIEW also takes ER0=viewport top and returns
ER2=normalized top; entries return ER0=complete length or -1.
XR4 and R8..R15 are preserved.
"""

from instruction_table import ENTRIES, SUB_IMM, RECORD_SEGMENT, NAME_ADDRESSES
from u8_emit import Code
from instruction_text import emit_text
from small_font import SMALL_TEXT_ADDRESS

from flash_layout import VIEW_ADDRESS, DETAIL_ADDRESS, INSTRUCTION_RECORDS_ADDRESS
from instruction_codec import SOURCE_LENGTH_ADDRESS
from ui_text import TextPool


class _View(Code):
    def __init__(self):
        super().__init__(VIEW_ADDRESS)
        self.refs = []
        self.seq = 0
        self.pool = TextPool()

    def ref(self, reg, label):
        self.refs.append((len(self.data), label, False))
        self.mov(reg, 0)
        self.mov(reg + 1, 0)

    def build(self):
        data = bytearray(super().build())
        for pos, label, word in self.refs:
            addr = self.labels[label] & 0xffff
            if word:
                data[pos:pos + 2] = addr.to_bytes(2, "little")
            else:
                data[pos], data[pos + 2] = addr & 255, addr >> 8
        return bytes(data)

    def pair(self, dst, src):
        self.db((src << 4) | 5, 0xf0 | dst)

    def copy(self, dst, src):
        self.db(src << 4, 0x80 | dst)

    def add_er(self, reg, value):
        while value > 63:
            self.db(0xa0, 0xe0 | reg)
            value -= 32
        while value < -64:
            self.db(0xe0, 0xe0 | reg)
            value += 32
        self.db(0x80 | (value & 0x7f), 0xe0 | reg)

    def slot(self, reg, offset, store=False):
        self.pair(2, 14)
        self.add_er(2, offset)
        self.db(0x20 | int(store), 0x90 | reg)

    def ram(self, reg, ptr, segment=None, store=False):
        if segment is not None:
            self.db(segment, 0xe3)
        self.db(ptr | int(store), 0x90 | reg)

    def goto_if(self, condition, target):
        self.seq += 1
        skip = f"skip_{self.seq}"
        self.branch({"eq": "ne", "ne": "eq", "lt": "ge", "ge": "lt"}[condition], skip)
        self.jump(target)
        self.label(skip)

    def flash(self, offset, reg):
        self.pair(2, 8)
        if offset:
            self.add_er(2, offset)
        self.ram(reg, 0x20, segment=8)

    def char(self, value):
        if isinstance(value, str):
            self.mov(0, ord(value))
        else:
            self.copy(0, value)
        self.ram(0, 0xa0, store=True)
        self.add_er(10, 1)

    def text(self, value):
        if len(value) > 4:
            self.pair(2, 10)
            self.pool.copy(self, value, len(value) + 1)
            self.add_er(10, len(value))
        else:
            for char in value:
                self.char(char)

    def line(self, y, x=0, small=False):
        self.mov(0, 0)
        self.char(0)
        self.pair(2, 14)
        self.mov(0, x)
        if y is None:
            self.slot(1, 74)
            self.pair(2, 14)
        else:
            self.mov(1, y)
        self.call(SMALL_TEXT_ADDRESS if small else 0x041da)




def _build():
    c = _View()
    c.jump("view")
    c.jump("detail")
    c.label("view")
    c.raw("ce f8 6e f4 7e f8 5e fc 5e fe")
    c.mov(6, 1)
    c.jump("entry")
    c.label("detail")
    c.raw("ce f8 6e f4 7e f8 5e fc 5e fe")
    c.mov(6, 2)
    c.jump("entry")
    c.label("entry")
    c.pair(12, 0)
    c.pair(8, 2)
    c.raw("e0 e1 e0 e1 e0 e1 1a ae")  # 96-byte frame; ER14=SP.
    c.slot(8, 40, True)
    c.slot(9, 41, True)
    c.slot(8, 64, True)
    c.slot(9, 65, True)
    c.slot(12, 66, True)
    c.slot(13, 67, True)
    c.slot(6, 69, True)
    c.call("probe")
    c.db(0xff, 0x71)
    c.goto_if("eq", "entry_invalid")
    c.slot(0, 68, True)
    c.slot(0, 69)
    c.db(0, 0x70)
    c.goto_if("eq", "result")
    c.db(2, 0x70)
    c.goto_if("eq", "detail_draw")
    c.call("normalize")
    c.call("draw_list")
    c.jump("result")
    c.label("detail_draw")
    c.call("draw_detail")
    c.label("result")
    c.slot(8, 64)
    c.slot(9, 65)
    c.slot(8, 40, True)
    c.slot(9, 41, True)
    c.slot(0, 68)
    c.slot(0, 42, True)
    c.mov(1, 0)
    c.slot(6, 69)
    c.db(1, 0x76)
    c.branch("ne", "return_pc")
    c.slot(6, 66)
    c.slot(7, 67)
    c.pair(2, 6)
    c.jump("exit")
    c.label("return_pc")
    c.pair(2, 8)
    c.jump("exit")
    c.label("entry_invalid")
    c.slot(8, 64)
    c.slot(9, 65)
    c.pair(2, 8)
    c.label("exit")
    c.raw("20 e1 20 e1 20 e1 1e fe 1e fc 3e f8 2e f4 8e f2")

    c.label("probe")
    c.raw("ce f8")
    c.slot(8, 40)
    c.slot(9, 41)
    c.copy(0, 8)
    c.db(1, 0x20)
    c.goto_if("ne", "probe_invalid")
    c.pair(0, 8)
    c.mov_er(2, 0x4000)
    c.raw("27 f0")
    c.goto_if("lt", "probe_invalid")
    c.pair(0, 8)
    c.mov(2, 8)
    c.mov_er(4, 0x5ff0)
    c.call(SOURCE_LENGTH_ADDRESS)
    c.db(0xff, 0x71)
    c.goto_if("eq", "probe_invalid")
    c.copy(6, 2)
    c.copy(7, 3)
    c.slot(0, 42, True)
    c.slot(6, 78, True)
    c.slot(7, 79, True)
    c.mov(7, 0)
    c.raw("66 f8")
    c.flash(0, 4)
    c.flash(1, 5)
    c.slot(8, 40)
    c.slot(9, 41)
    c.slot(0, 42)
    c.mov(1, 0)
    c.raw("8e f2")
    c.label("probe_invalid")
    c.mov(0, 0xff)
    c.slot(0, 42, True)
    c.mov_er(0, 0xffff)
    c.raw("8e f2")

    c.label("decode")
    c.raw("ce f8")
    c.mov_er(0, NAME_ADDRESSES["DW"] & 0xffff)
    c.slot(0, 44, True)
    c.slot(1, 45, True)
    c.mov(0, 0xff)
    c.slot(0, 43, True)
    c.slot(0, 42)
    c.db(8, 0x70)
    c.goto_if("ne", "scan")
    c.mov_er(0, NAME_ADDRESSES["SUB R,#"] & 0xffff)
    c.slot(0, 44, True)
    c.slot(1, 45, True)
    c.mov(0, SUB_IMM)
    c.slot(0, 43, True)
    c.jump("decoded")
    c.label("scan")
    c.copy(10, 4)
    c.copy(11, 5)
    c.mov_er(6, INSTRUCTION_RECORDS_ADDRESS & 0xffff)
    c.mov(9, len(ENTRIES))
    c.label("record")
    c.pair(2, 6)
    c.add_er(2, 1)
    c.ram(0, 0x20, segment=RECORD_SEGMENT)
    c.db(1, 0x20)
    c.branch("eq", "next_record")
    c.add_er(2, 1)
    for reg in (0, 1):
        c.ram(reg, 0x20, segment=RECORD_SEGMENT)
        c.add_er(2, 1)
    c.add_er(2, 10)
    for reg in (4, 5):
        c.ram(reg, 0x20, segment=RECORD_SEGMENT)
        c.add_er(2, 1)
    c.copy(2, 10)
    c.db(0x42, 0x82, 0x07, 0x82)  # R2 = opcode low & mask low
    c.branch("ne", "next_record")
    c.copy(3, 11)
    c.db(0x52, 0x83, 0x17, 0x83)  # R3 = opcode high & mask high; compare record high
    c.branch("ne", "next_record")
    c.pair(2, 6)
    c.add_er(2, 12)
    c.ram(0, 0x20, segment=RECORD_SEGMENT)
    c.slot(0, 44, True)
    c.pair(2, 6)
    c.add_er(2, 13)
    c.ram(0, 0x20, segment=RECORD_SEGMENT)
    c.slot(0, 45, True)
    c.pair(2, 6)
    c.ram(0, 0x20, segment=RECORD_SEGMENT)
    c.slot(0, 43, True)
    c.jump("decoded")
    c.label("next_record")
    c.add_er(6, 16)
    c.db(0xff, 0x19, 0, 0x79)
    c.goto_if("ne", "record")
    c.label("decoded")
    c.raw("8e f2")

    c.label("normalize")
    c.raw("ce f8")
    c.slot(8, 66)
    c.slot(9, 67)
    c.copy(0, 8)
    c.db(1, 0x20)
    c.goto_if("ne", "top_reset")
    c.pair(0, 8)
    c.mov_er(2, 0x4000)
    c.raw("27 f0")
    c.goto_if("lt", "top_reset")
    c.mov_er(2, 0x5ff0)
    c.raw("27 f0")
    c.goto_if("ge", "top_reset")
    c.label("top_scan")
    c.slot(8, 66)
    c.slot(9, 67)
    c.slot(8, 40, True)
    c.slot(9, 41, True)
    c.mov(0, 0)
    c.slot(0, 71, True)
    c.label("top_instruction")
    c.slot(8, 40)
    c.slot(9, 41)
    c.slot(0, 64)
    c.slot(1, 65)
    c.raw("07 f8")
    c.goto_if("eq", "top_done")
    c.goto_if("ge", "top_reset")
    c.call("probe")
    c.db(0xff, 0x71)
    c.goto_if("eq", "top_reset")
    c.slot(0, 71)
    c.db(0, 0x70)
    c.branch("ne", "top_advance")
    c.slot(0, 42)
    c.slot(0, 70, True)
    c.label("top_advance")
    c.slot(8, 40)
    c.slot(9, 41)
    c.slot(0, 42)
    c.mov(1, 0)
    c.raw("06 f8")
    c.slot(8, 40, True)
    c.slot(9, 41, True)
    c.slot(0, 71)
    c.db(1, 0x10)
    c.slot(0, 71, True)
    c.db(3, 0x70)
    c.goto_if("lt", "top_instruction")
    c.slot(8, 66)
    c.slot(9, 67)
    c.slot(0, 70)
    c.mov(1, 0)
    c.raw("06 f8")
    c.slot(8, 66, True)
    c.slot(9, 67, True)
    c.jump("top_scan")
    c.label("top_reset")
    c.slot(8, 64)
    c.slot(9, 65)
    c.slot(8, 66, True)
    c.slot(9, 67, True)
    c.label("top_done")
    c.raw("8e f2")

    c.label("draw_begin")
    c.raw("ce f8")
    c.db(0x10, 0x90, 0xa0, 0x80)
    c.slot(0, 47, True)
    c.db(0x10, 0x90, 0xa2, 0x80)
    c.slot(0, 48, True)
    c.mov(0, 1)
    c.db(0x11, 0x90, 0xa2, 0x80)
    c.call(0x0409a)
    c.raw("8e f2")

    c.label("draw_end")
    c.raw("ce f8")
    c.call(0x043be)
    c.slot(0, 48)
    c.db(0x11, 0x90, 0xa2, 0x80)
    c.slot(0, 47)
    c.db(0x11, 0x90, 0xa0, 0x80)
    c.raw("8e f2")

    c.label("draw_list")
    c.raw("ce f8")
    c.call("draw_begin")
    c.pair(10, 14)
    c.text("DISAS MODE  HEX MODE")
    c.line(1, small=True)
    c.mov_er(8, 0x80ec)
    c.mov(6, 5)
    c.call("reverse_rows")
    c.slot(8, 66)
    c.slot(9, 67)
    c.slot(8, 40, True)
    c.slot(9, 41, True)
    c.mov(0, 7)
    c.slot(0, 74, True)
    c.label("list_row")
    c.call("probe")
    c.db(0xff, 0x71)
    c.goto_if("eq", "list_footer")
    c.call("decode")
    c.slot(8, 40)
    c.slot(9, 41)
    c.slot(0, 64)
    c.slot(1, 65)
    c.raw("07 f8")
    c.branch("ne", "row_not_selected")
    c.mov(0, 1)
    c.jump("row_selection")
    c.label("row_not_selected")
    c.mov(0, 0)
    c.label("row_selection")
    c.slot(0, 72, True)
    c.pair(10, 14)
    c.copy(0, 9)
    c.call("hexbyte")
    c.copy(0, 8)
    c.call("hexbyte")
    c.text(" ")
    c.call("bytes")
    c.text(" ")
    c.line(None, small=True)
    c.slot(0, 42)
    c.db(0x1a, 0x90, 6, 0x10, 0x2a, 0x90)
    c.slot(0, 75, True)  # Mnemonic starts after address and machine bytes.
    c.db(0x2c, 0x90)
    c.mov(1, 24)
    c.db(0x08, 0x81)
    c.slot(1, 77, True)
    c.call("text_begin")
    c.call("operand_text")
    c.mov(0, 0)
    c.char(0)
    c.slot(0, 77)
    c.mov(1, 0)
    c.pair(8, 14)
    c.raw("06 f8")
    c.ram(0, 0x80)
    c.db(0, 0x70)
    c.branch("eq", "row_text")
    c.mov(0, 0)
    c.ram(0, 0x80, store=True)
    c.add_er(8, -1)
    c.mov(0, ord("+"))
    c.ram(0, 0x80, store=True)
    c.label("row_text")
    c.slot(0, 75)
    c.slot(1, 74)
    c.pair(2, 14)
    c.call(SMALL_TEXT_ADDRESS)
    c.slot(0, 72)
    c.db(0, 0x70)
    c.branch("eq", "row_next")
    c.slot(0, 74)
    c.copy(8, 0)
    c.mov(1, 12)
    c.raw("14 f8")  # ER8 = y * framebuffer stride.
    c.mov_er(0, 0x80e0)
    c.raw("06 f8")
    c.slot(0, 75)
    c.db(0x3c, 0x90)
    c.mov(1, 0)
    c.raw("06 f8")
    c.copy(6, 0)
    c.mov(0, 12)
    c.db(0x68, 0x80)
    c.copy(6, 0)
    c.call("reverse_rows")
    c.label("row_next")
    c.slot(8, 40)
    c.slot(9, 41)
    c.slot(0, 42)
    c.mov(1, 0)
    c.raw("06 f8")
    c.slot(8, 40, True)
    c.slot(9, 41, True)
    c.slot(0, 74)
    c.db(6, 0x10)
    c.slot(0, 74, True)
    c.db(25, 0x70)
    c.goto_if("lt", "list_row")
    c.label("list_footer")
    c.mov(0, 7)
    c.db(0x11, 0x90, 0xa0, 0x80)
    c.call("address_text")
    c.line(25)
    c.pair(10, 14)
    c.text("P")
    c.line(25, 90)
    c.call("draw_end")
    c.raw("8e f2")

    c.label("draw_detail")
    c.raw("ce f8")
    c.call("draw_begin")
    c.mov(0, 7)
    c.db(0x11, 0x90, 0xa0, 0x80)
    c.call("address_text")
    c.line(1)
    c.pair(10, 14)
    c.text("P")
    c.line(1, 90)
    c.slot(8, 64)
    c.slot(9, 65)
    c.slot(8, 40, True)
    c.slot(9, 41, True)
    c.call("probe")
    c.call("decode")
    c.pair(10, 14)
    c.call("bytes")
    c.line(9)
    c.call("text_begin")
    c.call("operand_text")
    c.mov(0, 0)
    c.char(0)
    c.slot(0, 16)
    c.slot(0, 80, True)
    c.mov(0, 0)
    c.slot(0, 16, True)
    c.pair(2, 14)
    c.mov(0, 0)
    c.mov(1, 17)
    c.call(0x041da)
    c.slot(0, 80)
    c.slot(0, 16, True)
    c.pair(2, 14)
    c.add_er(2, 16)
    c.mov(0, 0)
    c.mov(1, 25)
    c.call(0x041da)
    c.call("draw_end")
    c.raw("8e f2")

    c.label("address_text")
    c.raw("ce f8")
    c.slot(8, 64)
    c.slot(9, 65)
    c.pair(10, 14)
    c.text("8:")
    c.copy(0, 9)
    c.call("hexbyte")
    c.copy(0, 8)
    c.call("hexbyte")
    c.raw("8e f2")

    c.label("bytes")
    c.raw("ce f8")
    c.slot(8, 40)
    c.slot(9, 41)
    c.mov(6, 0)
    c.label("byte")
    c.pair(2, 8)
    c.copy(0, 6)
    c.mov(1, 0)
    c.raw("06 f2")
    c.ram(0, 0x20, segment=8)
    c.call("hexbyte")
    c.db(1, 0x16)
    c.slot(0, 42)
    c.db(0x07, 0x86)
    c.branch("lt", "byte")
    c.raw("8e f2")

    # All instruction prefixes occupy whole framebuffer bytes.
    c.label("reverse_rows")
    c.mov(7, 6)
    c.label("reverse_line")
    c.pair(2, 8)
    c.copy(4, 6)
    c.label("reverse_byte")
    c.ram(0, 0x20)
    c.db(0xff, 0x40)
    c.ram(0, 0x20, store=True)
    c.add_er(2, 1)
    c.db(0xff, 0x14)
    c.branch("ne", "reverse_byte")
    c.add_er(8, 12)
    c.db(0xff, 0x17)
    c.branch("ne", "reverse_line")
    c.raw("1f fe")

    c.label("text_begin")
    c.pair(10, 14)
    c.mov(6, 33)
    c.label("text_clear")
    c.mov(0, 0)
    c.char(0)
    c.db(0xff, 0x16)
    c.branch("ne", "text_clear")
    c.pair(10, 14)
    c.raw("1f fe")

    c.label("hexbyte")
    c.raw("ce f8")
    c.copy(7, 0)
    c.db(0x4c, 0x90)
    c.call("nibble")
    c.char(0)
    c.copy(0, 7)
    c.db(0x0f, 0x20)
    c.call("nibble")
    c.char(0)
    c.raw("8e f2")
    c.label("nibble")
    c.db(10, 0x70)
    c.branch("lt", "digit")
    c.db(55, 0x10, 0x1f, 0xfe)
    c.label("digit")
    c.db(48, 0x10, 0x1f, 0xfe)

    emit_text(c)
    c.pool.finish(c)

    return c


def view_code():
    """Return the physical viewer payload without duplicate instruction data."""
    return VIEW_ADDRESS - 0x80000, _build().build()
