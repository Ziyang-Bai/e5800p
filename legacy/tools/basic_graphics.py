"""BASIC framebuffer operations; only REFRESH transfers the canvas to LCD.

ER0=token index, ER2=six LE32 arguments, ER4=LE32 result. Returns native
status in ER0, preserving XR4/R8..R15 and the argument slots. Coordinates
are normalized int16 by the caller. Logical row zero is physical row one.
"""

from u8_emit import Code
from small_font import SMALL_TEXT_ADDRESS
from basic_native import STACK_LOW
from basic_memory import READ_RANGE_ADDRESS

GRAPHICS_ADDRESS = 0xfc530
GRAPHICS_STOP = 0xfd130
GRAPHICS_FRAME_SIZE = 80
# Saves16 + frame80 + snapshot384 + pixel4; interrupt headroom is separate.
GRAPHICS_STACK_SIZE = 484
GRAPHICS_STACK_MAX = GRAPHICS_STACK_SIZE + 32


def graphics_code():
    c = Code(GRAPHICS_ADDRESS)
    seq = 0

    def pair(dst, src):
        c.db(src << 4 | 5, 0xf0 | dst)

    def reg(dst, src, op=0):
        c.db(src << 4 | op, 0x80 | dst)

    def add(dst, value):
        c.db(value & 255, 0x10 | dst)

    def inc(dst, value):
        assert -64 <= value <= 63
        c.db(0x80 | (value & 127), 0xe0 | dst)

    def slot(dst, offset, store=False, word=False):
        # Direct ER14 displacement avoids changing a live ER2 argument.
        c.db(0xe8 | int(store), (0xa0 if word else 0x90) | dst)
        c.word(offset)

    def ram(dst, ptr, store=False):
        c.db(ptr << 4 | int(store), 0x90 | dst)

    def cmp(dst, value):
        c.db(value, 0x70 | dst)

    def branch(cond, label):
        if cond in ('ges', 'lts'):
            c.fixups.append((len(c.data), 'relative', label))
            c.db(0, 0xc4 if cond == 'ges' else 0xc5)
        else:
            c.branch(cond, label)

    def far_if(cond, label):
        nonlocal seq
        seq += 1
        skip = f'skip_{seq}'
        branch({'eq': 'ne', 'ne': 'eq', 'lt': 'ge', 'ge': 'lt',
                'ges': 'lts', 'lts': 'ges'}[cond], skip)
        c.jump(label)
        c.label(skip)

    def bounds(offset, limit, failure='argument'):
        slot(0, offset, word=True)
        cmp(1, 0)
        far_if('ne', failure)
        cmp(0, limit)
        far_if('ge', failure)

    def mode(offset):
        bounds(offset, 3)
        slot(0, 3, True)

    def pixel():
        reg(0, 8)
        reg(1, 9)
        reg(2, 12)
        c.call('pixel')

    # The scratch PUSH is checked separately, before the permanent frame.
    # Callers reserve at least the native interrupt margin before dispatch.
    c.raw('5e f0 1a a0')
    c.db((STACK_LOW + 16 + GRAPHICS_FRAME_SIZE + 96) & 255, 0x70)
    c.db((STACK_LOW + 16 + GRAPHICS_FRAME_SIZE + 96) >> 8, 0x51)
    branch('ge', 'stack_ok')
    c.raw('1e f0')
    c.mov_er(0, 6)
    c.raw('1f fe')
    c.label('stack_ok')
    c.raw('1e f0 ce f8 6e f4 7e f8 b0 e1 1a ae')
    slot(4, 0, True, True)
    slot(0, 2, True)
    pair(12, 2)
    for index, offset in enumerate((4, 6, 8, 10, 12, 14)):
        c.db(0xc8, 0xa0)
        c.word(index * 4)
        slot(0, offset, True, True)
    # Preserve the BLIT source bank; its low word is already at slot12.
    c.db(0xc8, 0x90)
    c.word(18)
    slot(0, 30, True)
    slot(0, 2)
    for token, label in ((16, 'cls'), (17, 'pset'), (12, 'point'),
                         (18, 'line'), (19, 'rect'), (20, 'blit'),
                         (21, 'text'), (22, 'refresh')):
        cmp(0, token)
        far_if('eq', label)
    c.jump('argument')

    c.label('cls')
    c.mov_er(8, 0x80ec)
    c.mov_er(10, 372)
    c.mov(0, 0)
    c.label('cls_byte')
    ram(0, 8, True)
    inc(8, 1)
    inc(10, -1)
    branch('ne', 'cls_byte')
    c.jump('success')

    c.label('refresh')
    c.call(0x043be)
    c.jump('success')

    c.label('pset')
    mode(8)
    c.jump('point_bounds')
    c.label('point')
    c.mov(0, 3)
    slot(0, 3, True)
    c.label('point_bounds')
    bounds(4, 96, 'success')
    bounds(6, 31, 'success')
    slot(0, 4)
    slot(1, 6)
    slot(2, 3)
    c.call('pixel')
    c.jump('value')

    c.label('line')
    c.label('rect')
    mode(12)
    for offset, limit in ((4, 96), (6, 31), (8, 96), (10, 31)):
        bounds(offset, limit)
    for dst, offset in ((8, 4), (9, 6), (10, 8), (11, 10), (12, 3)):
        slot(dst, offset)
    slot(0, 2)
    cmp(0, 19)
    far_if('eq', 'rectangle')

    # Bresenham: dx>=0, dy<=0, err=dx+dy. The signed comparisons
    # use the same doubled error for both axes, including the last point.
    c.mov_er(4, 0)
    reg(4, 10)
    c.mov_er(0, 0)
    reg(0, 8)
    c.raw('08 84 19 85')
    c.mov_er(2, 1)
    branch('ge', 'dx_ready')
    c.mov_er(4, 0)
    reg(4, 8)
    reg(0, 10)
    c.raw('08 84 19 85')
    c.mov_er(2, 0xffff)
    c.label('dx_ready')
    slot(2, 22, True, True)
    c.mov_er(6, 0)
    reg(6, 9)
    c.mov_er(0, 0)
    reg(0, 11)
    c.raw('08 86 19 87')
    c.mov_er(2, 1)
    branch('lt', 'dy_ready')
    c.mov_er(6, 0)
    reg(6, 11)
    reg(0, 9)
    c.raw('08 86 19 87')
    c.mov_er(2, 0xffff)
    c.label('dy_ready')
    slot(2, 24, True, True)
    pair(0, 4)
    c.raw('66 f0')
    slot(0, 26, True, True)
    c.label('line_pixel')
    pixel()
    reg(0, 8)
    reg(0, 10, 7)
    branch('ne', 'line_step')
    reg(0, 9)
    reg(0, 11, 7)
    far_if('eq', 'success')
    c.label('line_step')
    slot(0, 26, word=True)
    c.raw('06 f0')
    slot(0, 28, True, True)
    c.raw('67 f0')
    branch('lts', 'line_y')
    slot(0, 26, word=True)
    c.raw('66 f0')
    slot(0, 26, True, True)
    slot(0, 22)
    reg(8, 0, 1)
    c.label('line_y')
    slot(0, 28, word=True)
    c.raw('07 f4')
    branch('lts', 'line_pixel')
    slot(0, 26, word=True)
    c.raw('46 f0')
    slot(0, 26, True, True)
    slot(0, 24)
    reg(9, 0, 1)
    c.jump('line_pixel')

    c.label('rectangle')
    for lo, hi, label in ((8, 10, 'rect_x'), (9, 11, 'rect_y')):
        reg(lo, hi, 7)
        branch('lt', label)
        reg(0, lo)
        reg(lo, hi)
        reg(hi, 0)
        c.label(label)
    reg(13, 8)
    slot(9, 18, True)
    c.label('rect_horizontal')
    pixel()
    reg(9, 11, 7)
    branch('eq', 'rect_next_x')
    reg(9, 11)
    pixel()
    slot(9, 18)
    c.label('rect_next_x')
    reg(8, 10, 7)
    branch('eq', 'rect_sides')
    add(8, 1)
    c.jump('rect_horizontal')
    c.label('rect_sides')
    add(9, 1)
    reg(9, 11, 7)
    far_if('ge', 'success')
    reg(8, 13)
    pixel()
    reg(8, 10, 7)
    branch('eq', 'rect_sides')
    reg(8, 10)
    pixel()
    c.jump('rect_sides')

    c.label('blit')
    mode(14)
    for offset, limit in ((4, 96), (6, 31), (8, 97), (10, 33)):
        bounds(offset, limit)
    for offset in (8, 10):
        slot(0, offset)
        cmp(0, 0)
        far_if('eq', 'argument')
    slot(0, 8)
    add(0, 7)
    c.raw('3c 90')
    slot(2, 10)
    c.raw('24 f0')
    slot(0, 16, True, True)
    pair(4, 0)
    slot(0, 12, word=True)
    slot(2, 30)
    c.call(READ_RANGE_ADDRESS)
    cmp(0, 0)
    far_if('ne', 'argument')
    slot(8, 12, word=True)
    slot(10, 30)
    cmp(10, 0)
    branch('ne', 'blit_ready')
    c.mov_er(0, 0x8260)
    c.raw('07 f8')
    branch('ge', 'blit_ready')
    pair(0, 8)
    slot(2, 16, word=True)
    c.raw('26 f0')
    c.mov_er(2, 0x80ed)
    c.raw('27 f0')
    branch('lt', 'blit_ready')
    c.raw('1a a0')
    c.mov_er(2, STACK_LOW + 384 + 4 + 32)
    c.raw('27 f0')
    far_if('lt', 'memory')
    c.raw('80 e1 80 e1 80 e1 1a a4')
    slot(6, 16, word=True)
    c.label('snapshot')
    ram(0, 8)
    ram(0, 4, True)
    inc(8, 1)
    inc(4, 1)
    inc(6, -1)
    branch('ne', 'snapshot')
    c.raw('1a a8')
    c.label('blit_ready')
    c.mov(13, 0)
    c.label('blit_row')
    c.mov(12, 0)
    c.label('blit_column')
    reg(0, 12)
    c.db(7, 0x20)
    branch('ne', 'blit_bit')
    c.raw('0f 9a 80 9b')  # DSR R10; L R11,[ER8].
    inc(8, 1)
    branch('ne', 'blit_bit')
    add(10, 1)
    c.label('blit_bit')
    slot(0, 4)
    reg(0, 12, 1)
    cmp(0, 96)
    branch('ge', 'blit_next')
    slot(1, 6)
    reg(1, 13, 1)
    cmp(1, 31)
    branch('ge', 'blit_next')
    slot(2, 3)
    cmp(11, 128)
    branch('ge', 'blit_set')
    cmp(2, 0)
    branch('ne', 'blit_next')
    c.jump('blit_plot')
    c.label('blit_set')
    cmp(2, 0)
    branch('ne', 'blit_plot')
    c.mov(2, 1)
    c.label('blit_plot')
    c.call('pixel')
    c.label('blit_next')
    c.raw('1a 9b')
    add(12, 1)
    slot(0, 8)
    reg(12, 0, 7)
    branch('lt', 'blit_column')
    add(13, 1)
    slot(0, 10)
    reg(13, 0, 7)
    branch('lt', 'blit_row')
    c.jump('success')

    c.label('text')
    bounds(4, 96)
    bounds(10, 2)
    slot(0, 10)
    cmp(0, 0)
    branch('ne', 'text_regular_bounds')
    bounds(6, 27)
    slot(0, 4)
    c.db(3, 0x20)
    far_if('ne', 'argument')
    c.jump('text_copy')
    c.label('text_regular_bounds')
    bounds(6, 25)
    c.label('text_copy')
    slot(8, 8, word=True)
    pair(10, 14)
    inc(10, 32)
    slot(6, 12)
    cmp(6, 33)
    far_if('ge', 'argument')
    cmp(6, 0)
    branch('eq', 'text_nul')
    c.label('text_byte')
    ram(0, 8)
    ram(0, 10, True)
    inc(8, 1)
    inc(10, 1)
    add(6, -1)
    branch('ne', 'text_byte')
    c.label('text_nul')
    c.mov(0, 0)
    ram(0, 10, True)
    for index in range(3):
        c.db(0x10, 0x90)
        c.word(0x80a0 + index)
        slot(0, 66 + index, True)
    for index, value in enumerate((7, 0, 1)):
        c.mov(0, value)
        c.db(0x11, 0x90)
        c.word(0x80a0 + index)
    slot(0, 10)
    cmp(0, 0)
    branch('ne', 'text_rom')
    slot(0, 4)
    slot(1, 6)
    add(1, 1)
    pair(2, 14)
    inc(2, 32)
    c.call(SMALL_TEXT_ADDRESS)
    c.jump('text_restore')
    c.label('text_rom')
    slot(0, 4)
    slot(1, 6)
    add(1, 1)
    pair(2, 14)
    inc(2, 32)
    c.call(0x041da)
    # The ROM string routine stops before a partial six-pixel cell.
    # Stage that last glyph at x=0, restore its scratch pixels, then
    # merge only the visible high columns into the rightmost byte.
    reg(8, 0)
    c.mov(1, 0)
    pair(2, 14)
    inc(2, 32)
    c.raw('06 f2')
    ram(0, 2)
    cmp(0, 0)
    far_if('eq', 'text_restore')
    slot(0, 70, True)
    c.mov(0, 0)
    slot(0, 71, True)
    reg(0, 8)
    c.mov(2, 6)
    c.raw('24 f0')
    slot(2, 4)
    reg(0, 2, 1)
    cmp(0, 96)
    far_if('ge', 'text_restore')
    reg(12, 0)
    c.db(7, 0x2c)
    slot(0, 6)
    c.mov(2, 12)
    c.raw('24 f0')
    c.mov_er(8, 0x80ec)
    c.raw('06 f8')
    pair(10, 14)
    inc(10, 16)
    c.mov(13, 7)
    c.label('text_save_edge')
    ram(0, 8)
    ram(0, 10, True)
    inc(8, 12)
    inc(10, 1)
    add(13, -1)
    branch('ne', 'text_save_edge')
    c.mov(0, 0)
    slot(1, 6)
    add(1, 1)
    pair(2, 14)
    inc(2, 35)
    inc(2, 35)
    c.call(0x041da)
    inc(8, -60)
    inc(8, -24)
    pair(10, 14)
    inc(10, 16)
    c.mov(13, 7)
    c.label('text_merge_edge')
    ram(0, 8)
    ram(1, 10)
    ram(1, 8, True)
    reg(0, 12, 0x0c)
    c.mov(1, 255)
    reg(1, 12, 0x0c)
    c.db(255, 0x41)
    pair(2, 8)
    inc(2, 11)
    ram(3, 2)
    reg(3, 1, 2)
    reg(0, 3, 3)
    ram(0, 2, True)
    inc(8, 12)
    inc(10, 1)
    add(13, -1)
    branch('ne', 'text_merge_edge')
    c.label('text_restore')
    for index in range(3):
        slot(0, 66 + index)
        c.db(0x11, 0x90)
        c.word(0x80a0 + index)
    c.jump('success')

    c.label('argument')
    c.mov_er(0, 4)
    c.jump('exit')
    c.label('memory')
    c.mov_er(0, 6)
    c.jump('exit')
    c.label('success')
    c.mov(0, 0)
    c.label('value')
    c.mov(1, 0)
    slot(2, 0, word=True)
    c.raw('23 90')
    inc(2, 2)
    c.mov_er(0, 0)
    c.raw('23 90')
    c.label('exit')
    pair(2, 14)
    inc(2, 40)
    inc(2, 40)
    c.raw('2a a1 3e f8 2e f4 8e f2')

    # R0=x,R1=logical y,R2=0 clear/1 set/2 xor/3 query.
    # Leaf preserves XR4 and R8..15; callers already checked coordinates.
    c.label('pixel')
    c.raw('6e f4')
    reg(6, 2)
    reg(2, 0)
    c.db(7, 0x22)
    c.mov(3, 128)
    reg(3, 2, 0x0c)
    reg(4, 1)
    c.mov(1, 0)
    c.raw('3c 90')
    c.mov(2, 12)
    c.raw('24 f4 06 f4')
    c.mov_er(0, 0x80ec)
    c.raw('06 f4')
    ram(0, 4)
    cmp(6, 3)
    branch('eq', 'pixel_query')
    cmp(6, 0)
    branch('eq', 'pixel_clear')
    cmp(6, 1)
    branch('eq', 'pixel_set')
    reg(0, 3, 4)
    c.jump('pixel_write')
    c.label('pixel_set')
    reg(0, 3, 3)
    c.jump('pixel_write')
    c.label('pixel_clear')
    c.db(255, 0x43)
    reg(0, 3, 2)
    c.label('pixel_write')
    ram(0, 4, True)
    c.mov(0, 0)
    c.jump('pixel_done')
    c.label('pixel_query')
    reg(0, 3, 2)
    branch('eq', 'pixel_done')
    c.mov(0, 1)
    c.label('pixel_done')
    c.raw('2e f4 1f fe')

    code = c.build()
    if GRAPHICS_ADDRESS + len(code) > GRAPHICS_STOP:
        raise ValueError('BASIC graphics exceeds its allocation')
    return GRAPHICS_ADDRESS - 0x80000, code
