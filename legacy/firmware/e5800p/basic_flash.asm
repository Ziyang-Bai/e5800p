; basic_flash
; Stream bytes to NOR Flash; erase commands and storage ownership belong to callers.
; CPU 0xF6E68, physical 0x76E68, 764 bytes
rom_flash_program EQU 0x04E86

basic_flash:
JMP replace
JMP write
replace:
PUSH LR
PUSH ER2
PUSH XR4
PUSH QR8
ADD SP,#0xE0
MOV ER14,SP
ST ER0,0x0000[ER14]
ST ER2,0x0002[ER14]
ST ER4,0x0004[ER14]
ST ER6,0x0006[ER14]
ST R8,0x0008[ER14]
MOV ER0,SP
MOV R2,#0x92
MOV R3,#0x83
CMP ER0,ER2
BGE near_2
JMP failed
near_2:
L ER2,0x0002[ER14]
MOV ER2,ER2
BNE near_4
JMP near_48
near_4:
CMP R8,#0x08
BGE near_6
JMP failed
near_6:
CMP R8,#0x10
BLT near_8
JMP failed
near_8:
L ER0,0x0000[ER14]
ADD ER2,#0x7F
ADD ER0,ER2
MOV R2,R8
ADDC R2,#0x00
CMP R2,#0x10
BLT near_10
JMP failed
near_10:
MOV R0,#0x00
ST R0,0x0009[ER14]
MOV R2,#0x00
CALL reader
CMP R1,#0x00
BEQ near_13
JMP failed
near_13:
L ER8,0x0000[ER14]
L ER10,0x0002[ER14]
L R12,0x0008[ER14]
preflight:
MOV R2,#0x01
CALL reader
CMP R1,#0x00
BEQ near_16
JMP failed
near_16:
MOV R4,R0
L R2,R12:[ER8]
CMP R2,R4
BEQ same
MOV R0,#0x01
ST R0,0x0009[ER14]
same:
AND R2,R4
CMP R2,R4
BEQ near_19
JMP failed
near_19:
ADD ER8,#0x01
BNE preflight_next
ADD R12,#0x01
preflight_next:
ADD ER10,#0x7F
MOV ER10,ER10
BEQ near_22
JMP preflight
near_22:
CALL reader_end
MOV ER0,ER0
BEQ near_25
JMP failed
near_25:
L R0,0x0009[ER14]
CMP R0,#0x00
BNE near_27
JMP near_48
near_27:
MOV R2,#0x00
CALL reader
CMP R1,#0x00
BEQ near_30
JMP failed
near_30:
chunk:
L ER8,0x0000[ER14]
L ER10,0x0002[ER14]
MOV ER12,ER14
ADD ER12,#0x10
MOV ER6,#0x00
fill:
MOV R2,#0x01
CALL reader
CMP R1,#0x00
BEQ near_33
JMP failed
near_33:
ST R0,[ER12]
ADD ER12,#0x01
ADD ER6,#0x01
ADD ER8,#0x01
ADD ER10,#0x7F
MOV ER10,ER10
BEQ program_chunk
MOV ER8,ER8
BEQ program_chunk
CMP R6,#0x10
BLT fill
program_chunk:
L ER0,0x0000[ER14]
L R2,0x0008[ER14]
MOV R3,#0x00
MOV ER4,ER14
ADD ER4,#0x10
CALL program
MOV ER0,ER0
BEQ near_39
JMP failed
near_39:
ST ER10,0x0002[ER14]
L ER10,0x0000[ER14]
ST ER8,0x0000[ER14]
L R12,0x0008[ER14]
MOV ER8,ER8
BNE verify
MOV R0,R12
ADD R0,#0x01
ST R0,0x0008[ER14]
verify:
L R0,[ER4]
L R2,R12:[ER10]
CMP R0,R2
BEQ near_42
JMP failed
near_42:
ADD ER4,#0x01
ADD ER10,#0x01
ADD ER6,#0x7F
MOV ER6,ER6
BNE verify
L ER0,0x0002[ER14]
MOV ER0,ER0
BEQ near_45
JMP near_30
near_45:
CALL reader_end
MOV ER0,ER0
BEQ near_48
JMP failed
near_48:
success:
MOV ER0,#0x00
JMP exit
failed:
MOV R0,#0xFF
MOV R1,#0xFF
exit:
ADD SP,#0x20
POP QR8
POP XR4
POP ER2
POP PC
reader:
PUSH LR
PUSH ER8
L ER0,0x0006[ER14]
L ER8,0x0004[ER14]
BL ER8
POP ER8
POP PC
reader_end:
PUSH LR
MOV R2,#0x01
CALL reader
CMP R1,#0x01
BNE reader_long
MOV ER0,#0x00
POP PC
reader_long:
MOV R0,#0xFF
MOV R1,#0xFF
POP PC
program:
PUSH LR
PUSH XR4
PUSH QR8
PUSH ER6
MOV R8,#0x00
PUSH R8
PUSH ER4
CALL rom_flash_program
ADD SP,#0x06
POP QR8
POP XR4
POP PC
write:
PUSH LR
PUSH ER2
PUSH XR4
PUSH QR8
MOV ER8,ER2
MOV ER0,SP
MOV R2,#0x12
MOV R3,#0x84
CMP ER0,ER2
BGE near_53
JMP write_stack
near_53:
ADD SP,#0xE8
MOV ER14,SP
ST ER4,0x0010[ER14]
L ER0,0x000A[ER8]
MOV ER0,ER0
BEQ near_55
JMP write_arg
near_55:
L ER0,0x0002[ER8]
MOV ER2,#0x10
CMP ER0,ER2
BLT near_57
JMP write_arg
near_57:
ST ER0,0x000E[ER14]
L ER0,[ER8]
ST ER0,0x000C[ER14]
L ER2,0x0006[ER8]
MOV R0,#0x00
MOV R1,#0x01
CMP ER2,ER0
BLT near_59
JMP write_arg
near_59:
ST ER2,0x0002[ER14]
L ER0,0x0004[ER8]
ST ER0,0x0000[ER14]
L ER4,0x0008[ER8]
ST ER4,0x0004[ER14]
CALL 0xF:0xB53C
MOV ER0,ER0
BEQ near_61
JMP write_arg
near_61:
L ER0,0x000C[ER14]
L ER2,0x0004[ER14]
MOV R4,#0x02
MOV R5,#0x71
MOV ER6,ER14
L ER8,0x000E[ER14]
CALL basic_flash
MOV ER0,ER0
BEQ near_63
JMP write_failed
near_63:
L ER4,0x0010[ER14]
MOV ER0,#0x00
ST R0,[ER4]
ADD ER4,#0x01
ST R0,[ER4]
ADD ER4,#0x01
ST R0,[ER4]
ADD ER4,#0x01
ST R0,[ER4]
JMP write_exit
write_arg:
MOV ER0,#0x04
JMP write_exit
write_failed:
MOV R0,#0x00
MOV R1,#0x01
write_exit:
ADD SP,#0x18
POP QR8
POP XR4
POP ER2
POP PC
write_stack:
MOV ER0,#0x06
POP QR8
POP XR4
POP ER2
POP PC
ram_reader:
PUSH XR4
MOV ER4,ER0
CMP R2,#0x00
BNE ram_next
L ER0,[ER4]
ST ER0,0x0006[ER4]
L ER0,0x0002[ER4]
ST ER0,0x0008[ER4]
L ER0,0x0004[ER4]
ST ER0,0x000A[ER4]
MOV ER0,#0x00
JMP ram_out
ram_next:
L ER2,0x000A[ER4]
MOV ER2,ER2
BEQ ram_end
L ER6,0x0006[ER4]
L R3,0x0008[ER4]
L R0,R3:[ER6]
ADD ER6,#0x01
ST ER6,0x0006[ER4]
BNE ram_count
L ER2,0x0008[ER4]
ADD ER2,#0x01
ST ER2,0x0008[ER4]
ram_count:
L ER2,0x000A[ER4]
ADD ER2,#0x7F
ST ER2,0x000A[ER4]
MOV R1,#0x00
JMP ram_out
ram_end:
MOV R0,#0x00
MOV R1,#0x01
ram_out:
POP XR4
RET
